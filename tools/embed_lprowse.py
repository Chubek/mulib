#!/usr/bin/env python3
"""Regenerate the embedded lprowse Lua source, or verify it with --check."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def generated():
    source = (ROOT / 'library/lprowse/lprowse.lua').read_text()
    lines = ['/* Generated by tools/embed_lprowse.py from library/lprowse/lprowse.lua. */',
             '#ifndef INCLUDE_MULIB_LPROWSE_H', '#define INCLUDE_MULIB_LPROWSE_H',
             'static const char *const mulib_lprowse_source_[] = {']
    lines += ['  ' + json.dumps(line, ensure_ascii=True) + ',' for line in source.splitlines(keepends=True)]
    lines += ['};', '#endif', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'include/include-mulib-lprowse.h'
    text = generated()
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit('embedded lprowse is stale; run tools/embed_lprowse.py')
    else:
        path.write_text(text)
