#!/usr/bin/env python3
"""Generate MuLIB's REST operation catalog from the bundled OpenAI publication.

Uses only Python's standard library; never modifies the source specification.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render():
    source = (ROOT / 'standards/openai-openapi/openapi.json').read_bytes()
    spec = json.loads(source)
    rows = []
    ids = set()
    for path, item in spec['paths'].items():
        for method, operation in item.items():
            if method not in ('get', 'post', 'put', 'patch', 'delete', 'head', 'options'):
                continue
            name = operation['operationId']
            if name in ids:
                raise ValueError('duplicate operationId: ' + name)
            ids.add(name)
            body = operation.get('requestBody', {})
            media = '|'.join(body.get('content', {}))
            rows.append('  { %s, %s, %s, %s, %d },' % (
                json.dumps(name), json.dumps(method.upper()), json.dumps(path),
                json.dumps(media), bool(body.get('required'))))
    license_text = (ROOT / 'standards/openai-openapi/LICENSE').read_text().strip()
    return ('/* Generated by tools/generate_openai.py; do not edit.\n'
            ' * OpenAI API ' + spec['info']['version'] + '; source SHA256:\n'
            ' * ' + hashlib.sha256(source).hexdigest() + '\n *\n'
            + '\n'.join(' * ' + line if line else ' *' for line in license_text.splitlines())
            + '\n */\n'
            + '\n'.join(rows) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'include/detail/mulib-openai-operations.inc'
    text = render()
    if args.check:
        if not path.exists() or path.read_text() != text:
            parser.exit(1, 'OpenAI catalog is stale: run python3 tools/generate_openai.py\n')
    else:
        path.write_text(text)
    print('OpenAI operation catalog is current')


if __name__ == '__main__':
    main()
