#!/usr/bin/env python3
"""Embed the original lcharts/lpaleo libraries; no runtime filesystem dependency."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for module, source in [('chart', 'lcharts/lcharts.lua'), ('paleography', 'lpaleo/lpaleo.lua')]:
        path = ROOT / 'include' / f'mulib-{module}-data.inc'
        text = (ROOT / 'library' / source).read_text()
        output = f'/* Generated by tools/embed_notation.py from library/{source}. */\n'
        output += f'static const char *const mulib_{module}_source_[] = {{\n'
        output += ''.join('    ' + json.dumps(text[i:i+1000]) + ',\n' for i in range(0, len(text), 1000))
        output += '};\n'
        if args.check:
            if not path.exists() or path.read_text() != output:
                parser.exit(1, f'stale {module} library; run tools/embed_notation.py\n')
        else:
            path.write_text(output)
    print('Embedded lcharts/lpaleo modules are current')


if __name__ == '__main__':
    main()
