#!/usr/bin/env python3
"""Embed lmuw3 in the Mune engine; --check verifies the checked-in source."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def generated():
    source = (ROOT / 'library/lmuw3/lmuw3.lua').read_text()
    lines = ['/* Generated by tools/embed_lmuw3.py; edit library/lmuw3/lmuw3.lua. */',
             'static const char *const mulib_muw3_lua_source_[] = {']
    lines += ['  ' + json.dumps(line, ensure_ascii=True) + ','
              for line in source.splitlines(keepends=True)]
    return '\n'.join(lines + ['};', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'include/detail/mulib-lmuw3.inc'
    text = generated()
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit('embedded lmuw3 is stale; run tools/embed_lmuw3.py')
    else:
        path.write_text(text)
