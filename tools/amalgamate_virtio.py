#!/usr/bin/env python3
"""Reproduce standalone Virtio implementation headers from canonical C sources."""
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def amalgamate(side):
    directory = ROOT / 'library' / ('virtio-' + side)
    header = ROOT / 'include' / ('mulib-virtio-' + side + '.h')
    internal = (directory / 'internal.h').read_text()
    declarations = internal.split('#define MULIB_VIRTIO_INTERNAL\n', 1)[1].rsplit('#endif', 1)[0]
    chunks = ['/* Generated by tools/amalgamate_virtio.py from library/virtio-' + side + '. */\n']
    chunks.append('#define MULIB_VIRTIO_INTERNAL static\n' + declarations)
    sources = [directory / ('virtio-' + side + '.c')]
    sources += sorted(p for p in directory.glob('*.c') if p.name not in ('protocol.c', 'virtio-' + side + '.c'))
    for source in sources:
        text = source.read_text().replace('#include "internal.h"\n', '')
        chunks.append('/* ' + source.name + ' */\n' + text)
    chunks.append('#undef MULIB_VIRTIO_INTERNAL\n')
    text = header.read_text()
    begin = '/* BEGIN GENERATED VIRTIO IMPLEMENTATION */\n'
    end = '/* END GENERATED VIRTIO IMPLEMENTATION */'
    before, rest = text.split(begin, 1)
    _, after = rest.split(end, 1)
    return header, before + begin + '\n'.join(chunks) + end + after


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for side in ('os', 'guest'):
        path, text = amalgamate(side)
        if path.read_text() != text:
            if args.check:
                stale.append(str(path.relative_to(ROOT)))
            else:
                path.write_text(text)
    if stale:
        print('Stale Virtio headers: ' + ', '.join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
