#!/usr/bin/env python3
"""Embed the reviewed ArchML processor profiles; --check detects stale data."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROFILES = [("amd64", "amd64.aml", "MPU"),
            ("aarch64", "arm64.aml", "MPU"),
            ("riscv64", "riscv64.aml", "MPU"),
            ("avr32", "avr32.aml", "MCU"),
            ("xtensa", "xtensa.am", "MCU"),
            ("amdgpu", "amdgpu.am", "GPU"),
            ("nvptx", "nvptx.am", "GPU")]


def render():
    lines = ["/* Generated by tools/embed_units.py; edit library/archml profiles. */"]
    for name, filename, _ in PROFILES:
        source = (ROOT / "library/archml" / filename).read_text()
        lines.append(f"static const char *const mulib_unit_{name}_source_[] = {{")
        # Individual literals stay below ISO C's 4095-character minimum limit.
        for i in range(0, len(source), 1024):
            lines.append("  " + json.dumps(source[i:i + 1024], ensure_ascii=True) + ",")
        lines.append("  NULL\n};")
    lines.append("static const mulib_unit_builtin_ mulib_unit_builtins_[] = {")
    for name, filename, family in PROFILES:
        lines.append(f'  {{"{name}", "{Path(filename).stem}", MULIB_UNIT_{family}, '
                     f'mulib_unit_{name}_source_}},')
    lines.append("};\n")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "include/mulib-unit-data.inc"
    source = render()
    if args.check:
        if not path.exists() or path.read_text() != source:
            raise SystemExit("stale unit profiles: run python3 tools/embed_units.py")
        print("Embedded unit profiles are current")
    else:
        path.write_text(source)


if __name__ == "__main__":
    main()
