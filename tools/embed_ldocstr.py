#!/usr/bin/env python3
"""Embed the default ldocstr modules, without runtime filesystem dependencies."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def generated():
    result = '/* Generated by tools/embed_ldocstr.py; edit the library/ldocstr Lua modules. */\n'
    for name, filename in [('core', 'ldocstr.lua'), ('style', 'ldstr-style.lua')]:
        source = (ROOT / 'library/ldocstr' / filename).read_text()
        result += f'static const char *const mulib_docstrings_{name}_source_[] = {{\n'
        for start in range(0, len(source), 1000):
            result += '    ' + json.dumps(source[start:start + 1000], ensure_ascii=True) + ',\n'
        result += '};\n'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'include/mulib-docstring-data.inc'
    content = generated()
    if args.check:
        if not path.exists() or path.read_text() != content:
            parser.exit(1, 'stale ldocstr modules; run tools/embed_ldocstr.py\n')
        print('ldocstr embedded modules are current')
    else:
        path.write_text(content)


if __name__ == '__main__':
    main()
