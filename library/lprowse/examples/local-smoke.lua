local p = require('lprowse')
p.go('data:text/html,<title>Prowse</title><h1>Hello</h1><input id="q"><button onclick="document.querySelector(\'h1\').textContent=\'Clicked\'">Go</button><a href="https://example.com/a">A</a>')
p.wait('h1')
assert(p.title() == 'Prowse')
assert(p.text('h1') == 'Hello')
p.type('#q', 'mu"lib')
assert(p.eval('document.querySelector("#q").value') == 'mu"lib')
p.click('button')
assert(p.text('h1') == 'Clicked')
assert(p.links()[1] == 'https://example.com/a')
assert(p.attr('h1', 'missing') == p.null)
assert(p.json(p.text('.absent', true)) == '[]')
assert(#p.screenshot() > 100)
print('Prowse live browser passed')
