#!/usr/bin/env python3
"""Generate editor assets from shared syntax/snippets. --check detects drift."""
import argparse
import json
import plistlib
import re
import shutil
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def json_text(value):
    return json.dumps(value, indent=2, ensure_ascii=False) + "\n"


def xml_text(element):
    ET.indent(element, space="  ")
    return ET.tostring(element, encoding="unicode", xml_declaration=True) + "\n"


def live_template(body):
    defaults = {}

    def placeholder(match):
        index = match[1] or match[3]
        if index == "0":
            # JetBrains has an end marker, but no editable default for it.
            return (match[2] or "") + "$END$"
        if match[2] is not None:
            defaults[index] = match[2]
        else:
            defaults.setdefault(index, "")
        return "$V" + index + "$"

    body = re.sub(r"\$\{(\d+):([^}]*)\}|\$(\d+)", placeholder, body)
    return body.replace("\\$", "$$"), defaults


def assets():
    grammar = json.loads((ROOT / "shared/mull.tmLanguage.json").read_text(encoding="utf-8"))
    snippets = json.loads((ROOT / "shared/snippets.json").read_text(encoding="utf-8"))
    generated = {}
    generated["vscode/syntaxes/mull.tmLanguage.json"] = json_text(grammar)
    plist = plistlib.dumps(grammar, sort_keys=False).decode("utf-8")
    generated["sublime/MuLL.tmLanguage"] = plist
    generated["jetbrains/MuLL.tmbundle/Syntaxes/MuLL.tmLanguage"] = plist
    generated["jetbrains/MuLL.tmbundle/info.plist"] = plistlib.dumps({
        "name": "MuLL", "uuid": "A50726C6-EE84-420B-B4CE-682E29F349AC",
        "description": "MuLL language syntax for MuDSL and MuLIB",
    }).decode("utf-8")
    generated["jetbrains/MuLL.tmbundle/Preferences/Comments.tmPreferences"] = (ROOT / "sublime/Comments.tmPreferences").read_text(encoding="utf-8")
    scopes = {"mull": "source.mull", "c": "source.c", "cpp": "source.c++", "d": "source.d"}
    by_language = {language: {} for language in scopes}
    templates = ET.Element("templateSet", group="Mu")
    for languages, entries in snippets.items():
        for language in languages.split(","):
            by_language[language].update(entries)
        for name, snippet in entries.items():
            key = languages.replace(",", "-") + "-" + snippet["prefix"]
            element = ET.Element("snippet")
            ET.SubElement(element, "content").text = snippet["body"]
            ET.SubElement(element, "tabTrigger").text = snippet["prefix"]
            ET.SubElement(element, "scope").text = ", ".join(scopes[lang] for lang in languages.split(","))
            ET.SubElement(element, "description").text = name
            generated["sublime/snippets/" + key + ".sublime-snippet"] = xml_text(element)
            value, defaults = live_template(snippet["body"])
            template = ET.SubElement(templates, "template", name=key, value=value, description=name,
                                     toReformat="false", toShortenFQNames="false")
            for index, default in defaults.items():
                ET.SubElement(template, "variable", name="V" + index, expression="",
                              defaultValue=json.dumps(default), alwaysStopAt="true")
            context = ET.SubElement(template, "context")
            ET.SubElement(context, "option", name="OTHER", value="true")
    generated["jetbrains/templates/Mu.xml"] = xml_text(templates)
    for language, entries in by_language.items():
        generated[f"vscode/snippets/{language}.json"] = json_text(entries)
        generated[f"vim/UltiSnips/{language}.snippets"] = "# Generated by addons/generate.py\n" + "\n".join(
            f'snippet {s["prefix"]} "{name}" b\n{s["body"]}\nendsnippet\n' for name, s in entries.items())
    return generated


def bundle_server(destination):
    destination.mkdir(parents=True, exist_ok=True)
    for name in ("server.py", "api.py"):
        shutil.copy2(ROOT / "lsp" / name, destination / name)
    inventory = ROOT.parent / "mull/stdlib/Mulib/Inventory.json"
    if inventory.is_file():
        shutil.copy2(inventory, destination / "Inventory.json")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--vscode", action="store_true", help="also stage the server and license for a VSIX")
    args = parser.parse_args()
    stale = []
    for relative, content in assets().items():
        path = ROOT / relative
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        print("Stale editor assets; run python3 addons/generate.py:\n" + "\n".join(stale), file=sys.stderr)
        return 1
    if args.vscode:
        bundle_server(ROOT / "vscode/server")
        license_path = ROOT.parent.parent / "LICENSE"
        if license_path.is_file():
            shutil.copy2(license_path, ROOT / "vscode/LICENSE")
    return 0


if __name__ == "__main__":
    sys.exit(main())
