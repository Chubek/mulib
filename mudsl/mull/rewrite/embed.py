#!/usr/bin/env python3
"""Embed the shipped MuLLIER rules for cwd-independent C++ and D runtimes."""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def outputs():
    sources = {kind: "\n".join(p.read_text() for p in sorted(HERE.glob("*." + ext)))
               for kind, ext in (("analysis", "a"), ("transforms", "t"))}
    cpp = "// Generated by mull/rewrite/embed.py.\n#pragma once\nnamespace mull::mullier {\n"
    d = "// Generated by mull/rewrite/embed.py.\nmodule mull.mullier.DefaultRules;\n"
    for name, source in sources.items():
        cpp += f'inline constexpr auto default_{name} = R"mullier({source})mullier";\n'
        d += f'enum default_{name} = {json.dumps(source)};\n'
    return {HERE.parent / "mullier/DefaultRules.hpp": cpp + "}\n",
            HERE.parent / "mullier/DefaultRules.d": d}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                parser.exit(1, f"{path}: run mull/rewrite/embed.py\n")
        else:
            path.write_text(text)


if __name__ == "__main__":
    main()
