#!/usr/bin/env python3
"""Typeset complete manuals as titled, linked, print-friendly reference chapters."""
import argparse
from pathlib import Path
import sys

from book_support import fragment, write_output, repository_file
from manual_support import ManualCatalogue, ordered_sources
from md2latex import escape_latex, inline

HERE = Path(__file__).resolve().parent


def generate(manual, output, check=False):
    manual, output = Path(manual), Path(output)
    sources = ordered_sources(manual)
    if not sources:
        raise ValueError(f"no Markdown manuals in {manual}")
    catalogue = ManualCatalogue(manual, sources, HERE / "build", namespace=output.stem,
                                tex_directory=HERE)
    inputs = ["% Generated by typeset-manuals.py; edit the Markdown sources.",
              r"\begin{MuManuals}"]
    for index, document in enumerate(catalogue.manuals, 1):
        # Index paths use numeric filenames, so arbitrary source names cannot
        # accidentally become TeX commands or collide after slugification.
        target = output.parent / output.stem / f"manual-{index:04d}.tex"
        body = "% Source: " + document.relative.replace("\r", r"\r").replace("\n", r"\n") + "\n"
        body += "\\chapter{" + inline(document.title) + "}\n"
        body += r"\label{" + document.anchor + "}\n"
        body += r"\MuManualSource{" + escape_latex(document.relative) + "}\n"
        body += fragment(document.body, reference=(document, catalogue))
        write_output(target, body, check)
        path = target.resolve()
        if path.is_relative_to(HERE):
            path = path.relative_to(HERE)
        inputs.append(r"\input{\detokenize{" + path.as_posix() + "}}")
    inputs.append(r"\end{MuManuals}")
    write_output(output, "\n".join(inputs) + "\n", check)
    for warning in sorted(catalogue.warnings):
        print("Manual rendering: " + warning, file=sys.stderr)
    return len(sources)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manual-dir", type=Path, default=repository_file("manual"))
    parser.add_argument("--output", type=Path, default=HERE / "build/generated/manuals.tex")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        count = generate(args.manual_dir, args.output, args.check)
    except (ValueError, OSError) as exc:
        parser.exit(1, str(exc) + "\n")
    print(f"{count} root manuals {'verified' if args.check else 'typeset'}")


if __name__ == "__main__":
    main()
