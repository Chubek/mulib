#!/usr/bin/env python3
"""Render repository MANIFEST.yaml metadata and every module as LaTeX."""
import argparse
from pathlib import Path

import yaml

from book_support import write_output, repository_file
from md2latex import escape_latex

HERE = Path(__file__).resolve().parent


def render(source):
    manifest = yaml.safe_load(source)
    if not isinstance(manifest, dict) or not isinstance(manifest.get("modules"), list):
        raise ValueError("manifest must contain a modules sequence")
    modules = manifest["modules"]
    if manifest.get("module_count") != len(modules):
        raise ValueError("manifest module_count does not match modules")
    names = [module.get("name") for module in modules if isinstance(module, dict)]
    if len(names) != len(modules) or any(not isinstance(n, str) or not n for n in names) or len(set(names)) != len(names):
        raise ValueError("manifest module names must be unique nonempty strings")

    def value(item):
        if isinstance(item, (dict, list)):
            item = yaml.safe_dump(item, sort_keys=True, default_flow_style=True).strip()
        return escape_latex(str(item))

    def fields(record):
        return "\n".join(r"\item[" + escape_latex(str(key)) + "] " + value(item)
                         for key, item in record.items())

    out = ["% Generated by typeset-manifest.py from MANIFEST.yaml.",
           r"\chapter{MuLIB manifest}", r"\begin{description}",
           fields({k: v for k, v in manifest.items() if k != "modules"}), r"\end{description}"]
    for module in sorted(modules, key=lambda m: m["name"]):
        out += [r"\section{" + escape_latex(module["name"]) + "}", r"\begin{description}",
                fields({k: v for k, v in module.items() if k != "name"}), r"\end{description}"]
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, default=repository_file("MANIFEST.yaml"))
    parser.add_argument("--output", type=Path, default=HERE / "build/generated/manifest.tex")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        write_output(args.output, render(args.manifest.read_text()), args.check)
    except (ValueError, OSError, yaml.YAMLError) as exc:
        parser.exit(1, str(exc) + "\n")


if __name__ == "__main__":
    main()
