#!/usr/bin/env python3
"""Export the 37 toolkit chapters; edit their Markdown sources in manual/."""
import argparse
from pathlib import Path
import re
from book_support import fragment

HERE = Path(__file__).resolve().parent


def export(source, number):
    text = source.read_text()
    text = re.sub(r'^# Chapter \d+\s*[:—-]\s*', '# ', text, count=1)
    text = re.sub(r'\[([^\]]+)\]\(ch(\d+)[^)]*\.md(?:#[^)]*)?\)',
                  lambda m: m[1] + ' (Chapter ' + str(int(m[2])) + ')', text)
    result = fragment(text, chapter=True)
    # Pandoc heading IDs are local to each input. Prefix them for a single book.
    result = re.sub(r'\\label\{([^}]+)\}', lambda m: r'\label{ch' + str(number) + '-' + m[1] + '}', result)
    result = re.sub(r'\\hyperref\[([^]]+)\]', lambda m: r'\hyperref[ch' + str(number) + '-' + m[1] + ']', result)
    return '% Generated by export_manual.py from ' + source.name + '\n' + result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sources = sorted((HERE.parent / 'manual').glob('ch[0-9][0-9]-*.md'))
    assert len(sources) == 37
    for number, source in enumerate(sources, 1):
        output = HERE / 'chapters' / f'chapter-{number}.ltx'
        result = export(source, number)
        if args.check:
            assert output.read_text() == result, f'{output}: run make -C book export'
        else:
            output.write_text(result)
    print('37 toolkit chapters ' + ('verified' if args.check else 'exported'))


if __name__ == '__main__':
    main()
