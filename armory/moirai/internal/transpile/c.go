package transpile

import (
	"strconv"
	"strings"

	"domscript/internal/ast"
	"domscript/internal/diag"
	"domscript/internal/parser"
)

// C converts Domscript source to a standalone, dependency-free ANSI C
// translation unit.  The generated program uses double for scalar values;
// Domscript constructs without a direct C scalar equivalent are emitted as
// conservative comments/zero expressions so the result remains compilable.
func C(src, name string) (string, error) {
	return CWithOptions(src, name, parser.ParseOptions{})
}

func CWithOptions(src, name string, opts parser.ParseOptions) (string, error) {
	diags := diag.NewSet(name, src)
	prog := parser.Parse(src, name, diags, opts)
	if diags.HasErrors() {
		return "", diag.NewErrorWithSource(diags)
	}
	e := &cEmitter{}
	e.program(prog)
	return e.b.String(), nil
}

type cEmitter struct {
	b      strings.Builder
	indent int
}

func (e *cEmitter) line(s string) {
	e.b.WriteString(strings.Repeat("  ", e.indent))
	e.b.WriteString(s)
	e.b.WriteByte('\n')
}

func (e *cEmitter) program(p *ast.Program) {
	e.line("/* Generated by domscript -T c; ANSI C */")
	e.line("#include <stddef.h>")
	e.line("#include <stdint.h>")
	e.line("/* The optional DOMSCRIPT_USE_RUNTIME bridge exposes the C API and stdlib. */")
	e.line("#ifdef DOMSCRIPT_USE_RUNTIME")
	e.line("#include \"domscript.h\"")
	e.line("#endif")
	e.line("")
	// Named function declarations are emitted before main, as required by C.
	for _, s := range p.Stmts {
		if l, ok := s.(*ast.Let); ok {
			switch f := l.Value.(type) {
			case *ast.FnLit:
				e.function(f, l.Name)
			case *ast.FnDecl:
				e.function(f.Fn, f.Name)
			}
		}
	}
	e.line("int main(void)")
	e.line("{")
	e.indent++
	e.line("#ifdef DOMSCRIPT_USE_RUNTIME")
	e.line("DomscriptState *__domscript_state = DomscriptOpen();")
	e.line("DomscriptRegisterStdlib(__domscript_state);")
	e.line("#endif")
	for _, s := range p.Stmts {
		if l, ok := s.(*ast.Let); ok {
			if _, fn := l.Value.(*ast.FnLit); fn {
				continue
			}
			if _, fn := l.Value.(*ast.FnDecl); fn {
				continue
			}
		}
		e.stmt(s)
	}
	e.line("#ifdef DOMSCRIPT_USE_RUNTIME")
	e.line("DomscriptClose(__domscript_state);")
	e.line("#endif")
	e.line("return 0;")
	e.indent--
	e.line("}")
}

func (e *cEmitter) function(f *ast.FnLit, name string) {
	params := make([]string, len(f.Params))
	for i, p := range f.Params {
		params[i] = "double " + p.Name
	}
	e.line("static double " + name + "(" + strings.Join(params, ", ") + ")")
	e.block(f.Body)
	e.line("")
}

func (e *cEmitter) block(b *ast.Block) {
	e.line("{")
	e.indent++
	for _, s := range b.Stmts {
		e.stmt(s)
	}
	e.indent--
	e.line("}")
}

func (e *cEmitter) stmt(s ast.Stmt) {
	switch x := s.(type) {
	case *ast.Let:
		e.line(e.declType(x.Value) + " " + x.Name + " = " + e.expr(x.Value) + ";")
	case *ast.Assign:
		e.line(e.expr(x.Target) + " = " + e.expr(x.Value) + ";")
	case *ast.ExprStmt:
		e.line(e.expr(x.X) + ";")
	case *ast.Import:
		e.line("/* import " + x.Module + " omitted */")
	case *ast.Module:
		return
	case *ast.ProgramDecl:
		return
	case *ast.Dialect:
		e.line("/* dialect " + x.Name + " */")
	case *ast.Extend:
		e.line("/* extend using " + x.Using + " */")
	case *ast.If:
		e.line("if (" + e.expr(x.Cond) + ")")
		e.block(x.Then)
		switch z := x.Else.(type) {
		case *ast.If:
			e.line("else")
			e.stmt(z)
		case *ast.Block:
			e.line("else")
			e.block(z)
		}
	case *ast.While:
		e.line("while (" + e.expr(x.Cond) + ")")
		e.block(x.Body)
	case *ast.For:
		e.line("/* for " + x.Var + " in " + e.expr(x.Iter) + " */")
		e.block(x.Body)
	case *ast.Return:
		if x.Value == nil {
			e.line("return 0;")
		} else {
			e.line("return " + e.expr(x.Value) + ";")
		}
	case *ast.Break:
		e.line("break;")
	case *ast.Continue:
		e.line("continue;")
	case *ast.BlockStmt:
		e.block(x.Block)
	case *ast.Block:
		e.block(x)
	case *ast.Effect:
		e.line("/* effect */")
		e.stmt(x.Body)
	case *ast.GrammarDecl:
		e.line("/* grammar " + x.Name + " */")
	case *ast.AbsynDecl:
		e.line("/* absyn " + x.Name + " */")
	case *ast.Match:
		e.matchStmt(x)
	case *ast.On:
		e.line("/* event handler omitted: " + x.Event + " */")
	}
}

func (e *cEmitter) declType(x ast.Expr) string {
	switch x.(type) {
	case *ast.StringLit:
		return "const char *"
	default:
		return "double"
	}
}

func (e *cEmitter) matchStmt(x *ast.Match) {
	for i, arm := range x.Arms {
		if i == 0 {
			e.line("if (" + e.pattern(x.Scrutinee, arm.Pat) + ")")
		} else {
			e.line("else if (" + e.pattern(x.Scrutinee, arm.Pat) + ")")
		}
		if b, ok := arm.Body.(*ast.Block); ok {
			e.block(b)
		} else {
			e.block(&ast.Block{Stmts: []ast.Stmt{&ast.ExprStmt{X: arm.Body}}})
		}
	}
}

func (e *cEmitter) pattern(scr ast.Expr, p ast.Pattern) string {
	switch x := p.(type) {
	case *ast.PatWildcard, *ast.PatBind, *ast.PatOptAny:
		return "1"
	case *ast.PatLit:
		return "(" + e.expr(scr) + " == " + e.expr(x.Lit) + ")"
	default:
		return "0"
	}
}

func (e *cEmitter) expr(x ast.Expr) string {
	switch v := x.(type) {
	case *ast.Ident:
		return v.Name
	case *ast.IntLit, *ast.FloatLit:
		return strings.TrimSpace(exprText(v))
	case *ast.StringLit:
		return strconv.Quote(v.Value)
	case *ast.InterpLit:
		parts := make([]string, len(v.Parts))
		for i, p := range v.Parts {
			parts[i] = e.expr(p)
		}
		return "(" + strings.Join(parts, ") /*+*/ (") + ")"
	case *ast.CharLit:
		return strconv.Quote(v.Value)
	case *ast.RegexLit:
		return strconv.Quote(v.Pattern)
	case *ast.NullLit:
		return "0"
	case *ast.BoolLit:
		if v.Value {
			return "1"
		}
		return "0"
	case *ast.UnitLit, *ast.OptNone, *ast.EffectResult:
		return "0"
	case *ast.TagLit, *ast.SelectorLit:
		return "0"
	case *ast.ListLit, *ast.TableLit, *ast.TaggedLit, *ast.NodeLit, *ast.EnumLit:
		return "0"
	case *ast.FnLit, *ast.FnDecl:
		return "0"
	case *ast.Unary:
		switch v.Op {
		case ast.OpNot:
			return "(!" + e.expr(v.X) + ")"
		case ast.OpNeg:
			return "(-" + e.expr(v.X) + ")"
		default:
			return e.expr(v.X)
		}
	case *ast.Binary:
		op := v.Op.String()
		switch v.Op {
		case ast.OpAnd:
			op = "&&"
		case ast.OpOr:
			op = "||"
		case ast.OpQuery:
			op = "||"
		case ast.OpRange:
			return "0"
		}
		return "(" + e.expr(v.L) + " " + op + " " + e.expr(v.R) + ")"
	case *ast.Call:
		args := make([]string, len(v.Args))
		for i, a := range v.Args {
			args[i] = e.expr(a)
		}
		return e.expr(v.Fn) + "(" + strings.Join(args, ", ") + ")"
	case *ast.Index:
		return e.expr(v.X) + "[" + e.expr(v.I) + "]"
	case *ast.Field:
		return e.expr(v.X) + "." + v.Name
	case *ast.If:
		then, els := "0", "0"
		if len(v.Then.Stmts) > 0 {
			if s, ok := v.Then.Stmts[len(v.Then.Stmts)-1].(*ast.ExprStmt); ok {
				then = e.expr(s.X)
			}
		}
		if b, ok := v.Else.(*ast.Block); ok && len(b.Stmts) > 0 {
			if s, ok := b.Stmts[len(b.Stmts)-1].(*ast.ExprStmt); ok {
				els = e.expr(s.X)
			}
		}
		return "(" + e.expr(v.Cond) + " ? " + then + " : " + els + ")"
	case *ast.Match, *ast.On:
		return "0"
	}
	return "0"
}

func exprText(v interface{}) string {
	switch x := v.(type) {
	case *ast.IntLit:
		return x.Text
	case *ast.FloatLit:
		return x.Text
	default:
		return "0"
	}
}
