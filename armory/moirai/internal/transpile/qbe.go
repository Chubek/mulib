package transpile

import (
	"strconv"
	"strings"

	"domscript/internal/ast"
	"domscript/internal/diag"
	"domscript/internal/parser"
)

// QBE lowers Domscript into QBE's textual SSA IL.  Scalar expressions use
// 32-bit words (w), which keeps the output consumable by every QBE target;
// richer Domscript values remain represented by runtime calls/comments until
// a host supplies the Domscript C API.
func QBE(src, name string) (string, error) {
	return QBEWithOptions(src, name, parser.ParseOptions{})
}

func QBEWithOptions(src, name string, opts parser.ParseOptions) (string, error) {
	diags := diag.NewSet(name, src)
	prog := parser.Parse(src, name, diags, opts)
	if diags.HasErrors() {
		return "", diag.NewErrorWithSource(diags)
	}
	e := &qbeEmitter{vars: make(map[string]string)}
	e.program(prog)
	return e.b.String(), nil
}

type qbeEmitter struct {
	b          strings.Builder
	data       strings.Builder
	vars       map[string]string
	tmp        int
	label      int
	dataID     int
	indent     int
	terminated bool
}

func (e *qbeEmitter) line(s string) {
	e.b.WriteString(strings.Repeat("\t", e.indent))
	e.b.WriteString(s)
	e.b.WriteByte('\n')
}

func (e *qbeEmitter) fresh(prefix string) string {
	e.tmp++
	return "%" + prefix + strconv.Itoa(e.tmp)
}

func (e *qbeEmitter) freshLabel(prefix string) string {
	e.label++
	return "@" + prefix + strconv.Itoa(e.label)
}

func (e *qbeEmitter) program(p *ast.Program) {
	e.line("# Generated by domscript -T qbe")
	e.line("# Domscript stdlib and C API symbols are supplied by the embedding host.")
	e.line("")
	for _, s := range p.Stmts {
		if l, ok := s.(*ast.Let); ok {
			switch f := l.Value.(type) {
			case *ast.FnLit:
				e.function(f, l.Name)
			case *ast.FnDecl:
				e.function(f.Fn, f.Name)
			}
		}
	}
	e.line("export function w $main() {")
	e.indent++
	e.line("@entry")
	for _, s := range p.Stmts {
		if l, ok := s.(*ast.Let); ok {
			if _, fn := l.Value.(*ast.FnLit); fn {
				continue
			}
			if _, fn := l.Value.(*ast.FnDecl); fn {
				continue
			}
		}
		e.stmt(s)
	}
	e.line("ret 0")
	e.indent--
	e.line("}")
	if e.data.Len() > 0 {
		e.line("")
		e.b.WriteString(e.data.String())
	}
}

func (e *qbeEmitter) function(f *ast.FnLit, name string) {
	if name == "" {
		name = "anonymous"
	}
	params := make([]string, len(f.Params))
	for i, p := range f.Params {
		params[i] = "w %" + p.Name
	}
	e.line("function w $" + sanitize(name) + "(" + strings.Join(params, ", ") + ") {")
	e.indent++
	e.line("@entry")
	for _, p := range f.Params {
		e.vars[p.Name] = "%" + p.Name
	}
	for _, s := range f.Body.Stmts {
		e.stmt(s)
	}
	if !e.terminated {
		e.line("ret 0")
	}
	e.terminated = false
	e.indent--
	e.line("}")
	e.line("")
}

func (e *qbeEmitter) stmt(s ast.Stmt) {
	switch x := s.(type) {
	case *ast.Let:
		if _, fn := x.Value.(*ast.FnLit); fn {
			return
		}
		if _, fn := x.Value.(*ast.FnDecl); fn {
			return
		}
		e.vars[x.Name] = e.expr(x.Value)
	case *ast.Assign:
		if id, ok := x.Target.(*ast.Ident); ok {
			e.vars[id.Name] = e.expr(x.Value)
		} else {
			_ = e.expr(x.Value)
		}
	case *ast.ExprStmt:
		_ = e.expr(x.X)
	case *ast.Import:
		e.line("# import " + x.Module + " form " + x.Library)
	case *ast.Module:
		return
	case *ast.ProgramDecl:
		return
	case *ast.Dialect:
		e.line("# dialect " + x.Name)
	case *ast.Extend:
		e.line("# extend using " + x.Using)
	case *ast.GrammarDecl:
		e.line("# grammar " + x.Name)
	case *ast.AbsynDecl:
		e.line("# absyn " + x.Name)
	case *ast.Return:
		if x.Value == nil {
			e.line("ret 0")
		} else {
			e.line("ret " + e.expr(x.Value))
		}
		e.terminated = true
	case *ast.If:
		cond := e.expr(x.Cond)
		thenLabel, elseLabel, endLabel := e.freshLabel("then"), e.freshLabel("else"), e.freshLabel("ifend")
		e.line("jnz " + cond + ", " + thenLabel + ", " + elseLabel)
		e.line(thenLabel)
		e.indent++
		e.block(x.Then)
		e.indent--
		e.line("jmp " + endLabel)
		e.line(elseLabel)
		if x.Else != nil {
			e.indent++
			e.stmt(x.Else)
			e.indent--
		}
		e.line("jmp " + endLabel)
		e.line(endLabel)
	case *ast.While:
		head, body, done := e.freshLabel("while"), e.freshLabel("whilebody"), e.freshLabel("whileend")
		e.line("jmp " + head)
		e.line(head)
		e.line("jnz " + e.expr(x.Cond) + ", " + body + ", " + done)
		e.line(body)
		e.indent++
		e.block(x.Body)
		e.indent--
		e.line("jmp " + head)
		e.line(done)
	case *ast.Block, *ast.BlockStmt:
		if b, ok := x.(*ast.Block); ok {
			e.block(b)
		} else {
			e.block(x.(*ast.BlockStmt).Block)
		}
	case *ast.For:
		e.line("# for " + x.Var + " in " + e.expr(x.Iter))
		e.block(x.Body)
	case *ast.Match:
		for _, arm := range x.Arms {
			e.line("# match arm " + e.pattern(x.Scrutinee, arm.Pat))
			if b, ok := arm.Body.(*ast.Block); ok {
				e.block(b)
			} else {
				_ = e.expr(arm.Body)
			}
		}
	case *ast.Effect:
		e.stmt(x.Body)
	case *ast.Break, *ast.Continue, *ast.On:
		e.line("# unsupported control construct")
	}
}

func (e *qbeEmitter) block(b *ast.Block) {
	for _, s := range b.Stmts {
		e.stmt(s)
	}
}

func (e *qbeEmitter) pattern(scr ast.Expr, p ast.Pattern) string {
	switch x := p.(type) {
	case *ast.PatLit:
		return e.expr(scr) + " == " + e.expr(x.Lit)
	default:
		return "1"
	}
}

func (e *qbeEmitter) expr(x ast.Expr) string {
	switch v := x.(type) {
	case *ast.Ident:
		if value, ok := e.vars[v.Name]; ok {
			return value
		}
		return "0"
	case *ast.IntLit:
		return v.Text
	case *ast.FloatLit:
		return "0"
	case *ast.BoolLit:
		if v.Value {
			return "1"
		}
		return "0"
	case *ast.StringLit:
		e.stringData(v.Value)
		return "0"
	case *ast.InterpLit:
		for _, p := range v.Parts {
			_ = e.expr(p)
		}
		return "0"
	case *ast.CharLit:
		e.stringData(v.Value)
		return "0"
	case *ast.RegexLit:
		e.stringData(v.Pattern)
		return "0"
	case *ast.NullLit:
		return "0"
	case *ast.UnitLit, *ast.OptNone, *ast.TagLit, *ast.SelectorLit, *ast.EffectResult:
		return "0"
	case *ast.Unary:
		x := e.expr(v.X)
		switch v.Op {
		case ast.OpNeg:
			t := e.fresh("neg")
			e.line(t + " =w neg " + x)
			return t
		case ast.OpNot:
			t := e.fresh("not")
			e.line(t + " =w ceqw " + x + ", 0")
			return t
		}
		return x
	case *ast.Binary:
		l, r := e.expr(v.L), e.expr(v.R)
		op := v.Op.String()
		switch v.Op {
		case ast.OpAdd:
			op = "add"
		case ast.OpSub:
			op = "sub"
		case ast.OpMul:
			op = "mul"
		case ast.OpDiv:
			op = "div"
		case ast.OpMod:
			op = "rem"
		case ast.OpAnd:
			op = "and"
		case ast.OpOr:
			op = "or"
		case ast.OpEq:
			op = "ceqw"
		case ast.OpNeq:
			op = "cnew"
		case ast.OpLt:
			op = "csltw"
		case ast.OpLe:
			op = "cslew"
		case ast.OpGt:
			op = "csgtw"
		case ast.OpGe:
			op = "csgew"
		}
		t := e.fresh("bin")
		e.line(t + " =w " + op + " " + l + ", " + r)
		return t
	case *ast.Call:
		args := make([]string, len(v.Args))
		for i, a := range v.Args {
			args[i] = "w " + e.expr(a)
		}
		fn := e.expr(v.Fn)
		if id, ok := v.Fn.(*ast.Ident); ok {
			fn = "$" + sanitize(id.Name)
		}
		t := e.fresh("call")
		e.line(t + " =w call " + fn + "(" + strings.Join(args, ", ") + ")")
		return t
	case *ast.If:
		if len(v.Then.Stmts) > 0 {
			if last, ok := v.Then.Stmts[len(v.Then.Stmts)-1].(*ast.ExprStmt); ok {
				return e.expr(last.X)
			}
		}
		return "0"
	case *ast.FnLit, *ast.FnDecl, *ast.ListLit, *ast.TableLit, *ast.TaggedLit, *ast.NodeLit, *ast.EnumLit, *ast.Index, *ast.Field, *ast.Match, *ast.On:
		return "0"
	}
	return "0"
}

func (e *qbeEmitter) stringData(value string) {
	e.dataID++
	label := "$.domscript.str" + strconv.Itoa(e.dataID)
	// Keep strings visible to the QBE/linker pipeline even though scalar-only
	// lowering currently represents aggregate values as a null handle.
	e.data.WriteString("data " + label + " = { b ")
	e.data.WriteString(strconv.Quote(value))
	e.data.WriteString(", b 0 }\n")
}

func sanitize(name string) string {
	var b strings.Builder
	for _, r := range name {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '_' {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	if b.Len() == 0 {
		return "anon"
	}
	return b.String()
}
