package transpile

import (
	"strconv"
	"strings"

	"domscript/internal/ast"
	"domscript/internal/diag"
	"domscript/internal/parser"
)

// JavaScript converts Domscript source to readable, dependency-free
// ECMAScript. It intentionally emits ordinary JavaScript values so generated
// programs can be run directly in browsers, Node, or other JS hosts.
func JavaScript(src, name string) (string, error) {
	return JavaScriptWithOptions(src, name, parser.ParseOptions{})
}

func JavaScriptWithOptions(src, name string, opts parser.ParseOptions) (string, error) {
	diags := diag.NewSet(name, src)
	prog := parser.Parse(src, name, diags, opts)
	if diags.HasErrors() {
		return "", diag.NewErrorWithSource(diags)
	}
	e := &emitter{}
	e.program(prog)
	return e.b.String(), nil
}

type emitter struct {
	b      strings.Builder
	indent int
}

func (e *emitter) line(s string) {
	e.b.WriteString(strings.Repeat("  ", e.indent))
	e.b.WriteString(s)
	e.b.WriteByte('\n')
}

func (e *emitter) program(p *ast.Program) {
	e.line("// Generated by domscript -T js; VanillaJS")
	e.line("// The host may provide domscriptStdlib (the same modules exposed by the C API).")
	e.line("const __domscript_builtin_io = { print: (...xs) => console.log(...xs), println: (...xs) => console.log(...xs) };")
	e.line("const __domscript_stdlib = Object.assign({ io: __domscript_builtin_io }, globalThis.domscriptStdlib ?? {});")
	for _, s := range p.Stmts {
		e.stmt(s)
	}
}

func (e *emitter) block(b *ast.Block) {
	e.line("{")
	e.indent++
	for _, s := range b.Stmts {
		e.stmt(s)
	}
	e.indent--
	e.line("}")
}

func (e *emitter) stmt(s ast.Stmt) {
	switch x := s.(type) {
	case *ast.Let:
		e.line("let " + x.Name + " = " + e.expr(x.Value) + ";")
	case *ast.Assign:
		e.line(e.expr(x.Target) + " = " + e.expr(x.Value) + ";")
	case *ast.ExprStmt:
		e.line(e.expr(x.X) + ";")
	case *ast.Import:
		name := x.Alias
		if name == "" {
			name = x.Module
			if i := strings.LastIndex(name, "."); i >= 0 {
				name = name[i+1:]
			}
		}
		e.line("const " + name + " = __domscript_stdlib[" + strconv.Quote(x.Module) + "] ?? {};")
	case *ast.Module:
		return
	case *ast.ProgramDecl:
		return
	case *ast.Dialect:
		e.line("// dialect " + strconv.Quote(x.Name))
	case *ast.Extend:
		e.line("// extend using " + x.Using + " {")
		for _, line := range strings.Split(x.Body, "\n") {
			e.line("// " + line)
		}
		e.line("// }")
	case *ast.GrammarDecl:
		e.line("// grammar " + x.Name)
	case *ast.AbsynDecl:
		e.line("// absyn " + x.Name)
	case *ast.If:
		e.line("if (" + e.expr(x.Cond) + ") ")
		e.block(x.Then)
		switch z := x.Else.(type) {
		case *ast.If:
			e.line("else ")
			e.stmt(z)
		case *ast.Block:
			e.line("else ")
			e.block(z)
		}
	case *ast.While:
		e.line("while (" + e.expr(x.Cond) + ") ")
		e.block(x.Body)
	case *ast.For:
		e.line("for (const " + x.Var + " of " + e.expr(x.Iter) + ") ")
		e.block(x.Body)
	case *ast.Return:
		if x.Value == nil {
			e.line("return;")
		} else {
			e.line("return " + e.expr(x.Value) + ";")
		}
	case *ast.Break:
		e.line("break;")
	case *ast.Continue:
		e.line("continue;")
	case *ast.BlockStmt, *ast.Block:
		var b *ast.Block
		switch z := x.(type) {
		case *ast.BlockStmt:
			b = z.Block
		case *ast.Block:
			b = z
		}
		e.block(b)
	case *ast.Effect:
		e.line("try ")
		e.block(&ast.Block{Stmts: []ast.Stmt{&ast.ExprStmt{X: x.Operand}}})
		e.line("catch (__domscript_error) ")
		e.blockStmt(x.Body)
	case *ast.Match:
		e.matchStmt(x)
	case *ast.On:
		e.line("/* event handler omitted: " + x.Event + " */")
	}
}

func (e *emitter) blockStmt(s ast.Stmt) {
	if b, ok := s.(*ast.Block); ok {
		e.block(b)
		return
	}
	e.line("{")
	e.indent++
	e.stmt(s)
	e.indent--
	e.line("}")
}

func (e *emitter) matchStmt(x *ast.Match) {
	for i, arm := range x.Arms {
		kw := "if"
		if i > 0 {
			kw = "else if"
		}
		e.line(kw + " (" + e.pattern(x.Scrutinee, arm.Pat) + ") ")
		if b, ok := arm.Body.(*ast.Block); ok {
			e.block(b)
		} else {
			e.block(&ast.Block{Stmts: []ast.Stmt{&ast.ExprStmt{X: arm.Body}}})
		}
	}
}

func (e *emitter) pattern(scr ast.Expr, p ast.Pattern) string {
	switch x := p.(type) {
	case *ast.PatWildcard, *ast.PatBind, *ast.PatOptAny:
		return "true"
	case *ast.PatLit:
		return e.expr(scr) + " === " + e.expr(x.Lit)
	case *ast.PatTagged:
		return e.expr(scr) + "?.tag === " + strconv.Quote(x.Tag)
	case *ast.PatSome:
		return e.expr(scr) + "?.tag === \"Some\""
	case *ast.PatList:
		return "Array.isArray(" + e.expr(scr) + ")"
	default:
		return "false"
	}
}

func (e *emitter) expr(x ast.Expr) string {
	switch v := x.(type) {
	case *ast.Ident:
		return v.Name
	case *ast.IntLit:
		return v.Text
	case *ast.FloatLit:
		return v.Text
	case *ast.StringLit:
		return strconv.Quote(v.Value)
	case *ast.InterpLit:
		parts := make([]string, len(v.Parts))
		for i, p := range v.Parts {
			parts[i] = "${" + e.expr(p) + "}"
		}
		// Emit as concatenation to avoid backtick escaping issues.
		out := ""
		for i, p := range v.Parts {
			s := e.expr(p)
			if _, ok := p.(*ast.StringLit); ok {
				s = strconv.Quote(v.Parts[i].(*ast.StringLit).Value)
			} else {
				s = "String(" + s + ")"
			}
			if i > 0 {
				out += " + "
			}
			out += s
		}
		_ = parts
		return "(" + out + ")"
	case *ast.CharLit:
		return strconv.Quote(v.Value)
	case *ast.RegexLit:
		return "/" + v.Pattern + "/"
	case *ast.NullLit:
		return "{tag: \"None\"}"
	case *ast.BoolLit:
		if v.Value {
			return "true"
		}
		return "false"
	case *ast.UnitLit:
		return "undefined"
	case *ast.TagLit:
		return "{tag: " + strconv.Quote(v.Name) + "}"
	case *ast.OptNone:
		return "{tag: \"None\"}"
	case *ast.SelectorLit:
		return strconv.Quote(v.Src)
	case *ast.ListLit:
		parts := make([]string, len(v.Elems))
		for i, p := range v.Elems {
			parts[i] = e.expr(p)
		}
		return "[" + strings.Join(parts, ", ") + "]"
	case *ast.TableLit:
		parts := make([]string, len(v.Entries))
		for i, p := range v.Entries {
			key := e.expr(p.Key)
			if id, ok := p.Key.(*ast.Ident); ok {
				key = strconv.Quote(id.Name)
			}
			parts[i] = "[" + key + "]: " + e.expr(p.Value)
		}
		return "{" + strings.Join(parts, ", ") + "}"
	case *ast.TaggedLit:
		parts := make([]string, len(v.Elems))
		for i, p := range v.Elems {
			parts[i] = e.expr(p)
		}
		if len(parts) == 0 {
			return "{tag: " + strconv.Quote(v.Tag) + "}"
		}
		return "{tag: " + strconv.Quote(v.Tag) + ", value: [" + strings.Join(parts, ", ") + "]}"
	case *ast.FnLit:
		return e.fn(v, "")
	case *ast.FnDecl:
		return e.fn(v.Fn, v.Name)
	case *ast.EnumLit:
		parts := make([]string, len(v.Members))
		for i, m := range v.Members {
			parts[i] = strconv.Quote(m.Name) + ": " + e.expr(m.Value)
		}
		return "{" + strings.Join(parts, ", ") + "}"
	case *ast.Unary:
		switch v.Op {
		case ast.OpNot:
			return "(!" + e.expr(v.X) + ")"
		case ast.OpNeg:
			return "(-" + e.expr(v.X) + ")"
		case ast.OpSome:
			return "{tag: \"Some\", value: [" + e.expr(v.X) + "]}"
		case ast.OpEff:
			return e.expr(v.X)
		}
	case *ast.Binary:
		op := v.Op.String()
		switch v.Op {
		case ast.OpAnd:
			op = "&&"
		case ast.OpOr:
			op = "||"
		case ast.OpEq:
			op = "==="
		case ast.OpNeq:
			op = "!=="
		case ast.OpRange:
			return "Array.from({length: (" + e.expr(v.R) + ")-(" + e.expr(v.L) + ")}, (_, __i) => (" + e.expr(v.L) + ")+__i)"
		case ast.OpQuery:
			return "(" + e.expr(v.L) + " ?? " + e.expr(v.R) + ")"
		}
		return "(" + e.expr(v.L) + " " + op + " " + e.expr(v.R) + ")"
	case *ast.Call:
		args := make([]string, len(v.Args))
		for i, a := range v.Args {
			args[i] = e.expr(a)
		}
		return e.expr(v.Fn) + "(" + strings.Join(args, ", ") + ")"
	case *ast.Index:
		return e.expr(v.X) + "[" + e.expr(v.I) + "]"
	case *ast.Field:
		return e.expr(v.X) + "." + v.Name
	case *ast.If:
		then := e.exprBlock(v.Then)
		els := "undefined"
		if b, ok := v.Else.(*ast.Block); ok {
			els = e.exprBlock(b)
		} else if z, ok := v.Else.(*ast.If); ok {
			els = e.expr(z)
		}
		return "(" + e.expr(v.Cond) + " ? " + then + " : " + els + ")"
	case *ast.Match:
		return "undefined"
	case *ast.On:
		return "undefined"
	case *ast.EffectResult:
		return "__domscript_effect"
	case *ast.NodeLit:
		return e.node(v)
	}
	return "undefined"
}

func (e *emitter) fn(x *ast.FnLit, name string) string {
	params := make([]string, 0, len(x.Params))
	for _, p := range x.Params {
		if p.Rest {
			params = append(params, "..."+p.Name)
		} else {
			params = append(params, p.Name)
		}
	}
	var b strings.Builder
	b.WriteString("function")
	if name != "" {
		b.WriteByte(' ')
		b.WriteString(name)
	}
	b.WriteString("(")
	b.WriteString(strings.Join(params, ", "))
	b.WriteString(") ")
	body := &emitter{indent: e.indent}
	body.block(x.Body)
	b.WriteString(body.b.String())
	return b.String()
}

func (e *emitter) exprBlock(b *ast.Block) string {
	for _, s := range b.Stmts {
		if x, ok := s.(*ast.ExprStmt); ok {
			return e.expr(x.X)
		}
	}
	return "undefined"
}

func (e *emitter) node(n *ast.NodeLit) string {
	var parts []string
	for _, p := range n.Body {
		switch x := p.(type) {
		case *ast.NodeText:
			parts = append(parts, strconv.Quote(x.Text))
		case *ast.NodeSplice:
			parts = append(parts, e.expr(x.X))
		case *ast.NodeElement:
			parts = append(parts, e.element(x))
		}
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

func (e *emitter) element(x *ast.NodeElement) string {
	attrs := make([]string, len(x.Attrs))
	for i, a := range x.Attrs {
		value := strconv.Quote(a.Literal)
		if a.Value != nil {
			value = e.expr(a.Value)
		}
		attrs[i] = strconv.Quote(a.Name) + ": " + value
	}
	return "{tag: " + strconv.Quote(x.Name) + ", attrs: {" + strings.Join(attrs, ", ") + "}, children: []}"
}
