typedef struct mulib_midi_event {
  uint32_t tick;
  unsigned track, status, meta;
  unsigned char *data;
  size_t size;
} mulib_midi_event_t;
/** Owns every event and its payload. Initialize to zero, then init. */
typedef struct mulib_midi {
  unsigned division, tracks;
  mulib_midi_event_t *events;
  size_t count, capacity;
} mulib_midi_t;
/** PPQN division 1..32767, tracks 1..65535. SMPTE timing is unsupported. */
mulib_audio_status_t mulib_midi_init (mulib_midi_t *, unsigned division, unsigned tracks);
/** Free all storage and zero the sequence. */
void mulib_midi_free (mulib_midi_t *);
/** Copy a channel, F0/F7 SysEx or FF meta event. Channel payload has one or two
 * 7-bit bytes; meta identifies FF events. End-of-track is generated by encode:
 * explicit EOT events preserve trailing silence and must follow all track data.
 * Events may be added out of order; encode sorts a copy stably. */
mulib_audio_status_t mulib_midi_event (mulib_midi_t *, unsigned track, uint32_t tick,
    unsigned status, unsigned meta, const void *data, size_t size);
/** Append paired note-on/off atomically; duration must be positive. */
mulib_audio_status_t mulib_midi_note (mulib_midi_t *, unsigned track, uint32_t tick,
    uint32_t duration, unsigned channel, unsigned key, unsigned velocity);
/** Tempo in microseconds per quarter note, 1..16777215. */
mulib_audio_status_t mulib_midi_tempo (mulib_midi_t *, unsigned track, uint32_t tick, uint32_t usec);
/** Encode SMF0 for one track, SMF1 otherwise. Output must be empty. */
mulib_audio_status_t mulib_midi_encode (const mulib_midi_t *, mulib_audio_bytes_t *);
/** Decode SMF0/1 with running status. Zero max_events selects 1000000.
 * Output must be zero initialized. Failure leaves it unchanged. */
mulib_audio_status_t mulib_midi_decode (const void *, size_t, size_t max_events, mulib_midi_t *);
