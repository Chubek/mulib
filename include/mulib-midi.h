mulib_audio_status_t mulib_midi_init (mulib_midi_t *m, unsigned d, unsigned t)
{
  if(!m || m->events || m->count || m->capacity || m->division || m->tracks || !d || d>32767 || !t || t>65535) return MULIB_AUDIO_INVALID;
  m->division=d; m->tracks=t; return MULIB_AUDIO_OK;
}
void mulib_midi_free (mulib_midi_t *m)
{ if(m) { size_t i; for(i=0;i<m->count;++i) free(m->events[i].data); free(m->events); memset(m,0,sizeof(*m)); } }
mulib_audio_status_t mulib_midi_event (mulib_midi_t *m, unsigned track, uint32_t tick,
    unsigned status, unsigned meta, const void *data, size_t n)
{
  unsigned char *copy=NULL; size_t i; mulib_midi_event_t *p;
  if(!m || !m->division || track>=m->tracks || (!data && n) || n>0xfffffff) return MULIB_AUDIO_INVALID;
  if(status>=0x80 && status<=0xef) {
    if(n!=((status&0xe0)==0xc0 ? 1u : 2u)) return MULIB_AUDIO_INVALID;
    for(i=0;i<n;++i) if(((const unsigned char *)data)[i]>127) return MULIB_AUDIO_INVALID;
  } else if(status==255) { if(meta>127 || (meta==47 && n)) return MULIB_AUDIO_INVALID; }
  else if(status!=240 && status!=247) return MULIB_AUDIO_INVALID;
  if(n) { copy=(unsigned char *)malloc(n); if(!copy) return MULIB_AUDIO_MEMORY; memcpy(copy,data,n); }
  if(m->count==m->capacity) {
    size_t cap=m->capacity ? m->capacity*2 : 32;
    if(cap<m->capacity || cap>SIZE_MAX/sizeof(*p)) { free(copy); return MULIB_AUDIO_LIMIT; }
    p=(mulib_midi_event_t *)realloc(m->events,cap*sizeof(*p));
    if(!p) { free(copy); return MULIB_AUDIO_MEMORY; }
    m->events=p; m->capacity=cap;
  }
  p=m->events+m->count++; p->tick=tick; p->track=track; p->status=status; p->meta=meta; p->data=copy; p->size=n;
  return MULIB_AUDIO_OK;
}
mulib_audio_status_t mulib_midi_note (mulib_midi_t *m, unsigned t, uint32_t tick,
    uint32_t duration, unsigned channel, unsigned key, unsigned velocity)
{
  unsigned char data[2]; mulib_audio_status_t st;
  if(!duration || duration>UINT32_MAX-tick || channel>15 || key>127 || !velocity || velocity>127) return MULIB_AUDIO_INVALID;
  data[0]=(unsigned char)key; data[1]=(unsigned char)velocity;
  st=mulib_midi_event(m,t,tick,0x90|channel,0,data,2); if(st) return st;
  data[1]=0; st=mulib_midi_event(m,t,tick+duration,0x80|channel,0,data,2);
  if(st) free(m->events[--m->count].data);
  return st;
}
mulib_audio_status_t mulib_midi_tempo (mulib_midi_t *m, unsigned t, uint32_t tick, uint32_t us)
{
  unsigned char b[3]; if(!us || us>0xffffff) return MULIB_AUDIO_INVALID;
  b[0]=(unsigned char)(us>>16); b[1]=(unsigned char)(us>>8); b[2]=(unsigned char)us;
  return mulib_midi_event(m,t,tick,255,81,b,3);
}
static mulib_audio_status_t mulib_midi_vlq_ (mulib_audio_bytes_t *b, uint32_t v)
{
  unsigned char p[4]; unsigned n=1, i; if(v>0xfffffff) return MULIB_AUDIO_LIMIT;
  p[3]=(unsigned char)(v&127);
  while((v>>=7)!=0) p[3-n++]=(unsigned char)(128|(v&127));
  i=4-n; return mulib_audio_append(b,p+i,n);
}
static int mulib_midi_compare_ (const void *a, const void *b)
{
  const mulib_midi_event_t *x=*(const mulib_midi_event_t *const *)a, *y=*(const mulib_midi_event_t *const *)b;
  if(x->track!=y->track) return x->track<y->track ? -1 : 1;
  if(x->tick!=y->tick) return x->tick<y->tick ? -1 : 1;
  /* Preserve insertion order for simultaneous controls, programs and notes. */
  return x<y ? -1 : x>y;
}
static void mulib_midi_be_ (unsigned char *p, uint32_t v, unsigned n)
{ while(n) { p[--n]=(unsigned char)v; v>>=8; } }
mulib_audio_status_t mulib_midi_encode (const mulib_midi_t *m, mulib_audio_bytes_t *out)
{
  mulib_audio_bytes_t b={0}; const mulib_midi_event_t **order=NULL; size_t i, at=0; unsigned t;
  unsigned char h[14]={'M','T','h','d',0,0,0,6,0,0,0,0,0,0}; mulib_audio_status_t st;
  if(!m || !out || out->data || out->size || out->capacity || !m->division || m->division>32767 || !m->tracks || m->tracks>65535) return MULIB_AUDIO_INVALID;
  if(m->count>SIZE_MAX/sizeof(*order)) return MULIB_AUDIO_LIMIT;
  if(m->count) { order=(const mulib_midi_event_t **)malloc(m->count*sizeof(*order)); if(!order) return MULIB_AUDIO_MEMORY; }
  for(i=0;i<m->count;++i) order[i]=m->events+i;
  if(m->count) qsort(order,m->count,sizeof(*order),mulib_midi_compare_);
  h[9]=(unsigned char)(m->tracks>1); mulib_midi_be_(h+10,m->tracks,2); mulib_midi_be_(h+12,m->division,2);
  st=mulib_audio_append(&b,h,14);
  for(t=0;!st && t<m->tracks;++t) {
    size_t start=b.size; uint32_t tick=0; int ended=0;
    st=mulib_audio_append(&b,"MTrk\0\0\0\0",8);
    while(!st && at<m->count && order[at]->track==t) {
      const mulib_midi_event_t *e=order[at++]; unsigned char c=(unsigned char)e->status;
      if(ended) { st=MULIB_AUDIO_INVALID; break; }
      st=mulib_midi_vlq_(&b,e->tick-tick); tick=e->tick;
      if(!st) st=mulib_audio_append(&b,&c,1);
      if(!st && e->status==255) { c=(unsigned char)e->meta; st=mulib_audio_append(&b,&c,1); ended=e->meta==47; }
      if(!st && e->status>=240) st=mulib_midi_vlq_(&b,(uint32_t)e->size);
      if(!st) st=mulib_audio_append(&b,e->data,e->size);
    }
    if(!st && !ended) st=mulib_audio_append(&b,"\0\xff\x2f\0",4);
    if(!st) { if(b.size-start-8>UINT32_MAX) st=MULIB_AUDIO_LIMIT; else mulib_midi_be_(b.data+start+4,(uint32_t)(b.size-start-8),4); }
  }
  free(order);
  if(st) mulib_audio_bytes_free(&b); else *out=b;
  return st;
}
static uint32_t mulib_midi_u_ (const unsigned char *p, unsigned n)
{ uint32_t v=0; while(n--) v=(v<<8)|*p++; return v; }
static int mulib_midi_readvlq_ (const unsigned char *p, size_t end, size_t *at, uint32_t *out)
{
  unsigned i; uint32_t v=0;
  for(i=0;i<4;++i) { unsigned c; if(*at>=end) return 0; c=p[(*at)++]; v=(v<<7)|(c&127); if(!(c&128)) { *out=v; return 1; } }
  return 0;
}
mulib_audio_status_t mulib_midi_decode (const void *data, size_t size, size_t max, mulib_midi_t *out)
{
  const unsigned char *p=(const unsigned char *)data; size_t at; unsigned format, tracks, division, t;
  mulib_midi_t m={0}; mulib_audio_status_t st=MULIB_AUDIO_FORMAT;
  if(!out || out->events || out->count || out->capacity || out->tracks || out->division || (!data && size)) return MULIB_AUDIO_INVALID;
  if(size<14 || memcmp(p,"MThd",4) || mulib_midi_u_(p+4,4)<6 || mulib_midi_u_(p+4,4)>size-8) return MULIB_AUDIO_FORMAT;
  format=mulib_midi_u_(p+8,2); tracks=mulib_midi_u_(p+10,2); division=mulib_midi_u_(p+12,2);
  if(format>1 || (division&32768)) return MULIB_AUDIO_UNSUPPORTED;
  if(!tracks || !division || (!format && tracks!=1)) return MULIB_AUDIO_FORMAT;
  (void)mulib_midi_init(&m,division,tracks); if(!max) max=1000000;
  at=8+(size_t)mulib_midi_u_(p+4,4);
  for(t=0;t<tracks;++t) {
    size_t end; uint32_t tick=0; unsigned running=0; int ended=0;
    if(size-at<8 || memcmp(p+at,"MTrk",4) || mulib_midi_u_(p+at+4,4)>size-at-8) goto fail;
    end=at+8+mulib_midi_u_(p+at+4,4); at+=8;
    while(at<end) {
      uint32_t delta, n; unsigned status, meta=0;
      if(ended || !mulib_midi_readvlq_(p,end,&at,&delta) || delta>UINT32_MAX-tick || at==end) goto fail;
      tick+=delta; status=p[at];
      if(status<128) { if(!running) goto fail; status=running; } else ++at;
      if(status<240) { running=status; n=(status&0xe0)==0xc0 ? 1 : 2; }
      else {
        running=0;
        if(status==255) { if(at==end || p[at]>127) goto fail; meta=p[at++]; }
        else if(status!=240 && status!=247) goto fail;
        if(!mulib_midi_readvlq_(p,end,&at,&n)) goto fail;
      }
      if(n>end-at) goto fail;
      if(m.count==max) { st=MULIB_AUDIO_LIMIT; goto fail; }
      st=mulib_midi_event(&m,t,tick,status,meta,p+at,n);
      if(st) { if(st==MULIB_AUDIO_INVALID) st=MULIB_AUDIO_FORMAT; goto fail; }
      at+=n; ended=status==255 && meta==47; st=MULIB_AUDIO_FORMAT;
    }
    if(!ended) goto fail;
  }
  if(at!=size) goto fail;
  *out=m; return MULIB_AUDIO_OK;
fail:
  mulib_midi_free(&m); return st;
}
