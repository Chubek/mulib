mulib_docstril_t *mulib_docstril_create(void) {
    mulib_docstril_t *n = mulib_dsdom_element("docstril", NULL);
    if (n && !mulib_xml_set_attr(n, "version", "1")) { mulib_xml_destroy(n); n = NULL; }
    return n;
}
static int mulib_docstril_check_(const mulib_docstril_t *n, size_t depth, size_t *nodes,
                                size_t *bytes, const char **message) {
    const mulib_docstril_t *c;
    const char *name = mulib_xml_name(n), *value;
    size_t i, length;
    if (!*nodes || depth > MULIB_DOCSTRIL_MAX_DEPTH) { *message = "DocstrIL node/depth limit"; return 0; }
    --*nodes;
    if (mulib_xml_type(n) != MULIB_XML_ELEMENT && mulib_xml_type(n) != MULIB_XML_TEXT) {
        *message = "DocstrIL requires elements and text"; return 0;
    }
    if (name && !strcmp(name, "heading")) {
        value = mulib_xml_attr(n, "level");
        if (!value || value[0] < '1' || value[0] > '6' || value[1]) { *message = "invalid heading level"; return 0; }
    }
    value = name ? name : mulib_xml_value(n);
    length = strlen(value);
    if (length > *bytes) goto limit;
    *bytes -= length;
    for (i = 0; i < mulib_xml_attr_count(n); ++i) {
        length = strlen(mulib_xml_attr_name(n, i));
        if (length > *bytes) goto limit;
        *bytes -= length; length = strlen(mulib_xml_attr_value(n, i));
        if (length > *bytes) goto limit;
        *bytes -= length;
    }
    for (c = mulib_xml_first(n); c; c = mulib_xml_next(c)) {
        const char *child = mulib_xml_name(c);
        if (name && ((!strcmp(name, "table") && (!child || strcmp(child, "row"))) ||
                     (!strcmp(name, "row") && (!child || strcmp(child, "cell"))) ||
                     (!strcmp(name, "list") && (!child || strcmp(child, "item"))))) {
            *message = "invalid table/list child"; return 0;
        }
        if (!mulib_docstril_check_(c, depth + 1, nodes, bytes, message)) return 0;
    }
    return 1;
limit:
    *message = "DocstrIL byte limit"; return 0;
}
int mulib_docstril_validate(const mulib_docstril_t *d, size_t nodes, size_t bytes, mulib_xml_error_t *e) {
    const char *message = "invalid DocstrIL root/version";
    size_t initial;
    int ok = 0;
    if (!nodes) nodes = 100000;
    if (!bytes) bytes = 8 * 1024 * 1024;
    initial = nodes;
    if (d && mulib_xml_name(d) && !strcmp(mulib_xml_name(d), "docstril") &&
        mulib_xml_attr(d, "version") && !strcmp(mulib_xml_attr(d, "version"), "1"))
        ok = mulib_docstril_check_(d, 0, &nodes, &bytes, &message);
    if (e) { e->offset = initial - nodes; e->message = ok ? NULL : message; }
    return ok;
}
