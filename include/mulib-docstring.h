/** DocstrIL revision 1 is an XML-compatible, owned semantic tree, not source
 * markup. Root: <docstril version="1">. Text nodes contain literal Unicode.
 * Blocks: paragraph, heading(level=1..6,id), blockquote, list(ordered=true/false),
 * item, code-block(language), table/row/cell(header=true/false), rule, figure,
 * directive(name,argument), toc, index, index-entry(term,id).
 * Inlines: strong, emphasis, underline, strike, code, link(href), image(src,alt),
 * superscript, subscript, span, break, and extension-defined element names.
 * Attributes preserve metadata and computed CSS in style. Graph/diagram figures
 * contain real SVG. Unknown names are preserved, never executed by the IR.
 * All edits use mulib_xml_*; successful append transfers subtree ownership.
 */
typedef mulib_dsdom_t mulib_docstril_t;
enum { MULIB_DOCSTRIL_VERSION = 1, MULIB_DOCSTRIL_MAX_DEPTH = 96 };
/** Allocate an empty, owned revision-1 document root. */
mulib_docstril_t *mulib_docstril_create(void);
/** Validate root/version, heading levels, list/table shape and bounded XML
 * contents (elements/text only). Zero limits select 100000 nodes/8 MiB text.
 * 1/0; static diagnostic, offset is a preorder node index. */
int mulib_docstril_validate(const mulib_docstril_t *document, size_t node_limit,
                           size_t byte_limit, mulib_xml_error_t *error);
typedef struct mulib_docstrings mulib_docstrings_t;
typedef enum mulib_docstrings_status {
    MULIB_DOCSTRINGS_OK, MULIB_DOCSTRINGS_INVALID, MULIB_DOCSTRINGS_SYNTAX,
    MULIB_DOCSTRINGS_LIMIT, MULIB_DOCSTRINGS_MEMORY, MULIB_DOCSTRINGS_LUA,
    MULIB_DOCSTRINGS_IO, MULIB_DOCSTRINGS_POLICY
} mulib_docstrings_status_t;
/** Diagnostic owns its strings. offset is zero-based; line/column one-based
 * byte coordinates in source (or an included/expanded fragment named source). */
typedef struct mulib_docstrings_error {
    mulib_docstrings_status_t code;
    size_t offset, line, column;
    char source[128], message[256];
} mulib_docstrings_error_t;
/** Host-controlled I/O; append UTF-8 bytes to out and return nonzero.
 * path/format/command and out are borrowed only for the call. No reentrant
 * operations on the same compiler. NULL callbacks disable the capability.
 * A failing callback's partial buffer is discarded. Enforce path/command policy
 * here; the library never opens files or spawns processes on its own. */
typedef int (*mulib_docstrings_load_fn)(void *user, const char *path, const char *format, mulib_strbuf_t *out);
typedef int (*mulib_docstrings_exec_fn)(void *user, const char *command, mulib_strbuf_t *out);
enum { MULIB_DOCSTRINGS_TRUSTED_LUA = 1u };
typedef struct mulib_docstrings_options {
    /** Zero selects 1 MiB source, 8 MiB cumulative generated bytes, 100000
     * constructed nodes, 1000000 work units, depth 64, include depth 16.
     * Nonzero values may lower, not raise, these limits. */
    size_t source_bytes, output_bytes, nodes, steps, depth, include_depth;
    mulib_docstrings_load_fn load;
    mulib_docstrings_exec_fn exec;
    void *user;
    /** Default Lua removes OS/file/package/debug/loading facilities. This is
     * capability reduction, not a security sandbox. TRUSTED_LUA retains Mune's
     * standard libraries. Lua runtime limits are independent of IR limits. */
    unsigned flags;
    mulib_mune_runtime_options_t lua;
} mulib_docstrings_options_t;
/** Independent reusable compiler. NULL on invalid limits/allocation failure.
 * Language macros are document-local; Lua registrations persist across calls.
 * Objects require external synchronization and cannot be reentered. */
mulib_docstrings_t *mulib_docstrings_create(const mulib_docstrings_options_t *options);
void mulib_docstrings_destroy(mulib_docstrings_t *compiler);
/** Compile copied semantic nodes from borrowed source. format is docstrings,
 * markdown, asciidoc or lua (NULL means docstrings). NULL source allowed at zero
 * length. On failure no partial IR escapes; Lua side effects are not rolled back.
 * The caller owns the returned DocstrIL element and uses mulib_xml_destroy. */
mulib_docstril_t *mulib_docstrings_compile(mulib_docstrings_t *compiler, const char *source,
    size_t length, const char *format, mulib_docstrings_error_t *error);
/** Run extension registrations in the persistent Mune state. ldocstr and
 * ldocstr.style are installed automatically. Return status; no IR is returned. */
mulib_docstrings_status_t mulib_docstrings_extend(mulib_docstrings_t *compiler,
    const char *source, size_t length, mulib_docstrings_error_t *error);
/** Borrow the lazily initialized Mune state, or NULL. Do not destroy it.
 * It must not outlive its compiler. Native bindings remain caller-controlled. */
mulib_mune_state_t *mulib_docstrings_lua(mulib_docstrings_t *compiler, mulib_docstrings_error_t *error);
/** A Lua filter chunk returns a function (document/tokens/events mode) or a
 * handler table (walk mode, Pandoc-like names). Default mode is walk.
 * Success atomically replaces *document and destroys the old tree. Failure
 * leaves it untouched. Filters operate on a detached Lua snapshot, never C
 * pointers; malformed/cyclic results fail bounded validation. */
mulib_docstrings_status_t mulib_docstrings_filter(mulib_docstrings_t *compiler,
    mulib_docstril_t **document, const char *source, size_t length,
    const char *mode, mulib_docstrings_error_t *error);
/** Apply CSS, selector->declaration JSON/YAML, or a Lua document filter.
 * Atomically replace *document on success. No stylesheet fetching occurs. */
mulib_docstrings_status_t mulib_docstrings_style(mulib_docstrings_t *compiler,
    mulib_docstril_t **document, const char *source, size_t length,
    const char *format, mulib_docstrings_error_t *error);
/** Serialize validated IR as xml (default), html, or pandoc (JSON).
 * malloc-owned NUL-terminated output; length excludes NUL, zero on failure.
 * For other outputs use mulib_tas_from_dom, mulib_xtas_stream and
 * mulib_dsdom_clone directly; Lua exposes all six representations. */
char *mulib_docstrings_render(const mulib_docstril_t *document, const char *format,
    size_t *length, mulib_docstrings_error_t *error);
