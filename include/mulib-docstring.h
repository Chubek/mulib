static int mulib_docstrings_parse_(mulib_docstrings_parser_ *, mulib_dsdom_t *, const char *, size_t, const char *);
static int mulib_docstrings_inline_(mulib_docstrings_parser_ *, mulib_dsdom_t *, const char *, size_t);
static int mulib_docstrings_finalize_(mulib_docstrings_parser_ *, mulib_docstril_t *);
static int mulib_docstrings_lua_init_(mulib_docstrings_parser_ *);
static int mulib_docstrings_style_(mulib_docstrings_parser_ *, mulib_docstril_t *, const char *, size_t, const char *);
static int mulib_docstrings_fail_(mulib_docstrings_parser_ *p, mulib_docstrings_status_t code, const char *message) {
    if (!p->error.code) {
        size_t i;
        p->error.code = code; p->error.offset = p->offset;
        p->error.line = p->error.column = 1;
        for (i = 0; i < p->offset && i < p->length; ++i) {
            if (p->source[i] == '\n') { ++p->error.line; p->error.column = 1; }
            else ++p->error.column;
        }
        (void)snprintf(p->error.source,sizeof p->error.source,"%s",p->origin ? p->origin : "<input>");
        (void)snprintf(p->error.message,sizeof p->error.message,"%s",message ? message : "operation failed");
    }
    return 0;
}
static void mulib_docstrings_start_(mulib_docstrings_parser_ *p, mulib_docstrings_t *ctx) {
    memset(p,0,sizeof *p); p->ctx = ctx; p->origin = "<input>";
}
static int mulib_docstrings_work_(mulib_docstrings_parser_ *p, size_t n) {
    if (n > p->ctx->options.steps - p->steps) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"Docstrings work limit");
    p->steps += n; return 1;
}
static int mulib_docstrings_bytes_(mulib_docstrings_parser_ *p, size_t n) {
    if (n > p->ctx->options.output_bytes - p->bytes) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"Docstrings generated-byte limit");
    p->bytes += n; return 1;
}
static char *mulib_docstrings_copy_(const char *s, size_t n) {
    char *out;
    if ((!s && n) || n == SIZE_MAX) return NULL;
    out = (char *)malloc(n+1);
    if (out) { if (n) memcpy(out,s,n); out[n] = 0; }
    return out;
}
static int mulib_docstrings_space_(char c) { return c == ' ' || c == '\t' || c == '\r' || c == '\n'; }
static int mulib_docstrings_ident_(char c, int first) {
    return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || c == '_' ||
        (!first && ((c >= '0' && c <= '9') || c == '-'));
}
static void mulib_docstrings_trim_(const char **s, size_t *n) {
    while (*n && mulib_docstrings_space_(**s)) { ++*s; --*n; }
    while (*n && mulib_docstrings_space_((*s)[*n-1])) --*n;
}
static int mulib_docstrings_equal_(const char *s, size_t n, const char *word) {
    return n == strlen(word) && !memcmp(s,word,n);
}
static mulib_dsdom_t *mulib_docstrings_node_(mulib_docstrings_parser_ *p, mulib_dsdom_t *parent, const char *name) {
    mulib_dsdom_t *n;
    if (p->nodes == p->ctx->options.nodes || !mulib_docstrings_work_(p,1) || !mulib_docstrings_bytes_(p,strlen(name))) {
        (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"DocstrIL node limit"); return NULL;
    }
    ++p->nodes; n = mulib_dsdom_element(name,NULL);
    if (!n) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"element allocation/invalid name"); return NULL; }
    if (parent && !mulib_xml_append(parent,n)) {
        mulib_xml_destroy(n); (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_INVALID,"invalid tree append"); return NULL;
    }
    return n;
}
static int mulib_docstrings_text_(mulib_docstrings_parser_ *p, mulib_dsdom_t *parent, const char *s, size_t length) {
    mulib_dsdom_t *n;
    char *text;
    if (!length) return 1;
    if (p->nodes == p->ctx->options.nodes || !mulib_docstrings_work_(p,1) || !mulib_docstrings_bytes_(p,length))
        return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"DocstrIL node/byte limit");
    if (!mulib_xml_valid_text(s,length)) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_INVALID,"invalid UTF-8/XML text");
    ++p->nodes; text = mulib_docstrings_copy_(s,length);
    n = text ? mulib_xml_new(MULIB_XML_TEXT,text) : NULL; free(text);
    if (!n) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"text allocation failure");
    if (!mulib_xml_append(parent,n)) { mulib_xml_destroy(n); return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_INVALID,"invalid text parent"); }
    return 1;
}
static int mulib_docstrings_attr_(mulib_docstrings_parser_ *p, mulib_dsdom_t *n, const char *key, const char *value) {
    if (!mulib_docstrings_work_(p,1) || !mulib_docstrings_bytes_(p,strlen(key)) || !mulib_docstrings_bytes_(p,strlen(value))) return 0;
    if (!mulib_xml_set_attr(n,key,value)) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"attribute allocation/invalid value");
    return 1;
}
static int mulib_docstrings_lua_error_(mulib_docstrings_parser_ *p, const mulib_mune_error_t *e) {
    return mulib_docstrings_fail_(p,e->code == MULIB_MUNE_LIMIT ? MULIB_DOCSTRINGS_LIMIT :
        e->code == MULIB_MUNE_MEMORY ? MULIB_DOCSTRINGS_MEMORY : MULIB_DOCSTRINGS_LUA,e->message);
}
static int mulib_docstrings_raw_(mulib_mune_state_t *s, mulib_mune_value_t table, const char *key, mulib_mune_value_t *out) {
    mulib_mune_value_t k;
    return mulib_mune_make_string(s,key,strlen(key),&k) == MULIB_MUNE_OK && mulib_mune_raw_get(s,table,k,out) == MULIB_MUNE_OK;
}
static int mulib_docstrings_put_(mulib_mune_state_t *s, mulib_mune_value_t table, const char *key, mulib_mune_value_t value) {
    mulib_mune_value_t k;
    return mulib_mune_make_string(s,key,strlen(key),&k) == MULIB_MUNE_OK && mulib_mune_raw_set(s,table,k,value) == MULIB_MUNE_OK;
}
static int mulib_docstrings_puts_(mulib_mune_state_t *s, mulib_mune_value_t table, const char *key, const char *text) {
    mulib_mune_value_t v;
    return mulib_mune_make_string(s,text,strlen(text),&v) == MULIB_MUNE_OK && mulib_docstrings_put_(s,table,key,v);
}
static const char *mulib_docstrings_string_(mulib_mune_value_t v) {
    size_t n;
    const char *s = mulib_mune_value_string(v,&n);
    return s && !memchr(s,0,n) && mulib_xml_valid_text(s,n) ? s : NULL;
}
static int mulib_docstrings_to_lua_(mulib_mune_state_t *s, const mulib_dsdom_t *n, mulib_mune_value_t *out, unsigned depth) {
    mulib_mune_value_t table, attrs, list, child, v, k;
    const mulib_dsdom_t *c;
    size_t i;
    if (depth > MULIB_DOCSTRIL_MAX_DEPTH || mulib_mune_make_table(s,&table)) return 0;
    if (!mulib_docstrings_puts_(s,table,"t",mulib_xml_name(n) ? mulib_xml_name(n) : "Text")) return 0;
    if (!mulib_xml_name(n)) {
        if (!mulib_docstrings_puts_(s,table,"text",mulib_xml_value(n))) return 0;
    } else {
        if (mulib_mune_make_table(s,&attrs) || !mulib_docstrings_put_(s,table,"attrs",attrs) ||
            mulib_mune_make_table(s,&list) || !mulib_docstrings_put_(s,table,"children",list)) return 0;
        for (i = 0; i < mulib_xml_attr_count(n); ++i) {
            if (mulib_mune_make_string(s,mulib_xml_attr_name(n,i),strlen(mulib_xml_attr_name(n,i)),&k) ||
                mulib_mune_make_string(s,mulib_xml_attr_value(n,i),strlen(mulib_xml_attr_value(n,i)),&v) || mulib_mune_raw_set(s,attrs,k,v)) return 0;
        }
        i = 0;
        for (c = mulib_xml_first(n); c; c = mulib_xml_next(c)) {
            if (!mulib_docstrings_to_lua_(s,c,&child,depth+1) || mulib_mune_raw_set(s,list,mulib_mune_integer((int64_t)++i),child)) return 0;
        }
    }
    *out = table; return 1;
}
static int mulib_docstrings_array_(mulib_docstrings_parser_ *p, mulib_mune_value_t table, size_t *length) {
    size_t cursor = 0, count = 0, max = 0;
    mulib_mune_value_t key, value;
    int next;
    if (table.type != MULIB_MUNE_TABLE) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LUA,"expected dense IR array");
    while ((next = mulib_mune_table_next(p->ctx->lua,table,&cursor,&key,&value)) == 1) {
        if (!mulib_docstrings_work_(p,1) || key.type != MULIB_MUNE_INTEGER || key.as.integer < 1 ||
            (uint64_t)key.as.integer > p->ctx->options.nodes * 16u)
            return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LUA,"invalid IR array index");
        ++count; if ((size_t)key.as.integer > max) max = (size_t)key.as.integer;
    }
    if (next < 0 || count != max) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LUA,"sparse IR array");
    *length = count; return 1;
}
static mulib_dsdom_t *mulib_docstrings_from_lua_(mulib_docstrings_parser_ *p, mulib_mune_value_t table, unsigned depth) {
    mulib_mune_state_t *s = p->ctx->lua;
    mulib_mune_value_t t, attrs, list, k, v;
    mulib_dsdom_t *n = NULL, *child;
    const char *name, *key, *value;
    size_t cursor = 0, count, i;
    int next;
    if (depth > p->ctx->options.depth || !mulib_docstrings_work_(p,1)) {
        (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"Lua IR nesting limit"); return NULL;
    }
    if (!mulib_docstrings_raw_(s,table,"t",&t) || !(name = mulib_docstrings_string_(t))) goto invalid;
    if (!strcmp(name,"Text")) {
        if (!mulib_docstrings_raw_(s,table,"text",&v) || !(value = mulib_docstrings_string_(v))) goto invalid;
        if (p->nodes == p->ctx->options.nodes || !mulib_docstrings_bytes_(p,strlen(value))) goto limit;
        ++p->nodes; n = mulib_xml_new(MULIB_XML_TEXT,value);
        if (!n) (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"Lua text allocation");
        return n;
    }
    if (!mulib_xml_valid_name(name)) goto invalid;
    n = mulib_docstrings_node_(p,NULL,name); if (!n) return NULL;
    if (!mulib_docstrings_raw_(s,table,"attrs",&attrs)) goto invalid;
    if (attrs.type != MULIB_MUNE_NIL) {
        if (attrs.type != MULIB_MUNE_TABLE) goto invalid;
        while ((next = mulib_mune_table_next(s,attrs,&cursor,&k,&v)) == 1) {
            key = mulib_docstrings_string_(k); value = mulib_docstrings_string_(v);
            if (!key || !value || !mulib_xml_valid_name(key)) goto invalid;
            if (!mulib_docstrings_attr_(p,n,key,value)) goto fail;
        }
        if (next < 0) goto invalid;
    }
    if (!mulib_docstrings_raw_(s,table,"children",&list)) goto invalid;
    if (list.type != MULIB_MUNE_NIL) {
        if (!mulib_docstrings_array_(p,list,&count)) goto fail;
        for (i = 1; i <= count; ++i) {
            if (mulib_mune_raw_get(s,list,mulib_mune_integer((int64_t)i),&v)) goto invalid;
            child = mulib_docstrings_from_lua_(p,v,depth+1); if (!child) goto fail;
            if (!mulib_xml_append(n,child)) { mulib_xml_destroy(child); goto invalid; }
        }
    }
    return n;
invalid:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LUA,"invalid DocstrIL node/attribute from Lua"); goto fail;
limit:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"Lua IR node/byte limit");
fail:
    mulib_xml_destroy(n); return NULL;
}
static int mulib_docstrings_json_lua_(mulib_mune_state_t *s, const mulib_json_t *j, mulib_mune_value_t *out, unsigned depth) {
    mulib_mune_value_t t, k, v;
    size_t i, length;
    const char *text;
    if (depth > 128) return 0;
    switch (mulib_json_typeof(j)) {
    case MULIB_JSON_NULL:
        return mulib_mune_get_global(s,"ldocstr",&t) == MULIB_MUNE_OK && mulib_docstrings_raw_(s,t,"null",out);
    case MULIB_JSON_BOOL: *out = mulib_mune_boolean(mulib_json_boolean(j)); return 1;
    case MULIB_JSON_NUMBER: *out = mulib_mune_number(mulib_json_numeric(j)); return 1;
    case MULIB_JSON_STRING:
        text = mulib_json_text(j,&length); return mulib_mune_make_string(s,text,length,out) == MULIB_MUNE_OK;
    case MULIB_JSON_ARRAY: case MULIB_JSON_OBJECT:
        if (mulib_mune_make_table(s,&t)) return 0;
        for (i = 0; i < mulib_json_size(j); ++i) {
            if (mulib_json_typeof(j) == MULIB_JSON_ARRAY) k = mulib_mune_integer((int64_t)i+1);
            else {
                text = mulib_json_key(j,i,&length);
                if (mulib_mune_make_string(s,text,length,&k)) return 0;
            }
            if (!mulib_docstrings_json_lua_(s,mulib_json_at(j,i),&v,depth+1) || mulib_mune_raw_set(s,t,k,v)) return 0;
        }
        *out = t; return 1;
    }
    return 0;
}
static void mulib_docstrings_macros_free_(mulib_docstrings_macro_ *m) {
    while (m) {
        mulib_docstrings_macro_ *next = m->next; size_t i;
        free(m->name); free(m->body);
        for (i = 0; i < m->count; ++i) free(m->parameters[i]);
        free(m); m = next;
    }
}
typedef struct mulib_docstrings_style_pending_ {
    struct mulib_docstrings_style_pending_ *next;
    mulib_dsdom_t *node;
    char *text;
} mulib_docstrings_style_pending_;
static int mulib_docstrings_style_collect_(mulib_docstrings_parser_ *p, mulib_dsdom_t *n,
    const mulib_css_sheet_t *sheet, mulib_docstrings_style_pending_ **pending, unsigned depth) {
    mulib_css_style_t *in = NULL, *resolved;
    mulib_docstrings_style_pending_ *item;
    mulib_xml_error_t error;
    mulib_dsdom_t *c;
    const char *text;
    if (depth > MULIB_DOCSTRIL_MAX_DEPTH || !mulib_docstrings_work_(p,mulib_css_rule_count(sheet)+1))
        return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"stylesheet work/depth limit");
    if (mulib_xml_name(n)) {
        text = mulib_xml_attr(n,"style");
        if (text) { in = mulib_css_parse_declarations(text,strlen(text),&error); if (!in) goto css_error; }
        resolved = mulib_css_cascade(sheet,n,in,&error); mulib_css_style_destroy(in); in = NULL;
        if (!resolved) goto css_error;
        if (mulib_css_count(resolved)) {
            item = (mulib_docstrings_style_pending_ *)calloc(1,sizeof *item);
            if (!item) { mulib_css_style_destroy(resolved); return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"stylesheet allocation"); }
            item->text = mulib_css_serialize_declarations(resolved);
            if (!item->text) { free(item); mulib_css_style_destroy(resolved); return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"stylesheet serialization"); }
            item->node = n; item->next = *pending; *pending = item;
        }
        mulib_css_style_destroy(resolved);
    }
    for (c = mulib_xml_first(n); c; c = mulib_xml_next(c))
        if (!mulib_docstrings_style_collect_(p,c,sheet,pending,depth+1)) return 0;
    return 1;
css_error:
    mulib_css_style_destroy(in); return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,error.message);
}
static int mulib_docstrings_config_css_(mulib_docstrings_parser_ *p, const mulib_json_t *root, mulib_strbuf_t *css) {
    size_t i, j, length;
    const char *selector, *key, *value;
    const mulib_json_t *decl, *v;
    char *number;
    if (mulib_json_typeof(root) != MULIB_JSON_OBJECT) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"stylesheet must map selectors to declarations");
    for (i = 0; i < mulib_json_size(root); ++i) {
        selector = mulib_json_key(root,i,&length); decl = mulib_json_at(root,i);
        if (!selector || memchr(selector,0,length) || strpbrk(selector,"{}") || mulib_css_matches(NULL,selector) < 0 ||
            mulib_json_typeof(decl) != MULIB_JSON_OBJECT) goto invalid;
        if (!mulib_strbuf_append(css,selector) || !mulib_strbuf_putc(css,'{')) goto memory;
        for (j = 0; j < mulib_json_size(decl); ++j) {
            size_t k;
            key = mulib_json_key(decl,j,&length); v = mulib_json_at(decl,j); number = NULL;
            if (!key || !length || memchr(key,0,length)) goto invalid;
            for (k = 0; k < length; ++k) if (!mulib_docstrings_ident_(key[k],0)) goto invalid;
            if (mulib_json_typeof(v) == MULIB_JSON_STRING) {
                value = mulib_json_text(v,&length);
                if (memchr(value,0,length)) goto invalid;
            } else if (mulib_json_typeof(v) == MULIB_JSON_NUMBER) {
                number = mulib_json_stringify(v,0); if (!number) goto memory; value = number;
            } else goto invalid;
            if (strpbrk(value,";{}") || !mulib_xml_valid_text(value,strlen(value))) { free(number); goto invalid; }
            if (!mulib_strbuf_append(css,key) || !mulib_strbuf_putc(css,':') ||
                !mulib_strbuf_append(css,value) || !mulib_strbuf_putc(css,';')) { free(number); goto memory; }
            free(number);
            if (!mulib_docstrings_work_(p,1) || css->length > p->ctx->options.output_bytes) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"stylesheet size limit");
        }
        if (!mulib_strbuf_putc(css,'}')) goto memory;
    }
    return 1;
invalid:
    return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"invalid selector/declaration stylesheet mapping");
memory:
    return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"stylesheet allocation");
}
static int mulib_docstrings_stylesource_(mulib_docstrings_parser_ *p, const char *source, size_t length, const char *format, mulib_strbuf_t *out) {
    mulib_json_t *config;
    mulib_json_error_t je;
    mulib_yaml_error_t ye;
    int ok;
    if (!format || !strcmp(format,"css")) {
        if (mulib_strbuf_append_n(out,source,length) && mulib_strbuf_putc(out,'\n')) return 1;
        return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"stylesheet source allocation");
    }
    if (!strcmp(format,"json")) {
        config = mulib_json_parse(source,length,&je);
        if (!config) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,je.message);
    } else if (!strcmp(format,"yaml")) {
        config = mulib_yaml_parse(source,length,&ye);
        if (!config) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,ye.message);
    } else return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_INVALID,"unknown stylesheet format");
    ok = mulib_docstrings_config_css_(p,config,out); mulib_json_destroy(config); return ok;
}
static int mulib_docstrings_style_(mulib_docstrings_parser_ *p, mulib_docstril_t *root, const char *source, size_t length, const char *format) {
    mulib_css_sheet_t *sheet = NULL;
    mulib_json_t *config = NULL;
    mulib_json_error_t je;
    mulib_yaml_error_t ye;
    mulib_xml_error_t xe;
    mulib_strbuf_t css;
    mulib_docstrings_style_pending_ *pending = NULL, *item;
    size_t i;
    int ok = 0;
    mulib_strbuf_init(&css);
    if (!format || !strcmp(format,"css")) { sheet = mulib_css_parse(source,length,&xe); if (!sheet) goto css_error; }
    else {
        if (!strcmp(format,"json")) {
            config = mulib_json_parse(source,length,&je);
            if (!config) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,je.message); goto done; }
        } else if (!strcmp(format,"yaml")) {
            config = mulib_yaml_parse(source,length,&ye);
            if (!config) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,ye.message); goto done; }
        } else { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_INVALID,"unknown stylesheet format"); goto done; }
        if (!mulib_docstrings_config_css_(p,config,&css)) goto done;
        sheet = mulib_css_parse(css.data,css.length,&xe); if (!sheet) goto css_error;
    }
    for (i = 0; i < mulib_css_rule_count(sheet); ++i)
        if (mulib_css_matches(NULL,mulib_css_selector(sheet,i)) < 0) {
            (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unsupported stylesheet selector"); goto done;
        }
    if (!mulib_docstrings_style_collect_(p,root,sheet,&pending,0)) goto done;
    for (item = pending; item; item = item->next)
        if (!mulib_docstrings_attr_(p,item->node,"style",item->text)) goto done;
    ok = 1; goto done;
css_error:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,xe.message);
done:
    while (pending) { item = pending->next; free(pending->text); free(pending); pending = item; }
    mulib_css_destroy(sheet); mulib_json_destroy(config); mulib_strbuf_free(&css); return ok;
}
static int mulib_docstrings_tokens_lua_(mulib_mune_state_t *s, const mulib_dsdom_t *root, mulib_mune_value_t *out) {
    mulib_tas_t *tokens = mulib_tas_from_dom(root);
    mulib_mune_value_t list, item;
    size_t i;
    int ok = 0;
    static const char *const names[] = { "open", "attribute", "text", "close" };
    if (!tokens || mulib_mune_make_table(s,&list)) goto done;
    for (i = 0; i < mulib_tas_count(tokens); ++i) {
        const mulib_tas_token_t *t = mulib_tas_at(tokens,i);
        if (mulib_mune_make_table(s,&item) || !mulib_docstrings_puts_(s,item,"kind",names[t->kind]) ||
            (t->name && !mulib_docstrings_puts_(s,item,"name",t->name)) ||
            (t->value && !mulib_docstrings_puts_(s,item,"value",t->value)) ||
            mulib_mune_raw_set(s,list,mulib_mune_integer((int64_t)i+1),item)) goto done;
    }
    *out = list; ok = 1;
done:
    mulib_tas_destroy(tokens); return ok;
}
static mulib_dsdom_t *mulib_docstrings_tokens_dom_(mulib_docstrings_parser_ *p, mulib_mune_value_t list) {
    mulib_tas_t *tokens = mulib_tas_create();
    mulib_mune_value_t item, v;
    size_t count, i;
    const char *kind, *name, *value;
    mulib_tas_kind_t type;
    mulib_xml_error_t error;
    mulib_dsdom_t *root = NULL;
    if (!tokens) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"token allocation"); return NULL; }
    if (!mulib_docstrings_array_(p,list,&count)) goto done;
    for (i = 1; i <= count; ++i) {
        if (mulib_mune_raw_get(p->ctx->lua,list,mulib_mune_integer((int64_t)i),&item) ||
            !mulib_docstrings_raw_(p->ctx->lua,item,"kind",&v) || !(kind = mulib_docstrings_string_(v))) goto invalid;
        if (!strcmp(kind,"open")) type = MULIB_TAS_OPEN;
        else if (!strcmp(kind,"close")) type = MULIB_TAS_CLOSE;
        else if (!strcmp(kind,"attribute")) type = MULIB_TAS_ATTRIBUTE;
        else if (!strcmp(kind,"text")) type = MULIB_TAS_TEXT;
        else goto invalid;
        if (!mulib_docstrings_raw_(p->ctx->lua,item,"name",&v)) goto invalid;
        name = v.type == MULIB_MUNE_NIL ? NULL : mulib_docstrings_string_(v);
        if (v.type != MULIB_MUNE_NIL && !name) goto invalid;
        if (!mulib_docstrings_raw_(p->ctx->lua,item,"value",&v)) goto invalid;
        value = v.type == MULIB_MUNE_NIL ? NULL : mulib_docstrings_string_(v);
        if (v.type != MULIB_MUNE_NIL && !value) goto invalid;
        if (!mulib_docstrings_bytes_(p,(name ? strlen(name) : 0) + (value ? strlen(value) : 0))) goto done;
        if (!mulib_tas_push(tokens,type,name,value)) goto invalid;
    }
    root = mulib_tas_to_dom(tokens,&error);
    if (!root) (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LUA,error.message);
    goto done;
invalid:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LUA,"invalid token returned by Lua");
done:
    mulib_tas_destroy(tokens); return root;
}
static mulib_mune_status_t mulib_docstrings_native_(mulib_mune_state_t *s, const mulib_mune_value_t *args,
    size_t count, mulib_mune_result_t *out, void *user, int operation) {
    mulib_docstrings_t *ctx = (mulib_docstrings_t *)user;
    mulib_docstrings_parser_ local, *p = ctx->active;
    mulib_dsdom_t *root = NULL;
    mulib_json_t *json = NULL;
    mulib_mune_value_t result = mulib_mune_nil();
    const char *source = NULL, *format = NULL;
    size_t length = 0;
    char *text = NULL;
    int own = !p, ok = 0;
    if (own) { mulib_docstrings_start_(&local,ctx); p = &local; ctx->active = p; ctx->busy = 1; }
    if (operation == 4) {
        source = count == 1 ? mulib_docstrings_string_(args[0]) : NULL;
        if (!source || (strcmp(source,"ldocstr") && strcmp(source,"ldocstr.ldstr-style") && strcmp(source,"ldstr-style"))) goto invalid;
        if (mulib_mune_get_global(s,"ldocstr",&result)) goto invalid;
        if (strcmp(source,"ldocstr") && !mulib_docstrings_raw_(s,result,"style",&result)) goto invalid;
        ok = 1; goto done;
    }
    if (!count) goto invalid;
    if (operation == 0) {
        source = mulib_mune_value_string(args[0],&length);
        format = count > 1 ? mulib_docstrings_string_(args[1]) : "docstrings";
        if (!source || !format) goto invalid;
        root = mulib_docstril_create();
        if (!root) goto memory;
        if (!mulib_docstrings_parse_(p,root,source,length,format) || !mulib_docstrings_finalize_(p,root)) goto done;
        ok = mulib_docstrings_to_lua_(s,root,&result,0);
    } else if (operation == 2) {
        root = mulib_docstrings_tokens_dom_(p,args[0]); if (!root) goto done;
        ok = mulib_docstrings_to_lua_(s,root,&result,0);
    } else {
        root = mulib_docstrings_from_lua_(p,args[0],0); if (!root) goto done;
        if (operation == 3) {
            if (count < 2 || !(source = mulib_mune_value_string(args[1],&length))) goto invalid;
            format = count > 2 ? mulib_docstrings_string_(args[2]) : "css";
            if (!format || !mulib_docstrings_style_(p,root,source,length,format)) goto done;
            ok = mulib_docstrings_to_lua_(s,root,&result,0);
        } else {
            if (count < 2 || !(format = mulib_docstrings_string_(args[1]))) goto invalid;
            if (!strcmp(format,"tokens")) ok = mulib_docstrings_tokens_lua_(s,root,&result);
            else if (!strcmp(format,"pandoc")) {
                json = mulib_pandocast_from_docstril(root,NULL);
                ok = json && mulib_docstrings_json_lua_(s,json,&result,0);
            } else {
                mulib_docstrings_error_t render_error;
                text = mulib_docstrings_render(root,format,&length,&render_error);
                if (!text) (void)mulib_docstrings_fail_(p,render_error.code,render_error.message);
                ok = text && mulib_mune_make_string(s,text,length,&result) == MULIB_MUNE_OK;
            }
        }
    }
    if (!ok && !p->error.code) goto memory;
    goto done;
invalid:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LUA,"invalid ldocstr arguments/module name"); goto done;
memory:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"Lua bridge allocation/conversion failure");
done:
    if (ok && !mulib_mune_result_push(out,result)) ok = 0;
    mulib_xml_destroy(root); mulib_json_destroy(json); free(text);
    if (own) { mulib_docstrings_macros_free_(p->macros); ctx->active = NULL; ctx->busy = 0; }
    return ok ? MULIB_MUNE_OK : MULIB_MUNE_RUNTIME;
}
static mulib_mune_status_t mulib_docstrings_native_parse_(mulib_mune_state_t *s, const mulib_mune_value_t *a, size_t n, mulib_mune_result_t *r, void *u) { return mulib_docstrings_native_(s,a,n,r,u,0); }
static mulib_mune_status_t mulib_docstrings_native_output_(mulib_mune_state_t *s, const mulib_mune_value_t *a, size_t n, mulib_mune_result_t *r, void *u) { return mulib_docstrings_native_(s,a,n,r,u,1); }
static mulib_mune_status_t mulib_docstrings_native_tokens_(mulib_mune_state_t *s, const mulib_mune_value_t *a, size_t n, mulib_mune_result_t *r, void *u) { return mulib_docstrings_native_(s,a,n,r,u,2); }
static mulib_mune_status_t mulib_docstrings_native_style_(mulib_mune_state_t *s, const mulib_mune_value_t *a, size_t n, mulib_mune_result_t *r, void *u) { return mulib_docstrings_native_(s,a,n,r,u,3); }
static mulib_mune_status_t mulib_docstrings_native_require_(mulib_mune_state_t *s, const mulib_mune_value_t *a, size_t n, mulib_mune_result_t *r, void *u) { return mulib_docstrings_native_(s,a,n,r,u,4); }
static int mulib_docstrings_bootstrap_(mulib_docstrings_parser_ *p, const char *const *parts, size_t count, const char *global) {
    mulib_strbuf_t b;
    mulib_mune_result_t *r = NULL;
    mulib_mune_error_t e;
    size_t i;
    int ok = 0;
    mulib_strbuf_init(&b);
    for (i = 0; i < count; ++i) if (!mulib_strbuf_append(&b,parts[i])) goto done;
    if (mulib_mune_run_source(p->ctx->lua,b.data,b.length,&r,&e)) { (void)mulib_docstrings_lua_error_(p,&e); goto done; }
    if (global && mulib_mune_set_global(p->ctx->lua,global,mulib_mune_result_get(r,0))) goto done;
    ok = 1;
done:
    mulib_strbuf_free(&b); mulib_mune_result_destroy(r);
    if (!ok && !p->error.code) (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"ldocstr initialization allocation");
    return ok;
}
static int mulib_docstrings_lua_init_(mulib_docstrings_parser_ *p) {
    mulib_docstrings_t *ctx = p->ctx;
    mulib_mune_state_t *s;
    mulib_mune_value_t package, loaded, module, style;
    static const char *const disabled[] = { "io", "os", "debug", "package", "load", "loadfile", "dofile", "require", "print", "warn" };
    size_t i;
    if (ctx->lua) return 1;
    ctx->lua = mulib_mune_state_create(&ctx->options.lua); s = ctx->lua;
    if (!s) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"Mune state allocation");
    if (!(ctx->options.flags & MULIB_DOCSTRINGS_TRUSTED_LUA))
        for (i = 0; i < sizeof disabled / sizeof disabled[0]; ++i)
            if (mulib_mune_set_global(s,disabled[i],mulib_mune_nil())) goto fail;
    if (mulib_mune_bind(s,"_ldocstr_parse",mulib_docstrings_native_parse_,ctx) ||
        mulib_mune_bind(s,"_ldocstr_output",mulib_docstrings_native_output_,ctx) ||
        mulib_mune_bind(s,"_ldocstr_from_tokens",mulib_docstrings_native_tokens_,ctx) ||
        mulib_mune_bind(s,"_ldocstr_style",mulib_docstrings_native_style_,ctx)) goto fail;
    if (!mulib_docstrings_bootstrap_(p,mulib_docstrings_core_source_,sizeof mulib_docstrings_core_source_/sizeof mulib_docstrings_core_source_[0],"ldocstr") ||
        !mulib_docstrings_bootstrap_(p,mulib_docstrings_style_source_,sizeof mulib_docstrings_style_source_/sizeof mulib_docstrings_style_source_[0],NULL)) goto fail;
    if (!(ctx->options.flags & MULIB_DOCSTRINGS_TRUSTED_LUA)) {
        if (mulib_mune_bind(s,"require",mulib_docstrings_native_require_,ctx)) goto fail;
    } else {
        if (mulib_mune_get_global(s,"package",&package) || !mulib_docstrings_raw_(s,package,"loaded",&loaded) ||
            mulib_mune_get_global(s,"ldocstr",&module) || !mulib_docstrings_put_(s,loaded,"ldocstr",module) ||
            !mulib_docstrings_raw_(s,module,"style",&style) || !mulib_docstrings_put_(s,loaded,"ldstr-style",style) ||
            !mulib_docstrings_put_(s,loaded,"ldocstr.ldstr-style",style)) goto fail;
    }
    return 1;
fail:
    mulib_mune_state_destroy(ctx->lua); ctx->lua = NULL;
    return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LUA,"ldocstr initialization failed");
}
static int mulib_docstrings_registry_(mulib_docstrings_parser_ *p, const char *registry, const char *name, mulib_mune_value_t *fn) {
    mulib_mune_value_t module, table;
    if (!mulib_docstrings_lua_init_(p)) return 0;
    if (mulib_mune_get_global(p->ctx->lua,"ldocstr",&module) || !mulib_docstrings_raw_(p->ctx->lua,module,registry,&table) ||
        !mulib_docstrings_raw_(p->ctx->lua,table,name,fn)) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LUA,"ldocstr registry was replaced with invalid data");
    return 1;
}
typedef struct mulib_docstrings_call_ {
    char name[64];
    char *args[16];
    size_t count;
    int function;
    const char *raw;
    size_t raw_length;
} mulib_docstrings_call_;
static void mulib_docstrings_call_free_(mulib_docstrings_call_ *c) {
    size_t i; for (i = 0; i < c->count; ++i) free(c->args[i]);
}
static char *mulib_docstrings_argument_(const char *s, size_t n) {
    char *out;
    size_t i, at = 0;
    mulib_docstrings_trim_(&s,&n);
    out = mulib_docstrings_copy_(s,n); if (!out) return NULL;
    if (n >= 2 && (s[0] == '"' || s[0] == '\'') && s[n-1] == s[0]) {
        for (i = 1; i + 1 < n; ++i) {
            char c = s[i];
            if (c == '\\' && i + 2 < n) {
                c = s[++i]; if (c == 'n') c = '\n'; else if (c == 't') c = '\t';
            }
            out[at++] = c;
        }
        out[at] = 0;
    }
    return out;
}
static int mulib_docstrings_call_parse_(mulib_docstrings_parser_ *p, const char *s, size_t n, mulib_docstrings_call_ *c) {
    size_t i = 0, start, depth = 0, k;
    char stack[64], quote = 0;
    memset(c,0,sizeof *c); mulib_docstrings_trim_(&s,&n);
    while (i < n && mulib_docstrings_ident_(s[i],i == 0)) ++i;
    if (!i || i >= sizeof c->name) goto invalid;
    memcpy(c->name,s,i); c->name[i] = 0;
    while (i < n && mulib_docstrings_space_(s[i])) ++i;
    if (i == n) return 1;
    if (s[i] != '(' || s[n-1] != ')') goto invalid;
    c->function = 1; c->raw = s+i+1; c->raw_length = n-i-2;
    start = ++i;
    for (; i + 1 < n; ++i) {
        char ch = s[i];
        if (!mulib_docstrings_work_(p,1)) goto fail;
        if (quote) {
            if (ch == '\\' && i+2 < n) ++i;
            else if (ch == quote) quote = 0;
            continue;
        }
        if (ch == '"' || ch == '\'') { quote = ch; continue; }
        if (ch == '(' || ch == '[' || ch == '{') {
            if (depth == sizeof stack) goto invalid;
            stack[depth++] = ch; continue;
        }
        if (ch == ')' || ch == ']' || ch == '}') {
            if (!depth || stack[depth-1] != (ch == ')' ? '(' : ch == ']' ? '[' : '{')) goto invalid;
            --depth; continue;
        }
        if (ch == ',' && !depth) {
            if (c->count == 16) goto invalid;
            c->args[c->count] = mulib_docstrings_argument_(s+start,i-start);
            if (!c->args[c->count]) goto memory;
            ++c->count; start = i+1;
        }
    }
    if (quote || depth) goto invalid;
    { const char *tail = s+start; size_t tailn = n-1-start; mulib_docstrings_trim_(&tail,&tailn);
      if (tailn || c->count) {
        if (c->count == 16) goto invalid;
        c->args[c->count] = mulib_docstrings_argument_(tail,tailn);
        if (!c->args[c->count]) goto memory;
        ++c->count;
      }
    }
    /* Definition sites validate argument identifiers separately. */
    for (k = 0; k < c->count; ++k)
        if (!mulib_xml_valid_text(c->args[k],strlen(c->args[k]))) goto invalid;
    return 1;
invalid:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"malformed macro name/arguments (maximum 16)"); goto fail;
memory:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"macro argument allocation");
fail:
    mulib_docstrings_call_free_(c); c->count = 0; return 0;
}
static int mulib_docstrings_define_(mulib_docstrings_parser_ *p, const char *signature, size_t n, const char *body, size_t length) {
    mulib_docstrings_call_ call;
    mulib_docstrings_macro_ *m;
    size_t i, j;
    if (!mulib_docstrings_call_parse_(p,signature,n,&call)) return 0;
    for (i = 0; i < call.count; ++i) {
        for (j = 0; call.args[i][j]; ++j) if (!mulib_docstrings_ident_(call.args[i][j],j == 0)) goto invalid;
        if (!j) goto invalid;
        for (j = 0; j < i; ++j) if (!strcmp(call.args[i],call.args[j])) goto invalid;
    }
    if (!strcmp(call.name,"exec") || !strcmp(call.name,"eval")) goto invalid;
    if (!mulib_docstrings_work_(p,1) || !mulib_docstrings_bytes_(p,length)) goto fail;
    m = (mulib_docstrings_macro_ *)calloc(1,sizeof *m); if (!m) goto memory;
    m->name = mulib_docstrings_copy_(call.name,strlen(call.name)); m->body = mulib_docstrings_copy_(body,length);
    if (!m->name || !m->body) { mulib_docstrings_macros_free_(m); goto memory; }
    m->function = call.function; m->count = call.count;
    for (i = 0; i < call.count; ++i) { m->parameters[i] = call.args[i]; call.args[i] = NULL; }
    m->next = p->macros; p->macros = m; return 1;
invalid:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"invalid/repeated/reserved macro parameter/name"); goto fail;
memory:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"macro definition allocation");
fail:
    mulib_docstrings_call_free_(&call); return 0;
}
static int mulib_docstrings_emit_lua_(mulib_docstrings_parser_ *p, mulib_dsdom_t *parent, mulib_mune_value_t v, int block) {
    mulib_mune_value_t t, item;
    mulib_dsdom_t *n, *c;
    const char *text;
    size_t count, i, length;
    char number[64];
    if (v.type == MULIB_MUNE_NIL) return 1;
    if (v.type == MULIB_MUNE_STRING) {
        text = mulib_mune_value_string(v,&length);
        return block ? mulib_docstrings_parse_(p,parent,text,length,"docstrings") : mulib_docstrings_inline_(p,parent,text,length);
    }
    if (v.type == MULIB_MUNE_INTEGER || v.type == MULIB_MUNE_NUMBER || v.type == MULIB_MUNE_BOOLEAN) {
        if (v.type == MULIB_MUNE_INTEGER) (void)snprintf(number,sizeof number,"%lld",(long long)v.as.integer);
        else if (v.type == MULIB_MUNE_NUMBER && isfinite(v.as.number)) (void)snprintf(number,sizeof number,"%.17g",v.as.number);
        else if (v.type == MULIB_MUNE_BOOLEAN) (void)snprintf(number,sizeof number,"%s",v.as.boolean ? "true" : "false");
        else return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LUA,"nonfinite macro result");
        return mulib_docstrings_text_(p,parent,number,strlen(number));
    }
    if (v.type != MULIB_MUNE_TABLE || !mulib_docstrings_raw_(p->ctx->lua,v,"t",&t))
        return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LUA,"extension must return a node, list, string or nil");
    if (t.type == MULIB_MUNE_NIL) {
        if (!mulib_docstrings_array_(p,v,&count)) return 0;
        for (i = 1; i <= count; ++i) {
            if (mulib_mune_raw_get(p->ctx->lua,v,mulib_mune_integer((int64_t)i),&item) ||
                !mulib_docstrings_work_(p,1)) return 0;
            /* Array entries must be nodes, not recursively nested lists. */
            n = mulib_docstrings_from_lua_(p,item,(unsigned)p->depth); if (!n) return 0;
            if (!mulib_xml_append(parent,n)) { mulib_xml_destroy(n); return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LUA,"invalid extension list child"); }
        }
        return 1;
    }
    n = mulib_docstrings_from_lua_(p,v,(unsigned)p->depth); if (!n) return 0;
    if (mulib_xml_name(n) && !strcmp(mulib_xml_name(n),"docstril")) {
        while ((c = mulib_xml_first(n)) != NULL) {
            mulib_xml_detach(c);
            if (!mulib_xml_append(parent,c)) { mulib_xml_destroy(c); mulib_xml_destroy(n); return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LUA,"invalid extension document"); }
        }
        mulib_xml_destroy(n); return 1;
    }
    if (!mulib_xml_append(parent,n)) { mulib_xml_destroy(n); return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LUA,"invalid extension node"); }
    return 1;
}
static int mulib_docstrings_macro_expand_(mulib_docstrings_parser_ *p, mulib_dsdom_t *parent, const char *source, size_t length, int block) {
    mulib_docstrings_call_ call;
    mulib_docstrings_macro_ *m;
    mulib_strbuf_t expanded;
    mulib_mune_value_t fn, args[16];
    mulib_mune_result_t *result = NULL, *roots = NULL;
    mulib_mune_error_t error;
    size_t i, at;
    int ok = 0;
    if (!mulib_docstrings_call_parse_(p,source,length,&call)) return 0;
    mulib_strbuf_init(&expanded);
    if (!strcmp(call.name,"exec")) {
        char *command;
        if (!call.function || !p->ctx->options.exec) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_POLICY,"exec requires an explicit host callback"); goto done; }
        command = mulib_docstrings_argument_(call.raw,call.raw_length); if (!command) goto memory;
        ok = p->ctx->options.exec(p->ctx->options.user,command,&expanded); free(command);
        if (!ok) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_IO,"host exec callback failed"); goto done; }
        ok = mulib_docstrings_text_(p,parent,expanded.data,expanded.length); goto done;
    }
    if (!strcmp(call.name,"eval")) {
        if (!call.function || !mulib_docstrings_lua_init_(p)) goto done;
        if (!mulib_strbuf_append(&expanded,"return (") || !mulib_strbuf_append_n(&expanded,call.raw,call.raw_length) || !mulib_strbuf_putc(&expanded,')')) goto memory;
        if (mulib_mune_run_source(p->ctx->lua,expanded.data,expanded.length,&result,&error)) { (void)mulib_docstrings_lua_error_(p,&error); goto done; }
        /* String eval results are literal; only macros expand returned markup. */
        fn = mulib_mune_result_get(result,0);
        if (fn.type == MULIB_MUNE_STRING) {
            size_t n; const char *s = mulib_mune_value_string(fn,&n);
            ok = mulib_docstrings_text_(p,parent,s,n);
        } else ok = mulib_docstrings_emit_lua_(p,parent,fn,block);
        goto done;
    }
    for (m = p->macros; m; m = m->next) {
        if (!mulib_docstrings_work_(p,1)) goto done;
        if (!strcmp(call.name,m->name)) break;
    }
    if (m) {
        if (m->function != call.function || m->count != call.count) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"macro arity/call form mismatch"); goto done; }
        for (at = 0; m->body[at];) {
            if (!mulib_docstrings_work_(p,1)) goto done;
            if (m->body[at] == '$' && m->body[at+1] == '{') {
                size_t end = at+2; while (m->body[end] && m->body[end] != '}') ++end;
                if (!m->body[end]) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unclosed macro parameter"); goto done; }
                for (i = 0; i < m->count; ++i) if (mulib_docstrings_equal_(m->body+at+2,end-at-2,m->parameters[i])) break;
                if (i == m->count) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unknown macro parameter"); goto done; }
                if (!mulib_strbuf_append(&expanded,call.args[i])) goto memory;
                at = end+1;
            } else { if (!mulib_strbuf_putc(&expanded,m->body[at++])) goto memory; }
            if (expanded.length > p->ctx->options.output_bytes) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"macro expansion size limit"); goto done; }
        }
        if (!mulib_docstrings_bytes_(p,expanded.length)) goto done;
        ok = block ? mulib_docstrings_parse_(p,parent,expanded.data,expanded.length,"docstrings") : mulib_docstrings_inline_(p,parent,expanded.data,expanded.length);
        goto done;
    }
    if (!mulib_docstrings_registry_(p,"macros",call.name,&fn)) goto done;
    if (fn.type != MULIB_MUNE_FUNCTION) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unknown macro"); goto done; }
    roots = mulib_mune_result_create(p->ctx->lua); if (!roots) goto memory;
    for (i = 0; i < call.count; ++i) {
        if (mulib_mune_make_string(p->ctx->lua,call.args[i],strlen(call.args[i]),&args[i]) || !mulib_mune_result_push(roots,args[i])) goto memory;
    }
    if (mulib_mune_call(p->ctx->lua,fn,args,call.count,&result,&error)) { (void)mulib_docstrings_lua_error_(p,&error); goto done; }
    ok = mulib_docstrings_emit_lua_(p,parent,mulib_mune_result_get(result,0),block); goto done;
memory:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"macro expansion allocation");
done:
    mulib_docstrings_call_free_(&call); mulib_strbuf_free(&expanded);
    mulib_mune_result_destroy(result); mulib_mune_result_destroy(roots); return ok;
}
static size_t mulib_docstrings_close_(mulib_docstrings_parser_ *p, const char *s, size_t length, size_t at, const char *marker, size_t n) {
    while (at < length) {
        if (!mulib_docstrings_work_(p,1)) return length;
        if (s[at] == '\\' && at+1 < length) { at += 2; continue; }
        if (n <= length-at && !memcmp(s+at,marker,n)) return at;
        ++at;
    }
    return length;
}
static int mulib_docstrings_url_(const char *url) {
    const char *p, *colon = strchr(url,':'), *boundary = strpbrk(url,"/?#");
    if (!*url) return 0;
    for (p = url; *p; ++p) if ((unsigned char)*p <= 32 || *p == '\\' || *p == '<' || *p == '>' || *p == '"' || *p == '\'' || *p == '`') return 0;
    if (colon && (!boundary || colon < boundary)) {
        size_t n = (size_t)(colon-url), i; char scheme[8];
        if (n >= sizeof scheme) return 0;
        for (i = 0; i < n; ++i) scheme[i] = url[i] >= 'A' && url[i] <= 'Z' ? (char)(url[i]+32) : url[i];
        scheme[n] = 0;
        return !strcmp(scheme,"http") || !strcmp(scheme,"https") || !strcmp(scheme,"mailto");
    }
    return 1;
}
static int mulib_docstrings_attrs_(mulib_docstrings_parser_ *p, mulib_dsdom_t *n, const char *s, size_t length) {
    size_t at = 0, start, end;
    char *key = NULL, *value = NULL, quote;
    while (at < length) {
        while (at < length && mulib_docstrings_space_(s[at])) ++at;
        if (at == length) break;
        start = at;
        while (at < length && mulib_docstrings_ident_(s[at],at == start)) ++at;
        if (at == start) goto invalid;
        key = mulib_docstrings_copy_(s+start,at-start); if (!key) goto memory;
        while (at < length && mulib_docstrings_space_(s[at])) ++at;
        if (at == length || s[at++] != '=') goto invalid;
        while (at < length && mulib_docstrings_space_(s[at])) ++at;
        if (at == length || (s[at] != '"' && s[at] != '\'')) goto invalid;
        quote = s[at]; start = at++;
        while (at < length && s[at] != quote) { if (s[at] == '\\' && at+1 < length) ++at; ++at; }
        if (at == length) goto invalid;
        end = ++at; value = mulib_docstrings_argument_(s+start,end-start); if (!value) goto memory;
        if (mulib_xml_attr(n,key)) goto invalid;
        if (!mulib_docstrings_attr_(p,n,key,value)) goto fail;
        free(key); free(value); key = value = NULL;
    }
    return 1;
invalid:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"expected unique key=\"value\" element attributes"); goto fail;
memory:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"element attribute allocation");
fail:
    free(key); free(value); return 0;
}
static int mulib_docstrings_element_(mulib_docstrings_parser_ *p, mulib_dsdom_t *parent, const char *name,
    const char *attrs, size_t attrn, const char *body, size_t bodyn) {
    static const char *const builtins[] = { "strong", "emphasis", "underline", "strike", "code", "span", "link", "image", "superscript", "subscript", "break", "index-entry" };
    mulib_dsdom_t *n;
    mulib_mune_value_t fn, node, args[2];
    mulib_mune_result_t *roots = NULL, *result = NULL;
    mulib_mune_error_t error;
    size_t i;
    int builtin = 0, ok = 0;
    for (i = 0; i < sizeof builtins / sizeof builtins[0]; ++i) if (!strcmp(name,builtins[i])) builtin = 1;
    n = mulib_docstrings_node_(p,NULL,name); if (!n) return 0;
    if (!mulib_docstrings_attrs_(p,n,attrs,attrn)) goto done;
    if (!strcmp(name,"code")) ok = mulib_docstrings_text_(p,n,body,bodyn);
    else ok = mulib_docstrings_inline_(p,n,body,bodyn);
    if (!ok) goto done;
    if (!strcmp(name,"index-entry")) {
        char *term = mulib_dsdom_text(n,NULL); if (!term) goto memory;
        ok = mulib_docstrings_attr_(p,n,"term",term); free(term); if (!ok) goto done;
    }
    if (builtin) {
        ok = mulib_xml_append(parent,n); if (ok) n = NULL; goto done;
    }
    if (!mulib_docstrings_registry_(p,"elements",name,&fn)) { ok = 0; goto done; }
    if (fn.type != MULIB_MUNE_FUNCTION) { ok = mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unknown inline element (register with ldocstr.element)"); goto done; }
    roots = mulib_mune_result_create(p->ctx->lua);
    if (!roots || !mulib_docstrings_to_lua_(p->ctx->lua,n,&node,0) || !mulib_mune_result_push(roots,node) ||
        !mulib_docstrings_raw_(p->ctx->lua,node,"children",&args[0]) || !mulib_docstrings_raw_(p->ctx->lua,node,"attrs",&args[1])) goto memory;
    if (mulib_mune_call(p->ctx->lua,fn,args,2,&result,&error)) { ok = mulib_docstrings_lua_error_(p,&error); goto done; }
    ok = mulib_docstrings_emit_lua_(p,parent,mulib_mune_result_get(result,0),0); goto done;
memory:
    ok = mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"element extension allocation");
done:
    mulib_mune_result_destroy(roots); mulib_mune_result_destroy(result); mulib_xml_destroy(n); return ok;
}
static int mulib_docstrings_inline_(mulib_docstrings_parser_ *p, mulib_dsdom_t *parent, const char *s, size_t length) {
    size_t at = 0, plain = 0, end, run, start, i;
    int ok = 0;
    mulib_dsdom_t *n;
    if (++p->depth > p->ctx->options.depth) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"inline/macro nesting limit"); goto done; }
    if (!mulib_xml_valid_text(s,length)) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_INVALID,"invalid inline UTF-8/XML text"); goto done; }
    while (at < length) {
        const char *tag = NULL;
        if (!mulib_docstrings_work_(p,1)) goto done;
        if (s[at] == '\\' && at+1 < length) {
            if (!mulib_docstrings_text_(p,parent,s+plain,at-plain) || !mulib_docstrings_text_(p,parent,s+at+1,1)) goto done;
            at += 2; plain = at; continue;
        }
        if (!p->markup && length-at >= 2 && !memcmp(s+at,"{{",2)) {
            size_t depth = 0; char quote = 0;
            end = at+2;
            for (; end < length; ++end) {
                char ch = s[end];
                if (!mulib_docstrings_work_(p,1)) goto done;
                if (quote) { if (ch == '\\' && end+1 < length) ++end; else if (ch == quote) quote = 0; continue; }
                if (ch == '\'' || ch == '"') { quote = ch; continue; }
                if (!depth && length-end >= 2 && !memcmp(s+end,"}}",2)) break;
                if (ch == '(' || ch == '{' || ch == '[') ++depth;
                else if ((ch == ')' || ch == '}' || ch == ']') && depth) --depth;
            }
            if (end == length) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unclosed macro invocation"); goto done; }
            if (!mulib_docstrings_text_(p,parent,s+plain,at-plain) || !mulib_docstrings_macro_expand_(p,parent,s+at+2,end-at-2,0)) goto done;
            at = end+2; plain = at; continue;
        }
        if (!p->markup && s[at] == '@' && at+1 < length && mulib_docstrings_ident_(s[at+1],1)) {
            char name[64]; size_t attr = 0, attrn = 0, depth;
            start = at+1; end = start;
            while (end < length && mulib_docstrings_ident_(s[end],end == start)) ++end;
            if (end-start >= sizeof name) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"element name too long"); goto done; }
            memcpy(name,s+start,end-start); name[end-start] = 0;
            if (end < length && s[end] == '[') {
                char quote = 0; attr = ++end;
                while (end < length) {
                    char ch = s[end];
                    if (quote) { if (ch == '\\' && end+1 < length) ++end; else if (ch == quote) quote = 0; }
                    else if (ch == '"' || ch == '\'') quote = ch;
                    else if (ch == ']') break;
                    ++end;
                }
                if (end == length) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unclosed element attributes"); goto done; }
                attrn = end-attr; ++end;
            }
            if (end < length && s[end] == '{') {
                start = ++end; depth = 1;
                while (end < length) {
                    if (!mulib_docstrings_work_(p,1)) goto done;
                    if (s[end] == '\\' && end+1 < length) { end += 2; continue; }
                    if (s[end] == '{') ++depth;
                    if (s[end] == '}' && !--depth) break;
                    ++end;
                }
                if (end == length) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unclosed element body"); goto done; }
                if (!mulib_docstrings_text_(p,parent,s+plain,at-plain) ||
                    !mulib_docstrings_element_(p,parent,name,attrn ? s+attr : "",attrn,s+start,end-start)) goto done;
                at = end+1; plain = at; continue;
            }
        }
        if (s[at] == '`') {
            run = 1; while (at+run < length && s[at+run] == '`') ++run;
            end = mulib_docstrings_close_(p,s,length,at+run,s+at,run);
            if (end < length) {
                if (!mulib_docstrings_text_(p,parent,s+plain,at-plain) || !(n = mulib_docstrings_node_(p,parent,"code")) ||
                    !mulib_docstrings_text_(p,n,s+at+run,end-at-run)) goto done;
                at = end+run; plain = at; continue;
            }
        }
        if (s[at] == '[' || (s[at] == '!' && at+1 < length && s[at+1] == '[')) {
            int image = s[at] == '!'; char *url, *alt;
            start = at+1+(size_t)image;
            end = mulib_docstrings_close_(p,s,length,start,"](",2);
            i = end < length ? mulib_docstrings_close_(p,s,length,end+2,")",1) : length;
            if (i < length) {
                url = mulib_docstrings_copy_(s+end+2,i-end-2); alt = mulib_docstrings_copy_(s+start,end-start);
                if (!url || !alt) { free(url); free(alt); (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"link allocation"); goto done; }
                if (!mulib_docstrings_url_(url)) { free(url); free(alt); (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unsafe/unsupported link URL"); goto done; }
                n = NULL;
                ok = mulib_docstrings_text_(p,parent,s+plain,at-plain) && (n = mulib_docstrings_node_(p,parent,image ? "image" : "link")) &&
                    mulib_docstrings_attr_(p,n,image ? "src" : "href",url) && (!image || mulib_docstrings_attr_(p,n,"alt",alt)) &&
                    mulib_docstrings_inline_(p,n,s+start,end-start);
                free(url); free(alt); if (!ok) goto done;
                ok = 0; at = i+1; plain = at; continue;
            }
        }
        run = 1;
        if (length-at >= 2 && !memcmp(s+at,"**",2)) { tag = "strong"; run = 2; }
        else if (length-at >= 2 && !memcmp(s+at,"__",2)) { tag = p->markup == 1 ? "strong" : p->markup == 2 ? "emphasis" : "underline"; run = 2; }
        else if (length-at >= 2 && !memcmp(s+at,"~~",2)) { tag = "strike"; run = 2; }
        else if (s[at] == '*' || s[at] == '_') tag = s[at] == '*' && p->markup == 2 ? "strong" : "emphasis";
        else if (s[at] == '^') tag = "superscript";
        else if (s[at] == '~') tag = "subscript";
        if (s[at] == '_' && at && mulib_docstrings_ident_(s[at-1],0)) tag = NULL;
        if (tag && at+run < length && !mulib_docstrings_space_(s[at+run])) {
            end = mulib_docstrings_close_(p,s,length,at+run,s+at,run);
            if (end < length && end > at+run) {
                if (!mulib_docstrings_text_(p,parent,s+plain,at-plain) || !(n = mulib_docstrings_node_(p,parent,tag)) ||
                    !mulib_docstrings_inline_(p,n,s+at+run,end-at-run)) goto done;
                at = end+run; plain = at; continue;
            }
        }
        ++at;
    }
    ok = !p->error.code && mulib_docstrings_text_(p,parent,s+plain,length-plain);
done:
    --p->depth; return ok;
}
typedef struct mulib_docstrings_line_ { size_t start, length, next; } mulib_docstrings_line_;
static mulib_docstrings_line_ mulib_docstrings_line_at_(const char *s, size_t length, size_t at) {
    mulib_docstrings_line_ l;
    l.start = at;
    while (at < length && s[at] != '\r' && s[at] != '\n') ++at;
    l.length = at-l.start;
    if (at < length) { char ch = s[at++]; if (ch == '\r' && at < length && s[at] == '\n') ++at; }
    l.next = at; return l;
}
static int mulib_docstrings_block_(mulib_docstrings_parser_ *p, const char *source, size_t length,
    size_t *at, const char *closing, const char **body, size_t *bodyn) {
    size_t begin = *at;
    while (*at < length) {
        mulib_docstrings_line_ l = mulib_docstrings_line_at_(source,length,*at);
        const char *s = source+l.start; size_t n = l.length;
        mulib_docstrings_trim_(&s,&n);
        if (!mulib_docstrings_work_(p,1)) return 0;
        if (mulib_docstrings_equal_(s,n,closing)) {
            *body = source+begin; *bodyn = l.start-begin; *at = l.next; return 1;
        }
        *at = l.next;
    }
    return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unclosed fenced/directive block");
}
static int mulib_docstrings_code_(mulib_docstrings_parser_ *p, mulib_dsdom_t *parent, const char *body, size_t length, const char *language) {
    mulib_dsdom_t *n, *span, *svg;
    mulib_gvizz_t *graph;
    mulib_xml_error_t error;
    mulib_termsyn_t *syntax = NULL;
    mulib_edbuf_t *buffer = NULL;
    mulib_termsyn_language_t lang = MULIB_TERMSYN_PLAIN;
    mulib_termsyn_span_t token;
    size_t i;
    char cl[100];
    int ok = 0;
    if (!strcmp(language,"graph") || !strcmp(language,"diagram")) {
        graph = mulib_gvizz_parse(body,length,&error);
        if (!graph) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,error.message);
        svg = !strcmp(language,"graph") ? mulib_gvizz_svg(graph) : mulib_dyegram_svg(graph);
        mulib_gvizz_destroy(graph);
        if (!svg) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"SVG graph allocation");
        /* Account for generated SVG by a lossless Lua-independent tree walk. */
        { char *serialized = mulib_xml_serialize(svg,&i);
          if (!serialized || !mulib_docstrings_bytes_(p,i)) {
              if (!serialized) (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"SVG serialization allocation");
              free(serialized); mulib_xml_destroy(svg); return 0;
          }
          free(serialized);
        }
        n = mulib_docstrings_node_(p,parent,"figure");
        if (!n || !mulib_docstrings_attr_(p,n,"kind",language) || !mulib_xml_append(n,svg)) { mulib_xml_destroy(svg); return 0; }
        return 1;
    }
    n = mulib_docstrings_node_(p,parent,"code-block");
    if (!n || !mulib_docstrings_attr_(p,n,"language",language)) return 0;
    (void)snprintf(cl,sizeof cl,"language-%s",language);
    if (*language && !mulib_docstrings_attr_(p,n,"class",cl)) return 0;
    if (!strcmp(language,"c")) lang = MULIB_TERMSYN_C;
    else if (!strcmp(language,"cpp") || !strcmp(language,"c++")) lang = MULIB_TERMSYN_CPP;
    else if (!strcmp(language,"python")) lang = MULIB_TERMSYN_PYTHON;
    else if (!strcmp(language,"json")) lang = MULIB_TERMSYN_JSON;
    else if (!strcmp(language,"sh") || !strcmp(language,"shell")) lang = MULIB_TERMSYN_SHELL;
    if (lang == MULIB_TERMSYN_PLAIN) return mulib_docstrings_text_(p,n,body,length);
    buffer = mulib_edbuf_create(MULIB_EDBUF_GAP,body,length); syntax = mulib_termsyn_create(lang);
    if (!buffer || !syntax || mulib_termsyn_update(syntax,buffer) != MULIB_TERMSYN_OK) goto memory;
    for (i = 0; i < mulib_termsyn_span_count(syntax); ++i) {
        if (mulib_termsyn_span(syntax,i,&token) != MULIB_TERMSYN_OK) goto memory;
        if (token.token == MULIB_TERMSYN_TEXT) { if (!mulib_docstrings_text_(p,n,body+token.offset,token.length)) goto done; }
        else {
            span = mulib_docstrings_node_(p,n,"span");
            if (!span || !mulib_docstrings_attr_(p,span,"class",mulib_termsyn_token_name(token.token)) ||
                !mulib_docstrings_text_(p,span,body+token.offset,token.length)) goto done;
        }
    }
    ok = 1; goto done;
memory:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"syntax-highlighting allocation");
done:
    mulib_termsyn_destroy(syntax); mulib_edbuf_destroy(buffer); return ok;
}
static int mulib_docstrings_lua_block_(mulib_docstrings_parser_ *p, mulib_dsdom_t *parent, const char *body, size_t length) {
    mulib_mune_result_t *result = NULL;
    mulib_mune_error_t error;
    int ok;
    if (!mulib_docstrings_lua_init_(p)) return 0;
    if (mulib_mune_run_source(p->ctx->lua,body,length,&result,&error)) return mulib_docstrings_lua_error_(p,&error);
    ok = mulib_docstrings_emit_lua_(p,parent,mulib_mune_result_get(result,0),1);
    mulib_mune_result_destroy(result); return ok;
}
static int mulib_docstrings_include_(mulib_docstrings_parser_ *p, mulib_dsdom_t *parent, const char *format, const char *path) {
    mulib_strbuf_t body;
    size_t i;
    const char *origin = p->origin;
    int ok = 0;
    if (!p->ctx->options.load) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_POLICY,"includes require an explicit host loader");
    if (p->includes == p->ctx->options.include_depth) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"include depth limit");
    for (i = 0; i < p->includes; ++i) if (!strcmp(path,p->paths[i])) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"recursive document include");
    mulib_strbuf_init(&body);
    if (!p->ctx->options.load(p->ctx->options.user,path,format,&body)) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_IO,"host include loader failed"); goto done; }
    if (!mulib_docstrings_bytes_(p,body.length)) goto done;
    p->paths[p->includes++] = path; p->origin = path;
    ok = mulib_docstrings_parse_(p,parent,body.data,body.length,format);
    --p->includes; p->origin = origin;
done:
    mulib_strbuf_free(&body); return ok;
}
static int mulib_docstrings_flush_(mulib_docstrings_parser_ *p, mulib_dsdom_t *parent, mulib_strbuf_t *paragraph) {
    mulib_dsdom_t *n;
    if (!paragraph->length) return 1;
    n = mulib_docstrings_node_(p,parent,"paragraph");
    if (!n || !mulib_docstrings_inline_(p,n,paragraph->data,paragraph->length)) return 0;
    paragraph->length = 0; paragraph->data[0] = 0; return 1;
}
static int mulib_docstrings_heading_(mulib_docstrings_parser_ *p, mulib_dsdom_t *parent, unsigned level, const char *s, size_t length, const char *id) {
    mulib_dsdom_t *n = mulib_docstrings_node_(p,parent,"heading");
    char lv[2] = { (char)('0'+level), 0 }, *owned = NULL;
    int ok;
    if (!n || !mulib_docstrings_attr_(p,n,"level",lv)) return 0;
    mulib_docstrings_trim_(&s,&length);
    if (!id && length > 4 && s[length-1] == '}') {
        size_t at = length-2;
        while (at && s[at] != '{') --at;
        if (s[at] == '{' && s[at+1] == '#' && at && mulib_docstrings_space_(s[at-1])) {
            owned = mulib_docstrings_copy_(s+at+2,length-at-3);
            if (!owned) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"heading id allocation");
            id = owned; length = at; mulib_docstrings_trim_(&s,&length);
        }
    }
    ok = (!id || (*id && mulib_docstrings_attr_(p,n,"id",id))) && mulib_docstrings_inline_(p,n,s,length);
    free(owned); return ok;
}
static int mulib_docstrings_table_row_(mulib_docstrings_parser_ *p, mulib_dsdom_t *table, const char *s, size_t length,
    size_t *columns, size_t *rows) {
    size_t at = 1, start = 1, count = 0, depth = 0, i;
    int code = 0, separator = 1, hyphens = 0;
    mulib_dsdom_t *row = NULL, *cell, *first;
    if (length && s[length-1] == '|') --length;
    /* A separator is a row consisting solely of pipes, dashes, colons, space. */
    for (i = 1; i < length; ++i) {
        if (s[i] == '-') ++hyphens;
        else if (s[i] != '|' && s[i] != ':' && !mulib_docstrings_space_(s[i])) separator = 0;
    }
    separator = separator && hyphens >= 3;
    if (!separator) { row = mulib_docstrings_node_(p,table,"row"); if (!row) return 0; }
    for (; at <= length; ++at) {
        if (at < length) {
            if (s[at] == '\\' && at+1 < length) { ++at; continue; }
            if (s[at] == '`') code = !code;
            if (!code && (s[at] == '{' || s[at] == '[' || s[at] == '(')) ++depth;
            else if (!code && depth && (s[at] == '}' || s[at] == ']' || s[at] == ')')) --depth;
            if (s[at] != '|' || code || depth) continue;
        }
        ++count;
        if (!separator) {
            const char *body = s+start; size_t n = at-start; mulib_docstrings_trim_(&body,&n);
            cell = mulib_docstrings_node_(p,row,"cell");
            if (!cell || !mulib_docstrings_inline_(p,cell,body,n)) return 0;
        }
        start = at+1;
    }
    if (!*columns) *columns = count;
    if (count != *columns) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"ragged documentation table");
    if (separator) {
        if (*rows != 1) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"table separator must follow the header row");
        first = mulib_xml_first(table);
        for (cell = mulib_xml_first(first); cell; cell = mulib_xml_next(cell))
            if (!mulib_docstrings_attr_(p,cell,"header","true")) return 0;
    } else ++*rows;
    return 1;
}
static int mulib_docstrings_directive_(mulib_docstrings_parser_ *p, mulib_dsdom_t *parent,
    const char *name, const char *arg, size_t argn) {
    static const char *const names[] = { "file", "brief", "param", "return", "returns", "note", "warning", "see", "author", "since", "deprecated", "version", "title" };
    mulib_dsdom_t *n;
    mulib_mune_value_t fn, value;
    mulib_mune_result_t *result = NULL, *roots = NULL;
    mulib_mune_error_t error;
    size_t i, split;
    char *argument = NULL;
    int ok = 0, builtin = 0;
    mulib_docstrings_trim_(&arg,&argn);
    if (!strcmp(name,"use")) return mulib_docstrings_macro_expand_(p,parent,arg,argn,1);
    if (!strcmp(name,"toc") || !strcmp(name,"indices")) {
        if (argn) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unexpected index/TOC arguments");
        return mulib_docstrings_node_(p,parent,!strcmp(name,"toc") ? "toc" : "index") != NULL;
    }
    if (!strcmp(name,"section") || !strcmp(name,"subsection")) {
        split = 0; while (split < argn && !mulib_docstrings_space_(arg[split])) ++split;
        if (!split || split == argn) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"section requires an id and title");
        argument = mulib_docstrings_copy_(arg,split); if (!argument) goto memory;
        ok = mulib_docstrings_heading_(p,parent,!strcmp(name,"section") ? 1u : 2u,arg+split,argn-split,argument); goto done;
    }
    if (!strcmp(name,"include")) {
        char format[16]; split = 0;
        while (split < argn && !mulib_docstrings_space_(arg[split])) ++split;
        if (!split || split >= sizeof format || split == argn) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"include requires format and path");
        memcpy(format,arg,split); format[split] = 0;
        argument = mulib_docstrings_argument_(arg+split,argn-split); if (!argument) goto memory;
        ok = mulib_docstrings_include_(p,parent,format,argument); goto done;
    }
    if (!strcmp(name,"stylesheet")) {
        char format[16]; mulib_strbuf_t sheet;
        split = 0; while (split < argn && !mulib_docstrings_space_(arg[split])) ++split;
        if (!split || split >= sizeof format || split == argn) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"stylesheet requires format and path");
        memcpy(format,arg,split); format[split] = 0;
        if (!p->ctx->options.load) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_POLICY,"stylesheets require an explicit host loader");
        argument = mulib_docstrings_argument_(arg+split,argn-split); if (!argument) goto memory;
        mulib_strbuf_init(&sheet);
        if (!p->ctx->options.load(p->ctx->options.user,argument,format,&sheet))
            (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_IO,"host stylesheet loader failed");
        else if (sheet.length > p->ctx->options.source_bytes)
            (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"stylesheet source limit");
        else {
            n = mulib_docstrings_node_(p,parent,"stylesheet");
            ok = n && mulib_docstrings_attr_(p,n,"format",format) && mulib_docstrings_text_(p,n,sheet.data,sheet.length);
        }
        mulib_strbuf_free(&sheet); goto done;
    }
    argument = mulib_docstrings_copy_(arg,argn); if (!argument) goto memory;
    if (!strcmp(name,"index")) {
        n = mulib_docstrings_node_(p,parent,"index-entry");
        ok = n && *argument && mulib_docstrings_attr_(p,n,"term",argument);
        if (!*argument) (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"empty index term");
        goto done;
    }
    for (i = 0; i < sizeof names / sizeof names[0]; ++i) if (!strcmp(name,names[i])) builtin = 1;
    if (builtin) {
        n = mulib_docstrings_node_(p,parent,"directive");
        ok = n && mulib_docstrings_attr_(p,n,"name",name) && mulib_docstrings_attr_(p,n,"argument",argument) && mulib_docstrings_inline_(p,n,arg,argn);
        goto done;
    }
    if (!mulib_docstrings_registry_(p,"directives",name,&fn)) goto done;
    if (fn.type != MULIB_MUNE_FUNCTION) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unknown directive (register with ldocstr.directive)"); goto done; }
    roots = mulib_mune_result_create(p->ctx->lua);
    if (!roots || mulib_mune_make_string(p->ctx->lua,arg,argn,&value) || !mulib_mune_result_push(roots,value)) goto memory;
    if (mulib_mune_call(p->ctx->lua,fn,&value,1,&result,&error)) { (void)mulib_docstrings_lua_error_(p,&error); goto done; }
    ok = mulib_docstrings_emit_lua_(p,parent,mulib_mune_result_get(result,0),1); goto done;
memory:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"directive allocation");
done:
    free(argument); mulib_mune_result_destroy(result); mulib_mune_result_destroy(roots); return ok;
}
static int mulib_docstrings_parse_(mulib_docstrings_parser_ *p, mulib_dsdom_t *parent, const char *source, size_t length, const char *format) {
    const char *oldsource = p->source, *body, *line;
    size_t oldlength = p->length, oldoffset = p->offset, at = 0, n, bodyn, columns = 0, rows = 0;
    int oldmarkup = p->markup, ok = 0, adoc_table = 0, listkind = 0;
    mulib_dsdom_t *list = NULL, *table = NULL, *item, *node;
    mulib_strbuf_t paragraph, quote;
    char language[64] = "";
    mulib_docstrings_line_ l;
    mulib_strbuf_init(&paragraph); mulib_strbuf_init(&quote);
    p->source = source; p->length = length; p->offset = 0;
    if (++p->depth > p->ctx->options.depth) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"document/macro nesting limit"); goto done; }
    if (length > p->ctx->options.source_bytes) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"document source limit"); goto done; }
    if (!mulib_xml_valid_text(source,length)) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_INVALID,"invalid UTF-8/XML source"); goto done; }
    if (!format || !strcmp(format,"docstrings")) p->markup = 0;
    else if (!strcmp(format,"markdown")) p->markup = 1;
    else if (!strcmp(format,"asciidoc")) p->markup = 2;
    else if (!strcmp(format,"lua")) { ok = mulib_docstrings_lua_block_(p,parent,source,length); goto done; }
    else { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_INVALID,"unknown document format"); goto done; }
    while (at < length) {
        size_t indent = 0, content = 0, heading = 0;
        int kind = 0, special;
        char marker;
        l = mulib_docstrings_line_at_(source,length,at); at = l.next; p->offset = l.start;
        line = source+l.start; n = l.length;
        while (indent < n && (line[indent] == ' ' || line[indent] == '\t')) ++indent;
        line += indent; n -= indent; while (n && mulib_docstrings_space_(line[n-1])) --n;
        if (!mulib_docstrings_work_(p,1)) goto done;
        if (!n) {
            if (!mulib_docstrings_flush_(p,parent,&paragraph)) goto done;
            list = NULL; listkind = 0; if (!adoc_table) table = NULL; continue;
        }
        marker = p->markup == 2 ? '=' : '#';
        while (heading < n && line[heading] == marker) ++heading;
        if (!heading || heading > 6 || heading == n || !mulib_docstrings_space_(line[heading])) heading = 0;
        if (n > 1 && (line[0] == '-' || line[0] == '*' || line[0] == '+') && mulib_docstrings_space_(line[1])) { kind = 1; content = 2; }
        else {
            size_t d = 0; while (d < n && line[d] >= '0' && line[d] <= '9') ++d;
            if (d && d+1 < n && line[d] == '.' && mulib_docstrings_space_(line[d+1])) { kind = 2; content = d+2; }
        }
        special = heading || kind || line[0] == '>' || line[0] == '|' ||
            (n >= 3 && !memcmp(line,"```",3)) || (!p->markup && line[0] == '.' && n > 1 && mulib_docstrings_ident_(line[1],1)) ||
            mulib_docstrings_equal_(line,n,"---") || (p->markup == 2 && (line[0] == '[' || mulib_docstrings_equal_(line,n,"----") ||
            (n >= 9 && !memcmp(line,"include::",9))));
        if (special && !mulib_docstrings_flush_(p,parent,&paragraph)) goto done;
        if (heading) {
            list = table = NULL; listkind = 0;
            if (!mulib_docstrings_heading_(p,parent,(unsigned)heading,line+heading,n-heading,NULL)) goto done;
            continue;
        }
        if (n >= 3 && !memcmp(line,"```",3)) {
            size_t langn = n-3; const char *lang = line+3; mulib_docstrings_trim_(&lang,&langn);
            if (langn >= sizeof language) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"code language too long"); goto done; }
            memcpy(language,lang,langn); language[langn] = 0;
            if (!mulib_docstrings_block_(p,source,length,&at,"```",&body,&bodyn) || !mulib_docstrings_code_(p,parent,body,bodyn,language)) goto done;
            language[0] = 0; list = table = NULL; listkind = 0; continue;
        }
        if (p->markup == 2 && line[0] == '[') {
            if (n < 10 || memcmp(line,"[source,",8) || line[n-1] != ']' || n-9 >= sizeof language) {
                (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unsupported AsciiDoc block attributes"); goto done;
            }
            memcpy(language,line+8,n-9); language[n-9] = 0; continue;
        }
        if (p->markup == 2 && mulib_docstrings_equal_(line,n,"----")) {
            if (!mulib_docstrings_block_(p,source,length,&at,"----",&body,&bodyn) || !mulib_docstrings_code_(p,parent,body,bodyn,language)) goto done;
            language[0] = 0; list = table = NULL; listkind = 0; continue;
        }
        if (p->markup == 2 && n >= 9 && !memcmp(line,"include::",9)) {
            char *path;
            if (n < 12 || memcmp(line+n-2,"[]",2)) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"AsciiDoc include requires empty [] options"); goto done; }
            path = mulib_docstrings_copy_(line+9,n-11); if (!path) goto memory;
            ok = mulib_docstrings_include_(p,parent,"asciidoc",path); free(path); if (!ok) goto done;
            ok = 0; list = table = NULL; listkind = 0; continue;
        }
        if (!p->markup && line[0] == '.' && n > 1 && mulib_docstrings_ident_(line[1],1)) {
            size_t split = 1, argn, siglen;
            const char *arg;
            char name[64], closing[80];
            while (split < n && mulib_docstrings_ident_(line[split],split == 1)) ++split;
            if (split-1 >= sizeof name || (split < n && !mulib_docstrings_space_(line[split]))) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"malformed directive"); goto done; }
            memcpy(name,line+1,split-1); name[split-1] = 0; arg = line+split; argn = n-split; mulib_docstrings_trim_(&arg,&argn);
            list = table = NULL; listkind = 0;
            if (!strcmp(name,"define") || !strcmp(name,"macro")) {
                size_t d = 0;
                siglen = 0;
                while (siglen < argn) {
                    if (arg[siglen] == '(') ++d; else if (arg[siglen] == ')' && d) --d;
                    if (!d && mulib_docstrings_space_(arg[siglen])) break;
                    ++siglen;
                }
                if (!strcmp(name,"macro")) {
                    if (siglen != argn) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"multiline macro header must contain only its signature"); goto done; }
                    if (!mulib_docstrings_block_(p,source,length,&at,".endmacro",&body,&bodyn)) goto done;
                } else { body = arg+siglen; bodyn = argn-siglen; mulib_docstrings_trim_(&body,&bodyn); }
                if (!mulib_docstrings_define_(p,arg,siglen,body,bodyn)) goto done;
            } else if (!strcmp(name,"code") || !strcmp(name,"graph") || !strcmp(name,"diagram") || !strcmp(name,"lua") || !strcmp(name,"style")) {
                (void)snprintf(closing,sizeof closing,".end%s",name);
                if (!mulib_docstrings_block_(p,source,length,&at,closing,&body,&bodyn)) goto done;
                if (!strcmp(name,"lua")) {
                    if (argn) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unexpected Lua block arguments"); goto done; }
                    if (!mulib_docstrings_lua_block_(p,parent,body,bodyn)) goto done;
                }
                else if (!strcmp(name,"style")) {
                    char *fmt = mulib_docstrings_copy_(arg,argn); if (!fmt) goto memory;
                    node = mulib_docstrings_node_(p,parent,"stylesheet");
                    ok = node && mulib_docstrings_attr_(p,node,"format",*fmt ? fmt : "css") && mulib_docstrings_text_(p,node,body,bodyn);
                    free(fmt); if (!ok) goto done; ok = 0;
                } else {
                    if (!strcmp(name,"code")) {
                        if (argn >= sizeof language) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"code language too long"); goto done; }
                        memcpy(language,arg,argn); language[argn] = 0;
                    } else { if (argn) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unexpected graph/diagram arguments"); goto done; } (void)snprintf(language,sizeof language,"%s",name); }
                    if (!mulib_docstrings_code_(p,parent,body,bodyn,language)) goto done;
                    language[0] = 0;
                }
            } else if (!mulib_docstrings_directive_(p,parent,name,arg,argn)) goto done;
            continue;
        }
        if (p->markup == 2 && mulib_docstrings_equal_(line,n,"|===")) {
            adoc_table = !adoc_table;
            if (adoc_table) { table = mulib_docstrings_node_(p,parent,"table"); columns = rows = 0; if (!table) goto done; }
            else table = NULL;
            list = NULL; listkind = 0; continue;
        }
        if (line[0] == '|') {
            list = NULL; listkind = 0;
            if (!table) { table = mulib_docstrings_node_(p,parent,"table"); columns = rows = 0; if (!table) goto done; }
            if (!mulib_docstrings_table_row_(p,table,line,n,&columns,&rows)) goto done;
            continue;
        }
        if (adoc_table) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"AsciiDoc table rows must start with a pipe"); goto done; }
        table = NULL;
        if (line[0] == '>') {
            quote.length = 0; if (quote.data) quote.data[0] = 0;
            for (;;) {
                content = n > 1 && line[1] == ' ' ? 2 : 1;
                if (!mulib_strbuf_append_n(&quote,line+content,n-content) || !mulib_strbuf_putc(&quote,'\n')) goto memory;
                if (at == length) break;
                l = mulib_docstrings_line_at_(source,length,at); line = source+l.start; n = l.length;
                if (!n || line[0] != '>') break;
                at = l.next;
            }
            node = mulib_docstrings_node_(p,parent,"blockquote");
            if (!node || !mulib_docstrings_parse_(p,node,quote.data,quote.length,format)) goto done;
            list = NULL; listkind = 0; continue;
        }
        if (kind) {
            if (indent) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"indented lists are outside this markup profile"); goto done; }
            if (!list || kind != listkind) {
                list = mulib_docstrings_node_(p,parent,"list"); listkind = kind;
                if (!list || !mulib_docstrings_attr_(p,list,"ordered",kind == 2 ? "true" : "false")) goto done;
            }
            item = mulib_docstrings_node_(p,list,"item");
            if (!item || !mulib_docstrings_inline_(p,item,line+content,n-content)) goto done;
            continue;
        }
        list = NULL; listkind = 0;
        if (mulib_docstrings_equal_(line,n,"---")) { if (!mulib_docstrings_node_(p,parent,"rule")) goto done; continue; }
        if (paragraph.length && !mulib_strbuf_putc(&paragraph,'\n')) goto memory;
        if (!mulib_strbuf_append_n(&paragraph,line,n)) goto memory;
    }
    if (adoc_table || *language) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_SYNTAX,"unclosed AsciiDoc table/source attributes"); goto done; }
    ok = mulib_docstrings_flush_(p,parent,&paragraph); goto done;
memory:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"document parser allocation");
done:
    mulib_strbuf_free(&paragraph); mulib_strbuf_free(&quote); --p->depth;
    p->source = oldsource; p->length = oldlength; p->offset = oldoffset; p->markup = oldmarkup;
    return ok && !p->error.code;
}
typedef struct mulib_docstrings_nodes_ { mulib_dsdom_t **data; size_t count, capacity; } mulib_docstrings_nodes_;
static int mulib_docstrings_collect_(mulib_docstrings_parser_ *p, mulib_dsdom_t *n, mulib_docstrings_nodes_ *list, unsigned depth) {
    mulib_dsdom_t *c;
    const char *name = mulib_xml_name(n);
    if (depth > MULIB_DOCSTRIL_MAX_DEPTH || !mulib_docstrings_work_(p,1)) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"DocstrIL traversal limit");
    if (name) {
        if (list->count == list->capacity) {
            size_t cap = list->capacity ? list->capacity * 2 : 32;
            mulib_dsdom_t **data;
            if (cap > SIZE_MAX / sizeof *data) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"DocstrIL size overflow");
            data = (mulib_dsdom_t **)realloc(list->data,cap*sizeof *data);
            if (!data) return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"DocstrIL traversal allocation");
            list->data = data; list->capacity = cap;
        }
        list->data[list->count++] = n;
        if (!strcmp(name,"stylesheet")) return 1;
        if (!strcmp(name,"toc") || !strcmp(name,"index")) {
            while ((c = mulib_xml_first(n)) != NULL) mulib_xml_destroy(c);
            return 1;
        }
    }
    for (c = mulib_xml_first(n); c; c = mulib_xml_next(c))
        if (!mulib_docstrings_collect_(p,c,list,depth+1)) return 0;
    return 1;
}
static int mulib_docstrings_used_id_(mulib_docstrings_parser_ *p, const mulib_docstrings_nodes_ *list, const mulib_dsdom_t *node, const char *id) {
    size_t i;
    for (i = 0; i < list->count; ++i) {
        const char *other;
        if (!list->data[i] || list->data[i] == node) continue;
        if (!mulib_docstrings_work_(p,1)) return -1;
        other = mulib_xml_attr(list->data[i],"id");
        if (other && !strcmp(other,id)) return 1;
    }
    return 0;
}
static int mulib_docstrings_index_compare_(const void *a, const void *b) {
    const mulib_dsdom_t *x = *(mulib_dsdom_t *const *)a, *y = *(mulib_dsdom_t *const *)b;
    return strcmp(mulib_xml_attr(x,"term"),mulib_xml_attr(y,"term"));
}
static int mulib_docstrings_index_link_(mulib_docstrings_parser_ *p, mulib_dsdom_t *list, const mulib_dsdom_t *target, int index) {
    mulib_dsdom_t *item = mulib_docstrings_node_(p,list,"item"), *link;
    mulib_strbuf_t href;
    char *label = NULL;
    int ok = 0;
    mulib_strbuf_init(&href);
    if (!item || !(link = mulib_docstrings_node_(p,item,"link"))) goto done;
    if (!mulib_strbuf_putc(&href,'#') || !mulib_strbuf_append(&href,mulib_xml_attr(target,"id"))) goto memory;
    label = index ? mulib_docstrings_copy_(mulib_xml_attr(target,"term"),strlen(mulib_xml_attr(target,"term"))) : mulib_dsdom_text(target,NULL);
    if (!label) goto memory;
    ok = mulib_docstrings_attr_(p,link,"href",href.data) && mulib_docstrings_text_(p,link,label,strlen(label)); goto done;
memory:
    (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"index generation allocation");
done:
    mulib_strbuf_free(&href); free(label); return ok;
}
static int mulib_docstrings_finalize_(mulib_docstrings_parser_ *p, mulib_docstril_t *root) {
    mulib_docstrings_nodes_ list = { NULL,0,0 }, entries = { NULL,0,0 };
    mulib_xml_error_t error;
    size_t i, j;
    int ok = 0;
    mulib_strbuf_t styles;
    mulib_strbuf_init(&styles);
    if (!mulib_docstril_validate(root,p->ctx->options.nodes,p->ctx->options.output_bytes,&error))
        return mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_INVALID,error.message);
    if (!mulib_docstrings_collect_(p,root,&list,0)) goto done;
    for (i = 0; i < list.count; ++i) {
        mulib_dsdom_t *n = list.data[i];
        const char *name = mulib_xml_name(n), *id = mulib_xml_attr(n,"id");
        if (!strcmp(name,"stylesheet")) {
            char *source = mulib_dsdom_text(n,&j);
            if (!source) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"stylesheet source allocation"); goto done; }
            ok = mulib_docstrings_stylesource_(p,source,j,mulib_xml_attr(n,"format"),&styles); free(source);
            if (!ok) goto done;
            if (styles.length > p->ctx->options.output_bytes) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,"combined stylesheet size limit"); goto done; }
            ok = 0; continue;
        }
        if (id) {
            const char *c;
            if (!*id || strlen(id) > 256) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_INVALID,"invalid/oversized element id"); goto done; }
            for (c = id; *c; ++c) if (mulib_docstrings_space_(*c)) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_INVALID,"whitespace in element id"); goto done; }
            if (mulib_docstrings_used_id_(p,&list,n,id)) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_INVALID,"duplicate element id"); goto done; }
        }
        if ((!strcmp(name,"heading") || !strcmp(name,"index-entry")) && !id) {
            char base[80], candidate[110]; size_t at = 0, suffix = 1; int used;
            char *text = !strcmp(name,"heading") ? mulib_dsdom_text(n,NULL) : NULL;
            if (!strcmp(name,"heading") && !text) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"heading slug allocation"); goto done; }
            if (text) {
                for (j = 0; text[j] && at < 64; ++j) {
                    char c = text[j];
                    if (c >= 'A' && c <= 'Z') c = (char)(c+32);
                    if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')) base[at++] = c;
                    else if (at && base[at-1] != '-') base[at++] = '-';
                }
                while (at && base[at-1] == '-') --at;
                base[at] = 0; free(text);
            }
            if (!at) (void)snprintf(base,sizeof base,"%s",!strcmp(name,"heading") ? "section" : "index-entry");
            (void)snprintf(candidate,sizeof candidate,"%s",base);
            while ((used = mulib_docstrings_used_id_(p,&list,n,candidate)) == 1)
                (void)snprintf(candidate,sizeof candidate,"%s-%zu",base,++suffix);
            if (used < 0 || !mulib_docstrings_attr_(p,n,"id",candidate)) goto done;
        }
        if (!strcmp(name,"index-entry")) {
            const char *term = mulib_xml_attr(n,"term");
            if (!term || !*term) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_INVALID,"index entry requires a nonempty term"); goto done; }
            /* Reuse the bounded vector collector with leaf nodes only. */
            if (entries.count == entries.capacity) {
                size_t cap = entries.capacity ? entries.capacity * 2 : 16;
                mulib_dsdom_t **data = (mulib_dsdom_t **)realloc(entries.data,cap*sizeof *data);
                if (!data) { (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_MEMORY,"index entry allocation"); goto done; }
                entries.data = data; entries.capacity = cap;
            }
            entries.data[entries.count++] = n;
        }
    }
    if (entries.count > 1) qsort(entries.data,entries.count,sizeof *entries.data,mulib_docstrings_index_compare_);
    for (i = 0; i < list.count; ++i) {
        mulib_dsdom_t *n = list.data[i], *items;
        const char *name;
        int index;
        if (!n) continue;
        name = mulib_xml_name(n); index = !strcmp(name,"index");
        if (!index && strcmp(name,"toc")) continue;
        items = mulib_docstrings_node_(p,n,"list");
        if (!items || !mulib_docstrings_attr_(p,items,"ordered","false")) goto done;
        if (index) {
            for (j = 0; j < entries.count; ++j) if (!mulib_docstrings_index_link_(p,items,entries.data[j],1)) goto done;
        } else {
            for (j = 0; j < list.count; ++j)
                if (list.data[j] && !strcmp(mulib_xml_name(list.data[j]),"heading") && !mulib_docstrings_index_link_(p,items,list.data[j],0)) goto done;
        }
    }
    if (styles.length && !mulib_docstrings_style_(p,root,styles.data,styles.length,"css")) goto done;
    for (i = 0; i < list.count; ++i)
        if (list.data[i] && !strcmp(mulib_xml_name(list.data[i]),"stylesheet")) {
            mulib_xml_destroy(list.data[i]); list.data[i] = NULL;
        }
    if (!mulib_docstril_validate(root,p->ctx->options.nodes,p->ctx->options.output_bytes,&error)) {
        (void)mulib_docstrings_fail_(p,MULIB_DOCSTRINGS_LIMIT,error.message); goto done;
    }
    ok = 1;
done:
    mulib_strbuf_free(&styles); free(list.data); free(entries.data); return ok && !p->error.code;
}
static void mulib_docstrings_api_error_(mulib_docstrings_error_t *e, mulib_docstrings_status_t code, const char *message) {
    if (!e) return;
    memset(e,0,sizeof *e); e->code = code; e->line = e->column = 1;
    (void)snprintf(e->source,sizeof e->source,"<input>");
    (void)snprintf(e->message,sizeof e->message,"%s",message);
}
static int mulib_docstrings_enter_(mulib_docstrings_t *ctx, mulib_docstrings_parser_ *p,
    const char *source, size_t length, mulib_docstrings_error_t *error) {
    mulib_docstrings_api_error_(error,MULIB_DOCSTRINGS_OK,"");
    if (!ctx || ctx->busy || (!source && length)) {
        mulib_docstrings_api_error_(error,MULIB_DOCSTRINGS_INVALID,"invalid arguments or reentrant compiler operation"); return 0;
    }
    mulib_docstrings_start_(p,ctx); p->source = source; p->length = length;
    if (length > ctx->options.source_bytes || !mulib_xml_valid_text(source,length)) {
        mulib_docstrings_api_error_(error,length > ctx->options.source_bytes ? MULIB_DOCSTRINGS_LIMIT : MULIB_DOCSTRINGS_INVALID,"source size/UTF-8/XML validation failed"); return 0;
    }
    ctx->active = p; ctx->busy = 1; return 1;
}
static mulib_docstrings_status_t mulib_docstrings_leave_(mulib_docstrings_parser_ *p, mulib_docstrings_error_t *error) {
    if (error) *error = p->error;
    p->ctx->active = NULL; p->ctx->busy = 0; mulib_docstrings_macros_free_(p->macros);
    return p->error.code;
}
mulib_docstrings_t *mulib_docstrings_create(const mulib_docstrings_options_t *options) {
    mulib_docstrings_options_t o = {0};
    mulib_docstrings_t *ctx;
    if (options) o = *options;
    if (!o.source_bytes) o.source_bytes = 1024*1024;
    if (!o.output_bytes) o.output_bytes = 8*1024*1024;
    if (!o.nodes) o.nodes = 100000;
    if (!o.steps) o.steps = 1000000;
    if (!o.depth) o.depth = 64;
    if (!o.include_depth) o.include_depth = 16;
    if (o.source_bytes > 1024*1024 || o.output_bytes > 8*1024*1024 || o.nodes > 100000 || o.steps > 1000000 ||
        o.depth > 64 || o.include_depth > 16 || (o.flags & ~MULIB_DOCSTRINGS_TRUSTED_LUA)) return NULL;
    ctx = (mulib_docstrings_t *)calloc(1,sizeof *ctx); if (ctx) ctx->options = o; return ctx;
}
void mulib_docstrings_destroy(mulib_docstrings_t *ctx) {
    if (!ctx || ctx->busy) return;
    mulib_mune_state_destroy(ctx->lua); free(ctx);
}
mulib_docstril_t *mulib_docstrings_compile(mulib_docstrings_t *ctx, const char *source, size_t length, const char *format, mulib_docstrings_error_t *error) {
    mulib_docstrings_parser_ p;
    mulib_docstril_t *root;
    if (!mulib_docstrings_enter_(ctx,&p,source,length,error)) return NULL;
    root = mulib_docstril_create();
    if (!root) (void)mulib_docstrings_fail_(&p,MULIB_DOCSTRINGS_MEMORY,"DocstrIL root allocation");
    else if (!mulib_docstrings_parse_(&p,root,source,length,format) || !mulib_docstrings_finalize_(&p,root)) {
        if (!p.error.code) (void)mulib_docstrings_fail_(&p,MULIB_DOCSTRINGS_SYNTAX,"document compilation failed");
        mulib_xml_destroy(root); root = NULL;
    }
    (void)mulib_docstrings_leave_(&p,error); return root;
}
mulib_docstrings_status_t mulib_docstrings_extend(mulib_docstrings_t *ctx, const char *source, size_t length, mulib_docstrings_error_t *error) {
    mulib_docstrings_parser_ p;
    mulib_docstrings_error_t fallback;
    mulib_mune_result_t *result = NULL;
    mulib_mune_error_t e;
    if (!error) error = &fallback;
    if (!mulib_docstrings_enter_(ctx,&p,source,length,error)) return error->code;
    if (mulib_docstrings_lua_init_(&p) && mulib_mune_run_source(ctx->lua,source,length,&result,&e)) (void)mulib_docstrings_lua_error_(&p,&e);
    mulib_mune_result_destroy(result); return mulib_docstrings_leave_(&p,error);
}
mulib_mune_state_t *mulib_docstrings_lua(mulib_docstrings_t *ctx, mulib_docstrings_error_t *error) {
    mulib_docstrings_parser_ p;
    if (!mulib_docstrings_enter_(ctx,&p,NULL,0,error)) return NULL;
    (void)mulib_docstrings_lua_init_(&p); (void)mulib_docstrings_leave_(&p,error); return ctx->lua;
}
mulib_docstrings_status_t mulib_docstrings_filter(mulib_docstrings_t *ctx, mulib_docstril_t **document,
    const char *source, size_t length, const char *mode, mulib_docstrings_error_t *error) {
    mulib_docstrings_parser_ p;
    mulib_docstrings_error_t fallback;
    mulib_mune_result_t *filter = NULL, *result = NULL, *roots = NULL;
    mulib_mune_value_t module, apply, args[3];
    mulib_mune_error_t e;
    mulib_xml_error_t xe;
    mulib_docstril_t *replacement = NULL;
    if (!error) error = &fallback;
    if (!mulib_docstrings_enter_(ctx,&p,source,length,error)) return error->code;
    if (!mode) mode = "walk";
    if (!document || !*document || (strcmp(mode,"walk") && strcmp(mode,"document") && strcmp(mode,"tokens") && strcmp(mode,"events"))) {
        (void)mulib_docstrings_fail_(&p,MULIB_DOCSTRINGS_INVALID,"invalid document/filter mode"); goto done;
    }
    if (!mulib_docstril_validate(*document,ctx->options.nodes,ctx->options.output_bytes,&xe)) { (void)mulib_docstrings_fail_(&p,MULIB_DOCSTRINGS_INVALID,xe.message); goto done; }
    if (!mulib_docstrings_lua_init_(&p)) goto done;
    if (mulib_mune_run_source(ctx->lua,source,length,&filter,&e)) { (void)mulib_docstrings_lua_error_(&p,&e); goto done; }
    args[1] = mulib_mune_result_get(filter,0);
    if (args[1].type != (!strcmp(mode,"walk") ? MULIB_MUNE_TABLE : MULIB_MUNE_FUNCTION)) {
        (void)mulib_docstrings_fail_(&p,MULIB_DOCSTRINGS_LUA,"filter chunk returned the wrong filter type"); goto done;
    }
    roots = mulib_mune_result_create(ctx->lua);
    if (!roots || !mulib_docstrings_to_lua_(ctx->lua,*document,&args[0],0) || !mulib_mune_result_push(roots,args[0]) ||
        mulib_mune_make_string(ctx->lua,mode,strlen(mode),&args[2]) || !mulib_mune_result_push(roots,args[2]) ||
        mulib_mune_get_global(ctx->lua,"ldocstr",&module) || !mulib_docstrings_raw_(ctx->lua,module,"apply_filter",&apply)) {
        (void)mulib_docstrings_fail_(&p,MULIB_DOCSTRINGS_MEMORY,"filter snapshot allocation"); goto done;
    }
    if (mulib_mune_call(ctx->lua,apply,args,3,&result,&e)) { (void)mulib_docstrings_lua_error_(&p,&e); goto done; }
    replacement = mulib_docstrings_from_lua_(&p,mulib_mune_result_get(result,0),0);
    if (replacement && mulib_docstrings_finalize_(&p,replacement)) {
        mulib_xml_destroy(*document); *document = replacement; replacement = NULL;
    }
done:
    mulib_xml_destroy(replacement); mulib_mune_result_destroy(filter); mulib_mune_result_destroy(result); mulib_mune_result_destroy(roots);
    return mulib_docstrings_leave_(&p,error);
}
mulib_docstrings_status_t mulib_docstrings_style(mulib_docstrings_t *ctx, mulib_docstril_t **document,
    const char *source, size_t length, const char *format, mulib_docstrings_error_t *error) {
    mulib_docstrings_parser_ p;
    mulib_docstrings_error_t fallback;
    mulib_docstril_t *copy = NULL;
    mulib_xml_error_t e;
    if (format && !strcmp(format,"lua")) return mulib_docstrings_filter(ctx,document,source,length,"document",error);
    if (!error) error = &fallback;
    if (!mulib_docstrings_enter_(ctx,&p,source,length,error)) return error->code;
    if (!document || !*document) { (void)mulib_docstrings_fail_(&p,MULIB_DOCSTRINGS_INVALID,"invalid stylesheet document"); goto done; }
    if (!mulib_docstril_validate(*document,ctx->options.nodes,ctx->options.output_bytes,&e)) { (void)mulib_docstrings_fail_(&p,MULIB_DOCSTRINGS_INVALID,e.message); goto done; }
    copy = mulib_dsdom_clone(*document);
    if (!copy) { (void)mulib_docstrings_fail_(&p,MULIB_DOCSTRINGS_MEMORY,"stylesheet snapshot allocation"); goto done; }
    if (mulib_docstrings_style_(&p,copy,source,length,format) && mulib_docstril_validate(copy,ctx->options.nodes,ctx->options.output_bytes,&e)) {
        mulib_xml_destroy(*document); *document = copy; copy = NULL;
    } else if (!p.error.code) (void)mulib_docstrings_fail_(&p,MULIB_DOCSTRINGS_LIMIT,e.message);
done:
    mulib_xml_destroy(copy); return mulib_docstrings_leave_(&p,error);
}
static int mulib_docstrings_html_(const mulib_dsdom_t *n, mulib_strbuf_t *out, int in_svg, int in_inline, unsigned depth) {
    const char *name = mulib_xml_name(n), *tag = NULL, *value;
    const mulib_dsdom_t *c;
    size_t i;
    char heading[3] = "h1";
    int svg, leaf = 0, code = 0, inline_children = in_inline;
    static const char *const svg_tags[] = { "svg", "g", "title", "desc", "path", "rect", "circle", "ellipse", "line", "polyline", "polygon", "text", "tspan" };
    static const char *const svg_attrs[] = { "viewBox", "role", "x", "y", "x1", "x2", "y1", "y2", "cx", "cy", "r", "rx", "ry", "width", "height", "d", "points", "fill", "stroke", "stroke-width", "stroke-dasharray", "text-anchor", "font-size", "transform" };
    if (depth > MULIB_DOCSTRIL_MAX_DEPTH) return 0;
    if (!name) { value = mulib_xml_value(n); return mulib_xml_escape(out,value,strlen(value),0); }
    svg = in_svg || !strcmp(name,"svg");
    if (svg) {
        for (i = 0; i < sizeof svg_tags/sizeof svg_tags[0]; ++i) if (!strcmp(name,svg_tags[i])) tag = name;
        if (!tag) tag = "g";
    } else if (!strcmp(name,"docstril")) tag = "article";
    else if (!strcmp(name,"paragraph")) { tag = "p"; inline_children = 1; }
    else if (!strcmp(name,"heading")) { heading[1] = mulib_xml_attr(n,"level")[0]; tag = heading; inline_children = 1; }
    else if (!strcmp(name,"strong")) tag = "strong";
    else if (!strcmp(name,"emphasis")) tag = "em";
    else if (!strcmp(name,"underline")) tag = "u";
    else if (!strcmp(name,"strike")) tag = "s";
    else if (!strcmp(name,"superscript")) tag = "sup";
    else if (!strcmp(name,"subscript")) tag = "sub";
    else if (!strcmp(name,"code")) tag = "code";
    else if (!strcmp(name,"kbd")) tag = "kbd";
    else if (!strcmp(name,"code-block")) { tag = "pre"; code = 1; inline_children = 1; }
    else if (!strcmp(name,"blockquote")) tag = "blockquote";
    else if (!strcmp(name,"list")) { value = mulib_xml_attr(n,"ordered"); tag = value && !strcmp(value,"true") ? "ol" : "ul"; }
    else if (!strcmp(name,"item")) tag = "li";
    else if (!strcmp(name,"table")) tag = "table";
    else if (!strcmp(name,"row")) tag = "tr";
    else if (!strcmp(name,"cell")) { value = mulib_xml_attr(n,"header"); tag = value && !strcmp(value,"true") ? "th" : "td"; inline_children = 1; }
    else if (!strcmp(name,"link")) tag = "a";
    else if (!strcmp(name,"image")) { tag = "img"; leaf = 1; }
    else if (!strcmp(name,"break")) { tag = "br"; leaf = 1; }
    else if (!strcmp(name,"rule")) { tag = "hr"; leaf = 1; }
    else if (!strcmp(name,"toc") || !strcmp(name,"index")) tag = "nav";
    else if (!strcmp(name,"figure")) tag = "figure";
    else if (!strcmp(name,"directive")) tag = "aside";
    else if (!strcmp(name,"span") || !strcmp(name,"index-entry") || in_inline ||
        (mulib_xml_attr(n,"inline") && !strcmp(mulib_xml_attr(n,"inline"),"true"))) tag = "span";
    else tag = "div";
    if (!mulib_strbuf_putc(out,'<') || !mulib_strbuf_append(out,tag)) return 0;
    if (!strcmp(tag,"svg") && !mulib_strbuf_append(out," xmlns=\"http://www.w3.org/2000/svg\"")) return 0;
    for (i = 0; i < mulib_xml_attr_count(n); ++i) {
        const char *key = mulib_xml_attr_name(n,i);
        int allowed = !strcmp(key,"id") || !strcmp(key,"class") || !strcmp(key,"style") || !strcmp(key,"title");
        value = mulib_xml_attr_value(n,i);
        if (svg) { size_t j; for (j = 0; j < sizeof svg_attrs/sizeof svg_attrs[0]; ++j) if (!strcmp(key,svg_attrs[j])) allowed = 1; }
        if ((!strcmp(tag,"a") && !strcmp(key,"href")) || (!strcmp(tag,"img") && !strcmp(key,"src"))) allowed = mulib_docstrings_url_(value);
        if (!strcmp(tag,"img") && !strcmp(key,"alt")) allowed = 1;
        if (allowed && (!mulib_strbuf_putc(out,' ') || !mulib_strbuf_append(out,key) || !mulib_strbuf_append(out,"=\"") ||
            !mulib_xml_escape(out,value,strlen(value),1) || !mulib_strbuf_putc(out,'"'))) return 0;
    }
    if (leaf) return mulib_strbuf_append(out," />");
    if (!mulib_strbuf_putc(out,'>') || (code && !mulib_strbuf_append(out,"<code>"))) return 0;
    for (c = mulib_xml_first(n); c; c = mulib_xml_next(c)) if (!mulib_docstrings_html_(c,out,svg,inline_children,depth+1)) return 0;
    return (!code || mulib_strbuf_append(out,"</code>")) && mulib_strbuf_append(out,"</") && mulib_strbuf_append(out,tag) && mulib_strbuf_putc(out,'>');
}
char *mulib_docstrings_render(const mulib_docstril_t *document, const char *format, size_t *length, mulib_docstrings_error_t *error) {
    mulib_xml_error_t e;
    mulib_strbuf_t b;
    char *text = NULL;
    if (length) *length = 0;
    mulib_docstrings_api_error_(error,MULIB_DOCSTRINGS_OK,"");
    if (!mulib_docstril_validate(document,0,0,&e)) { mulib_docstrings_api_error_(error,MULIB_DOCSTRINGS_INVALID,e.message); return NULL; }
    if (!format || !strcmp(format,"xml")) text = mulib_xml_serialize(document,length);
    else if (!strcmp(format,"pandoc")) text = mulib_pandocast_serialize(document,length,&e);
    else if (!strcmp(format,"html")) {
        mulib_strbuf_init(&b);
        if (mulib_docstrings_html_(document,&b,0,0,0)) { text = b.data; if (length) *length = b.length; }
        else mulib_strbuf_free(&b);
    } else { mulib_docstrings_api_error_(error,MULIB_DOCSTRINGS_INVALID,"unknown output format"); return NULL; }
    if (!text) mulib_docstrings_api_error_(error,MULIB_DOCSTRINGS_MEMORY,"document output allocation/conversion failed");
    return text;
}
