"""Build real unsafe FFI test modules, then exercise the independent RT ABI.

There is no canonical module publication CLI yet. This test uses W10's native
plan, emitter and ABI probe as build-time helpers, not its executable lock or
review artifacts. Nothing here is an artifact producer for consumers.
"""

import hashlib
from pathlib import Path
import sys
from tempfile import TemporaryDirectory
from types import SimpleNamespace

TESTS = Path(__file__).resolve().parent
RT = TESTS.parent
ON1X = RT.parent
sys.path.insert(0, str(ON1X / "tools"))
from on1x_ffi_native import Build, capture, check_elf, probe_source


def check(mode, build, cc, on1xc, rt):
    source = TESTS / "ffi_embed.on1x"
    shim = TESTS / "ffi_embed_provider.c"
    host = TESTS / "ffi_embedding.c"
    with TemporaryDirectory(prefix=f"rt-ffi-{mode}-", dir=build) as work:
        stage = Path(work).resolve()
        staged_c = stage / "fixture.c"
        options = SimpleNamespace(cc=cc, ffi_provider="host", ffi_adapter_provider=None,
                                  cflag=["-O2"])
        command = [on1xc, "--emit-c", source, "-o", staged_c, "--no-prelude"]
        plan = Build(options, command, ON1X.parent, stage)
        if plan.safe or plan.dynamic:
            raise ValueError("the fixture requires lexical unsafe and one static FFI partition")
        if not any(d["module"] == "mulib.clamp" and d["member"] == "add_i64"
                   for d in plan.descriptors):
            raise ValueError("expected the compiler-owned clamp descriptor")

        for path in (Path(__file__), host, rt):
            plan.inputs.add(path)
        shim_digest = plan.inputs.add(shim)
        # RT's separate descriptor identity is not a file hash or any proof
        # of admission. Bind actual fixture source and its explicit C shim.
        source_digest = plan.inputs.add(source)
        identity = hashlib.sha256(bytes.fromhex(source_digest + shim_digest)).hexdigest()

        plan.host_flags += ["-fPIC", "-fvisibility=hidden"]
        links = plan.prepare()
        probe, comparisons = probe_source(plan.descriptors)
        if not comparisons:
            raise ValueError("the native ABI probe has no comparisons")
        probe_c = stage / "probe.c"
        probe_c.write_text(probe, encoding="ascii")
        plan.inputs.add(probe_c)
        plan.deps(probe_c, plan.host_flags)
        plan.host(*plan.host_flags, probe_c, plan.runtime, *links, "-o", "probe")
        plan.inputs.add(stage / "probe")
        capture([stage / "probe"], stage)

        capture([*command, "--kernel-c11", "--ffi-stage"], stage)
        private_flags = [*plan.host_flags, "-I", str(plan.runtime.parent)]
        # C11 source currently requires a main even in staging. Rename the
        # unused entry when compiling this test TU, not in generated bytes.
        checked_o = plan.compile("host", staged_c.name, "fixture.o", *private_flags,
                                 "-DON1X_KERNEL_ABI_V1=1", "-Dmain=on1x_rt_ffi_unused_entry")
        sdk_flags = [*private_flags, "-I", str(RT / "include")]
        import_flags = [str(rt), "-pthread", "-ldl"]
        if ".so" in rt.name:
            import_flags.append(f"-Wl,-rpath,{rt.parent}")
        shim_flags = [*sdk_flags, f'-DON1X_RT_FFI_TEST_IDENTITY="{identity}"']
        plan.deps(shim, shim_flags)
        plan.deps(plan.runtime, private_flags)
        plan.host(*shim_flags, "-c", shim, "-o", "shim.o")
        plan.inputs.add(stage / "shim.o")
        plan.host(*private_flags, "-c", plan.runtime, "-o", "runtime.o")
        plan.inputs.add(stage / "runtime.o")
        objects = [checked_o, "shim.o", "runtime.o", *links]

        if mode == "static":
            host_flags = [*sdk_flags, "-DON1X_RT_FFI_TEST_STATIC=1"]
            plan.deps(host, host_flags)
            plan.host(*host_flags, host, *objects, *import_flags, "-o", "host")
            arguments = [identity]
        elif mode == "dynamic":
            module = stage / "ffi_embed.so"
            plan.host("-shared", "-Wl,-z,defs", *objects, *import_flags, "-o", module)
            check_elf(module, 3)
            digest = hashlib.sha256(module.read_bytes()).hexdigest()
            plan.inputs.add(module, digest)
            mutated = stage / "changed.so"
            mutated.write_bytes(module.read_bytes() + b"\x01")
            plan.deps(host, sdk_flags)
            plan.host(*sdk_flags, host, *import_flags, "-o", "host")
            arguments = [identity, module, digest, mutated]
        else:
            raise ValueError(f"invalid fixture mode: {mode}")

        plan.inputs.add(stage / "host")
        plan.check_sources()
        capture([stage / "host", *arguments], stage)
        print(f"{mode}: {comparisons} native ABI comparisons; RT ABI 1 lifecycle passed")
        if mode == "dynamic":
            print(f"authorized fixture SHA-256: {digest}")


if __name__ == "__main__":
    mode, build, cc, on1xc, rt = sys.argv[1:]
    check(mode, Path(build), cc, Path(on1xc), Path(rt))
