#!/usr/bin/env python3
"""Deterministically regenerate ScalarABI.c; no third-party dependencies."""
from pathlib import Path
import argparse
import sys

TYPES = {"i64": "int64_t", "bool": "bool", "f64": "double", "f32": "float", "u8": "uint8_t", "u16": "uint16_t", "u32": "uint32_t", "u64": "uint64_t"}
rows = {}

def add(name, args, result):
    assert name not in rows, name
    rows[name] = (args, result)

for f in ('f64', 'f32'):
    for op in ('add', 'sub', 'mul', 'div', 'eq', 'ne', 'lt', 'le', 'gt', 'ge'):
        add(f'{op}_{f}', [f, f], 'bool' if op in ('eq','ne','lt','le','gt','ge') else f)
    add(f'neg_{f}', [f], f)
    for op in ('from_i64', 'from_bits'):
        add(f'{f}_{op}', ['i64'], f)
    for op in ('to_i64', 'to_bits'):
        add(f'{f}_{op}', [f], 'i64')
    for op in ('is_nan', 'is_finite', 'signbit'):
        add(f'{f}_{op}', [f], 'bool')
add('f32_from_f64', ['f64'], 'f32')
add('f64_from_f32', ['f32'], 'f64')

U = ('u8', 'u16', 'u32', 'u64')
for t in U:
    for op in ('add', 'sub', 'mul', 'div', 'mod'):
        add(f'{op}_{t}', [t, t], t)
    for op in ('from_i64', 'from_bits'):
        add(f'{t}_{op}', ['i64'], t)
    for op in ('to_i64', 'to_bits'):
        add(f'{t}_{op}', [t], 'i64')
    for op in ('wrapping_add', 'wrapping_sub', 'wrapping_mul', 'and', 'or', 'xor'):
        add(f'{t}_{op}', [t, t], t)
    for op in ('not',):
        add(f'{t}_{op}', [t], t)
    for op in ('shl', 'shr'):
        add(f'{t}_{op}', [t, 'i64'], t)
    for source in U:
        add(f'{t}_from_{source}', [source], t)
    for f in ('f32', 'f64'):
        add(f'{t}_from_{f}', [f], t)
        add(f'{f}_from_{t}', [t], f)

header = '''/* Generated by generate_scalar_abi.py. Do not hand-edit. */
/* All arguments/results use the integer LP64 calling convention, including
 * IEEE floating payloads. This is intentionally a separate ABI from the C
 * On1x runtime, whose floating arguments use FP registers on AMD64. */
#include <on1x_runtime.h>
#if defined(__FAST_MATH__) || (defined(__FINITE_MATH_ONLY__) && __FINITE_MATH_ONLY__ > 0) || \
    defined(__NO_SIGNED_ZEROS__) || defined(__ASSOCIATIVE_MATH__) || defined(__RECIPROCAL_MATH__)
#error "On1x numeric wrappers forbid relaxed floating-point semantics"
#endif
#include <stdint.h>
#include <string.h>
#include <limits.h>
#if CHAR_BIT != 8 || UINT64_MAX != 18446744073709551615ULL
#error "Archon ScalarABI requires 64-bit words and eight-bit bytes"
#endif
_Static_assert(sizeof(void *) == 8 && sizeof(long) == 8 && sizeof(size_t) == 8,
               "Archon ScalarABI requires an LP64 target");
_Static_assert(sizeof(int64_t) == 8 && INT64_MIN == (-INT64_MAX - 1),
               "Archon ScalarABI requires two's-complement i64");
static uint64_t enc_i64(int64_t v) { uint64_t b; memcpy(&b, &v, 8); return b; }
static int64_t dec_i64(uint64_t b) { int64_t v; memcpy(&v, &b, 8); return v; }
#if defined(ON1X_F64_ABI_VERSION)
_Static_assert(ON1X_F64_ABI_VERSION == 1 && sizeof(double) == 8,
               "Archon ScalarABI requires On1x binary64 ABI v1");
static uint64_t enc_f64(double v) { uint64_t b; memcpy(&b, &v, 8); return b; }
static double dec_f64(uint64_t b) { double v; memcpy(&v, &b, 8); return v; }
void on1x_archon_print_f64(uint64_t bits) { on1x_print_f64(dec_f64(bits)); }
#endif
#if defined(ON1X_F32_ABI_VERSION)
_Static_assert(ON1X_F32_ABI_VERSION == 1 && sizeof(float) == 4,
               "Archon ScalarABI requires On1x binary32 ABI v1");
static uint64_t enc_f32(float v) { uint32_t b; memcpy(&b, &v, 4); return (uint64_t)b; }
static float dec_f32(uint64_t b) { uint32_t lo=(uint32_t)b; float v; memcpy(&v, &lo, 4); return v; }
void on1x_archon_print_f32(uint64_t bits) { on1x_print_f32(dec_f32(bits)); }
#endif
'''

def decode(t, v):
    if t in ('i64','f32','f64'): return f'dec_{t}({v})'
    if t == 'bool': return f'({v} != 0)'
    return f'({TYPES[t]}){v}'

def encode(t, expr):
    if t in ('i64','f32','f64'): return f'enc_{t}({expr})'
    return f'(uint64_t)({expr})'

def feature_for(args, result):
    types = (*args, result)
    # The runtime declares *both* unsigned/float conversion families inside
    # ON1X_F32_ABI_VERSION (ON1X_UFLOAT_DECL), including f64 conversions.
    if 'f32' in types or ('f64' in types and any(t in U for t in types)):
        return 'f32'
    return 'f64' if 'f64' in types else None


def generate():
    out = [header]
    for name, (args, result) in sorted(rows.items()):
        feature = feature_for(args, result)
        if feature:
            out.append(f'#if defined(ON1X_{feature.upper()}_ABI_VERSION)\n')
        params = ', '.join(f'uint64_t a{i}' for i in range(len(args))) or 'void'
        values = ', '.join(decode(t, f'a{i}') for i, t in enumerate(args))
        out.append(f'uint64_t on1x_archon_{name}({params}) {{\n'
                   f'    return {encode(result, f"on1x_{name}({values})")};\n'
                   f'}}\n')
        if feature:
            out.append('#endif\n')
    return ''.join(out)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    path = Path(__file__).with_name('ScalarABI.c')
    generated = generate()
    if options.check:
        if not path.exists() or path.read_text(encoding='utf-8') != generated:
            sys.exit('ScalarABI.c is out of date: regenerate with python3 generate_scalar_abi.py')
    else:
        path.write_text(generated, encoding='utf-8')
    print(f'{path.name}: {len(rows)} scalar ABI adapters')


if __name__ == '__main__':
    main()
