#!/usr/bin/env python3
"""Regenerate/check the C dispatcher using the real, pinned vmweave-cli."""
import argparse
import hashlib
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parent
cli = argparse.ArgumentParser(description=__doc__)
cli.add_argument('generator', type=Path)
cli.add_argument('--check', action='store_true')
args = cli.parse_args()
with tempfile.TemporaryDirectory() as tmp:
    subprocess.run([args.generator.resolve(), '--generate', '-o', tmp, 'On1xVM.lua'],
                   cwd=root, check=True, timeout=120)
    files = {('snapshot/' + p.name): p.read_bytes() for p in sorted(Path(tmp).iterdir())}
    pins = {'On1xVM.lua': (root/'On1xVM.lua').read_bytes(), **files}
    manifest = ['# Generated by regen.py; verify the Lua input and every compiled VMWeave output.',
                'function(_vm_pin path digest)',
                '  file(SHA256 "${CMAKE_CURRENT_SOURCE_DIR}/${path}" actual)',
                '  if(NOT actual STREQUAL digest)',
                '    message(FATAL_ERROR "Stale On1x VMWeave snapshot: ${path}; run regen.py with vmweave-cli")',
                '  endif()', 'endfunction()']
    manifest += [f'_vm_pin("{p}" "{hashlib.sha256(data).hexdigest()}")' for p, data in pins.items()]
    files['snapshot.cmake'] = ('\n'.join(manifest) + '\n').encode()
    for name, data in files.items():
        out = root/name
        if args.check:
            if out.read_bytes() != data:
                raise SystemExit('stale VMWeave output: ' + name)
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_bytes(data)
