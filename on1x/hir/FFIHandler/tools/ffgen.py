IDENT = re.compile(r"[A-Za-z_][A-Za-z_0-9]{0,95}\Z", re.ASCII)
REASON = re.compile(r"[a-z][a-z0-9_]{0,95}\Z", re.ASCII)
FINGERPRINT = re.compile(r"[0-9a-f]{64}\Z", re.ASCII)
MAX_EXPORTS = 256
MAX_GUARDS = 16
MAX_DOCUMENT = 64 * 1024
INDEX_SCHEMA = "on1x.stdffi.mulib/v1"


class GenerationError(ValueError):
    """Unsafe to publish (as distinct from an explicit unsupported outcome)."""


@dataclass(frozen=True)
class GuardDelta:
    fingerprint: str
    guards: tuple[tuple[int, int], ...]


@dataclass(frozen=True)
class Override:
    target: tuple[str, str, str, str]
    module: str
    selections: tuple[str, ...] = ()
    deltas: dict[str, GuardDelta] = field(default_factory=dict)
    obligations: tuple[str, ...] = ()


@dataclass(frozen=True)
class Generation:
    document: bytes
    metadata: dict


def _sha(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def _parser_identity(raw: bytes, grammar_sha: str) -> str:
    """Hash genuine LLSynth Python output without its diagnostic source paths."""
    pattern = rb'^SPEC = json\.loads\(base64\.b64decode\("([A-Za-z0-9+/=]+)"\)\)$'
    matches = list(re.finditer(pattern, raw, re.MULTILINE))
    if len(matches) != 1:
        raise GenerationError("expected an LLSynth generated Python parser")
    match = matches[0]
    try:
        spec = json.loads(base64.b64decode(match[1], validate=True))
        dependencies = spec["dependencies"]
        # FFIHandler is a single self-contained grammar. If that changes,
        # bind all additional grammar inputs explicitly before using them.
        (grammar,) = dependencies
        if (not isinstance(spec["file"], str) or set(grammar) != {"path", "sha256"}
                or not isinstance(grammar["path"], str) or grammar["sha256"] != grammar_sha):
            raise ValueError
        spec["file"] = "FFIHandler.llsynth"
        grammar["path"] = "FFIHandler.llsynth"
    except (KeyError, TypeError, ValueError) as exc:
        raise GenerationError("LLSynth parser does not bind the selected FFIHandler grammar") from exc
    payload = json.dumps(spec, ensure_ascii=True, sort_keys=True, separators=(",", ":")).encode("ascii")
    return _sha(raw[:match.start(1)] + base64.b64encode(payload) + raw[match.end(1):])


def _member(module: str) -> str:
    ns, dot, name = module.partition(".")
    if ns != "mulib" or not dot or not IDENT.fullmatch(name):
        raise GenerationError(f"invalid canonical module identity: {module}")
    return name


def _validate_entry(entry) -> None:
    _member(entry.module)
    # The actual normalization comes from W04's canonical planner, not here.
    if not re.fullmatch(r"[a-z0-9][a-z0-9_+-]{0,95}", entry.key, re.ASCII):
        raise GenerationError("invalid manifest key")
    if (entry.filename != f"{entry.key}.ffi" or
            entry.header != f"mulib-{entry.key}.h" or
            entry.reserved_prefix != f"mulib_{_member(entry.module)}_"):
        raise GenerationError(f"inconsistent canonical module recipe: {entry.key}")


def _header(entry, target: tuple[str, str, str, str]) -> list[str]:
    triple, model, abi, cc = target
    return [
        "# GENERATED by ffgen; edit the canonical header or authored override.",
        "ffi 2;",
        f"target {json.dumps(triple)} {model} {json.dumps(abi)} {cc};",
        f"foreign {entry.module} {{",
        f"    provider mulib {json.dumps(entry.key)};",
        f"    header {json.dumps(entry.header)};",
    ]


def _document(entry, target, lines=(), *, unavailable=None) -> bytes:
    if unavailable is not None:
        if lines or not REASON.fullmatch(unavailable):
            raise GenerationError("invalid unavailable module outcome")
        lines = (f"    unavailable reason {unavailable};",)
    return ("\n".join([*_header(entry, target), *lines, "}", ""])).encode("ascii")


def failed_module(entry, target, reason, *, override: Override | None = None) -> Generation:
    """An attempted projection failed. An authored delta must not be lost."""
    _validate_entry(entry)
    obligations = _check_override(entry, target, override)
    if override is not None and (override.selections or override.deltas):
        raise GenerationError(f"{entry.key}: cannot verify override after {reason}")
    return Generation(_document(entry, target, unavailable=reason), {
        "status": "failed", "attempted": True, "projected": False, "reason": reason,
        "symbols": [], "native_tags": [], "obligations": obligations,
        "normalized_signature_sha256": None,
    })


def display_names(names) -> tuple[str, ...]:
    """Keep unique valid spellings; disambiguate generated names by position."""
    counts = Counter(names)
    reserved = {name for name in names
                if name is not None and IDENT.fullmatch(name) and counts[name] == 1}
    result = []
    for index, name in enumerate(names):
        if name not in reserved or counts[name] != 1:
            base = f"arg{index}"
            name = base
            suffix = 0
            while name in reserved:
                suffix += 1
                name = f"{base}_{suffix}"
            reserved.add(name)
        result.append(name)
    return tuple(result)


def _merge_guard(entry, symbol, native_fingerprint, surface_parameters,
                 delta: GuardDelta) -> tuple[tuple[int, int], ...]:
    if not FINGERPRINT.fullmatch(delta.fingerprint) or delta.fingerprint != native_fingerprint:
        raise GenerationError(f"{entry.key}: stale native signature for {symbol}")
    if not 0 < len(delta.guards) <= MAX_GUARDS:
        raise GenerationError(f"{entry.key}: invalid guard count for {symbol}")
    seen = set()
    for lhs, rhs in delta.guards:
        if (type(lhs) is not int or type(rhs) is not int or
                not 0 <= lhs < len(surface_parameters) or not 0 <= rhs < len(surface_parameters)):
            raise GenerationError(f"{entry.key}: invalid guard position for {symbol}")
        a, b = surface_parameters[lhs], surface_parameters[rhs]
        if a != b or a not in INTEGRAL_SURFACES:
            raise GenerationError(f"{entry.key}: guard requires matching integral types for {symbol}")
        if (lhs, rhs) in seen:
            raise GenerationError(f"{entry.key}: duplicate guard for {symbol}")
        seen.add((lhs, rhs))
    return delta.guards


def _more_specific_prefix(symbol, prefix, reserved_prefixes) -> bool:
    minimum = len(prefix) if symbol.startswith(prefix) else 0
    return any(symbol[:i + 1] in reserved_prefixes
               for i in range(minimum, len(symbol) - 1) if symbol[i] == "_")


def _ownership(symbol, entry, selections, origins, owned_headers, reserved_prefixes):
    if _more_specific_prefix(symbol, entry.reserved_prefix, reserved_prefixes):
        return "excluded", "reserved_other_module"
    known = frozenset(origins.get(symbol, ()))
    if known and known.isdisjoint(owned_headers):
        return "excluded", "foreign_origin"
    if known - owned_headers:
        return "discovery_only", "ambiguous_export"
    if symbol in selections:
        return "owned", "audited_selection"
    if known and known <= owned_headers:
        return "owned", "verified_origin"
    return "discovery_only", "ambiguous_export"


def _primitive_text(native) -> str:
    if native[0] == "void":
        return "void"
    return native[0] + "(" + ",".join(map(str, native[1:])) + ")"


def _render_fn(row) -> list[str]:
    surface = row["surface"]
    native = row["native_type"]
    params = ", ".join(f"{name}: {typ}" for name, typ in
                       zip(row["parameter_names"], surface["parameters"], strict=True))
    native_params = ", ".join(map(_primitive_text, native[4]))
    guards = "".join(f" requires {lhs} <= {rhs}" for lhs, rhs in row["guards"])
    return [
        f'    fn {row["member"]}({params}) -> {surface["result"]} = c::{row["symbol"]}',
        f'        native {row["linkage"]} {row["definition"]} ({native_params})',
        f'        -> {_primitive_text(native[3])} profile scalar{guards};',
    ]


def _c11_evidence(function, syntax):
    facts = []
    if "noreturn" in function.specifiers:
        facts.append(ffic.C11Fact.DECLARED_NORETURN.value)
    if function.definition == "inline-only":
        facts.append(ffic.C11Fact.INLINE_ONLY.value)
    if syntax.has_body:
        facts.append(ffic.C11Fact.SYNTAX_BODY.value)
    return dict(source=ffic.C11_EVIDENCE_SOURCE, facts=facts) if facts else None


def _check_override(entry, target, override: Override | None) -> list[str]:
    if override is None:
        return []
    if override.target != target or override.module != entry.module:
        raise GenerationError(f"{entry.key}: override target/module mismatch")
    if len(set(override.obligations)) != len(override.obligations) or any(
            not REASON.fullmatch(code) for code in override.obligations):
        raise GenerationError(f"{entry.key}: invalid discovery obligation")
    return sorted(override.obligations)


def generate_module(entry, interface, target, *, override: Override | None = None, syntax=None,
                     origins=None, owned_headers=(), reserved_prefixes=()) -> Generation:
    """Map one validated projection; caller supplies only *verified* origins.

    The interface format has no origin. The default without an authored
    selection or verified origin is deliberately non-callable discovery.
    """
    _validate_entry(entry)
    require_target(interface, target)
    syntax_by_name = None if syntax is None else pair_with_interface(syntax, interface)
    origins = origins or {}
    owned_headers = frozenset(owned_headers) | {entry.header_path}
    reserved_prefixes = frozenset(reserved_prefixes)
    obligations = _check_override(entry, target, override)
    selections = frozenset(override.selections if override else ())
    if override is not None and len(selections) != len(override.selections):
        raise GenerationError(f"{entry.key}: duplicate audited selection")
    deltas = override.deltas if override else {}
    pending_selections, pending_deltas = set(selections), set(deltas)
    graph = NativeGraph(interface.tags)
    rows, rendered = [], []
    used_members = set()
    prefix = entry.reserved_prefix
    for function in sorted(interface.functions, key=lambda fn: fn.name):
        symbol = function.name
        if symbol.startswith(prefix):
            member = symbol[len(prefix):]
        elif symbol in selections and ffic.symbol_allowed(entry.module, symbol):
            # W05's exact container-core exception; never reserve mulib_ct_*.
            member = symbol.removeprefix("mulib_ct_")
        else:
            continue
        if function.calling_convention != target[3]:
            raise GenerationError(f"{entry.key}: mismatched projected calling convention")
        ownership, evidence = _ownership(
            symbol, entry, selections, origins, owned_headers, reserved_prefixes)
        if ownership == "owned":
            pending_selections.discard(symbol)
        row = {
            "member": member, "symbol": symbol, "status": ownership,
            "ownership": evidence, "reason": None,
            "native_type": graph.type(function.type),
            "linkage": function.linkage, "definition": function.definition,
            "calling_convention": function.calling_convention,
            "storage": list(function.storage), "specifiers": sorted(function.specifiers),
            "original_parameter_names": list(function.parameter_names),
            "parameter_names": list(display_names(function.parameter_names)),
            "surface": None, "native_fingerprint": None, "guards": [], "emitted": False,
        }
        rows.append(row)
        if ownership == "excluded":
            row["reason"] = evidence
            continue
        if not IDENT.fullmatch(member) or not IDENT.fullmatch(symbol):
            row.update(status="unsupported", reason="identifier_unrepresentable")
            continue
        if member in used_members:
            raise GenerationError(f"{entry.key}: canonical member collision: {member}")
        used_members.add(member)
        if ownership == "discovery_only":
            reason = evidence
        elif entry.implementation == "static-data":
            reason = "data_only_module"
        else:
            mapping = represent(function, target)
            reason = mapping.reason
            if (reason is None and mapping.placement == "external" and
                    entry.implementation == "static-inline"):
                reason = "external_without_implementation"
        if reason is not None:
            row.update(status="discovery_only" if reason == "ambiguous_export" else "unsupported",
                       reason=reason)
            rendered.append(f"    unsupported {member} = c::{symbol} reason {reason};")
            row["emitted"] = True
            continue
        native = row["native_type"]
        fingerprint = ffic.native_fingerprint(
            target, symbol, function.linkage, function.definition, native[4], native[3])
        row.update(status="representable", native_fingerprint=fingerprint,
                   surface={"parameters": list(mapping.surface_parameters),
                            "result": mapping.surface_result})
        if symbol in deltas:
            row["guards"] = [list(pair) for pair in _merge_guard(
                entry, symbol, fingerprint, mapping.surface_parameters, deltas[symbol])]
            pending_deltas.remove(symbol)
        rendered.extend(_render_fn(row))
        row["emitted"] = True

    if pending_selections:
        raise GenerationError(f"{entry.key}: stale or unowned selection: {min(pending_selections)}")
    if pending_deltas:
        raise GenerationError(f"{entry.key}: stale or ineligible override: {min(pending_deltas)}")

    tags = graph.tags()
    signature_rows = [[row[key] for key in ("symbol", "linkage", "definition",
                                           "specifiers", "native_type")] for row in rows]
    reason = None
    if not rendered:
        reason = "data_only_module" if entry.implementation == "static-data" else "no_owned_exports"
    elif len(used_members) > MAX_EXPORTS:
        reason = "module_export_limit"
    if reason is None and syntax_by_name is not None:
        functions = {fn.name: fn for fn in interface.functions}
        for row in rows:
            if not row["emitted"]:
                continue
            symbol = row["symbol"]
            evidence = _c11_evidence(functions[symbol], syntax_by_name[symbol])
            if evidence:
                row["c11_evidence"] = evidence
                facts = " ".join(evidence["facts"])
                rendered.append(f'    evidence c::{symbol} {evidence["source"]} ({facts});')
    document = _document(entry, target, rendered) if reason is None else b""
    if len(document) > MAX_DOCUMENT:
        reason = "module_byte_limit"
    if reason is not None:
        if reason.startswith("module_") and deltas:
            raise GenerationError(f"{entry.key}: cannot emit authored override after {reason}")
        document = _document(entry, target, unavailable=reason)
        for row in rows:
            row["emitted"] = False
            row.pop("c11_evidence", None)
    elif any(row["status"] == "representable" for row in rows):
        status = "representable"
    elif any(row["status"] == "discovery_only" for row in rows):
        status = "discovery_only"
    else:
        status = "unsupported"
    return Generation(document, {
        "status": "unsupported" if reason is not None else status,
        "attempted": True, "projected": True, "reason": reason,
        "declaration_count": len(interface.declarations),
        "function_count": len(interface.functions),
        "symbols": rows, "native_tags": tags, "obligations": obligations,
        "normalized_signature_sha256": digest(["on1x.ffi-projection/v1", target,
                                                signature_rows, tags]),
    })


def _reason_code(prefix, code) -> str:
    if not isinstance(code, str):
        raise GenerationError("provider did not return a stable failure reason")
    reason = prefix + code.replace("-", "_")
    if not REASON.fullmatch(reason):
        raise GenerationError("provider did not return a stable failure reason")
    return reason


def _override_inputs(directory: Path, inventory) -> dict[str, bytes]:
    if not directory.exists() and not directory.is_symlink():
        return {}
    if directory.is_symlink() or not directory.is_dir():
        raise GenerationError("override directory must be a real directory")
    known = {entry.filename for entry in inventory.entries}
    overrides = {}
    for path in directory.iterdir():
        if path.suffix != ".ffi":
            continue
        if path.name not in known:
            raise GenerationError(f"override for unregistered module: {path.name}")
        overrides[path.name] = ffic.read(path)
    return overrides


def _parse_override(parser, raw, path) -> Override:
    parsed = ffic.parse_overrides(parser, raw, path)
    return Override(parsed.target, parsed.module, tuple(parsed.selections),
                    {symbol: GuardDelta(delta["fingerprint"], tuple(map(tuple, delta["guards"])))
                     for symbol, delta in parsed.overrides.items()}, tuple(parsed.obligations))


def _counts(records, unattempted) -> dict:
    try:
        modules = Counter(row["status"] for row in records)
        symbols = Counter(symbol["status"] for row in records for symbol in row["symbols"])
        return {
            "registered_modules": len(records) + len(unattempted),
            "attempted_modules": sum(row["attempted"] for row in records),
            "projected_modules": sum(row["projected"] for row in records),
            "unattempted_modules": len(unattempted),
            "module_outcomes": dict(sorted(modules.items())),
            "symbol_outcomes": dict(sorted(symbols.items())),
            "projected_functions": sum(row.get("function_count", 0) for row in records),
            "non_candidate_functions": sum(row.get("function_count", 0) - len(row["symbols"])
                                           for row in records),
            "owned_functions": sum(symbol["ownership"] in ("audited_selection", "verified_origin")
                                   for row in records for symbol in row["symbols"]),
            "emitted_scalar_candidates": sum(
                symbol["status"] == "representable" and symbol["emitted"]
                for row in records for symbol in row["symbols"]),
        }
    except (KeyError, TypeError) as exc:
        raise GenerationError("prior generation metadata is malformed; run --all") from exc


def _check_public_header(root, entry, provider):
    # Keep the planner's raw TU/feature profile, but do not let its include
    # resolve to an alternate file (even if it is the only search result).
    header = provider.check_public_header(entry.header)
    if header != root / entry.header_path:
        raise GenerationError(f"{entry.key}: projected header is not the canonical manifest header")


def _run(args) -> None:
    from cephyr_interface import InterfaceError, decode_interface
    import ffi_inventory
    import ffi_publish
    from project_interface import CephyrProvider, ProjectionError

    target = target_identity(args.target)
    root = args.mulib_root.resolve(strict=True)
    output = args.output.absolute()
    if output.is_symlink():
        raise GenerationError("output must not be a symbolic link")
    output = output.resolve()
    override_dir = args.overrides or (root / "on1x/stdffi/overrides/mulib")
    if output.is_relative_to(override_dir.resolve()):
        raise GenerationError("output overlaps authored overrides")
    tools = Path(__file__).resolve().parent
    toolchain = (
        tools / "ffgen.py", tools / "ffi_types.py", tools / "cephyr_interface.py", tools / "cephyr_syntax.py",
        tools / "project_interface.py", tools / "ffi_inventory.py", tools / "ffi_publish.py",
        tools / "ffi_plan.py", tools / "ffic.py", tools.parent / "FFIHandler.llsynth",
    )
    snapshots = {path: _sha(path.read_bytes()) for path in toolchain}
    parser_source = ffic.read(args.parser, 4 * 1024 * 1024)
    snapshots[args.parser] = _sha(parser_source)
    generation = {
        "tools": {path.name: snapshots[path] for path in toolchain},
        "parser_identity_sha256": _parser_identity(parser_source, snapshots[toolchain[-1]]),
    }
    protected_paths = (root, root / "include", root / "MANIFEST.yaml", override_dir.resolve(),
                       *snapshots, args.cephyr.resolve(), args.scratch_root.resolve(),
                       *(path.resolve() for path in (*args.system_include_dir, *args.tool_input)),
                       *((args.sysroot.resolve(),) if args.sysroot else ()))
    if any(path.is_relative_to(output) for path in protected_paths):
        raise GenerationError("output overlaps a protected input or scratch root")
    for path in protected_paths[1:]:
        if path.is_dir() and output.is_relative_to(path):
            raise GenerationError("output is inside a protected input or scratch root")
    if args.target != "x86_64-linux-gnu" and output == root / "on1x/stdffi/mulib":
        raise GenerationError("canonical stdffi output only supports x86_64-linux-gnu")

    inventory = ffi_inventory.load(root)
    if args.all:
        entries = inventory.entries
    else:
        if args.kernel not in inventory.by_key:
            raise GenerationError(f"unknown manifest module: {args.kernel}")
        entries = (inventory.by_key[args.kernel],)
    raw_overrides = _override_inputs(override_dir, inventory)
    parser = ffic.load_parser(args.parser)
    selected_overrides = {
        entry.key: _parse_override(parser, raw_overrides[entry.filename],
                                   override_dir / entry.filename)
        for entry in entries if entry.filename in raw_overrides
    }
    prefixes = frozenset(entry.reserved_prefix for entry in inventory.entries)

    providers = {}
    profiles = {}
    observed_profiles = {}
    provider_lock = Lock()
    staged_bytes = {"files": 0, "records": 0}
    budget_lock = Lock()

    def provider_for(plan):
        key = (plan.include_dirs, plan.defines)
        with provider_lock:
            if key not in providers:
                provider = CephyrProvider(
                    args.cephyr, args.target, libstone_revision=args.libstone_revision,
                    scratch_root=args.scratch_root, include_dirs=plan.include_dirs,
                    system_include_dirs=tuple(args.system_include_dir),
                    tool_inputs=tuple(args.tool_input),
                    defines=plan.defines,
                    sysroot=args.sysroot, freestanding=args.freestanding, require_syntax=True,
                )
                providers[key] = provider
            return providers[key], key

    def project(entry, plan, provider, key):
        _check_public_header(root, entry, provider)
        syntax_capture = None
        try:
            syntax_capture = provider.project_syntax(plan.source)
            projection = provider.project(syntax_capture.output, language="c11-ast-sexp")
            provenance = projection.provenance
            output = projection.output
            reason = None
        except ProjectionError as exc:
            if exc.code not in {"cephyr_failed", "cephyr_signaled", "timeout", "output_limit",
                                 "diagnostic_limit"}:
                raise
            reason = exc.code if exc.code.startswith("cephyr_") else _reason_code("cephyr_", exc.code)
            provenance = exc.provenance
            output = None
        # Keep relocatable evidence only, interning the invocation-common data.
        common = dict(provenance["identity"])
        projection_input = {name: common.pop(name) for name in
                            ("stdin_sha256", "language", "header", "stage", "origin")}
        common.pop("projection_sha256", None)
        profile_sha = digest(common)
        with provider_lock:
            if observed_profiles.setdefault(key, profile_sha) != profile_sha:
                raise GenerationError("Cephyr projection profile changed during generation")
            profiles.setdefault(profile_sha, common)
        if "exit_status" in provenance["invocation"]:
            projection_input["exit_status"] = provenance["invocation"]["exit_status"]
        if syntax_capture is not None:
            # C11Syntax bytes can include absolute diagnostic labels or source
            # spellings. Bind the raw C input and the normalized syntax facts
            # separately; never publish the raw AST digest as portable identity.
            del projection_input["stdin_sha256"]
            syntax_identity = syntax_capture.provenance["identity"]
            projection_input["syntax"] = {name: syntax_identity[name] for name in
                                          ("stdin_sha256", "language", "stage")}
        return output, syntax_capture, reason, projection_input, profile_sha

    def generate(entry):
        plan = inventory.plan(entry.key)
        provider, key = provider_for(plan)
        override = selected_overrides.get(entry.key)
        output, syntax_capture, reason, projection_input, profile_sha = project(entry, plan, provider, key)
        projection_sha = None
        if output is None:
            outcome = failed_module(entry, target, reason, override=override)
        else:
            projection_sha = _sha(output)
            try:
                interface = decode_interface(output, expected_target=args.target)
            except InterfaceError as exc:
                if exc.code in ("target", "version"):
                    raise
                outcome = failed_module(entry, target, _reason_code("interface_", exc.code),
                                        override=override)
            else:
                try:
                    syntax = declaration_syntax(syntax_capture.output)
                except InterfaceError as exc:
                    if exc.code != "limit":
                        raise
                    outcome = failed_module(entry, target, "syntax_limit", override=override)
                else:
                    projection_input["syntax"]["declarations_sha256"] = digest([
                        "on1x.ffi-cephyr-c11-syntax/v1",
                        [[row.name, row.declarations, row.has_body] for row in syntax],
                    ])
                    outcome = generate_module(entry, interface, target, override=override, syntax=syntax,
                                              owned_headers=plan.metadata["owned_headers"],
                                              reserved_prefixes=prefixes)
        row = {
            "key": entry.key, "module": entry.module, "header": entry.header_path,
            "file": entry.filename, "ffi_sha256": _sha(outcome.document),
            "projection_sha256": projection_sha, "projection": projection_input,
            "projection_profile_sha256": profile_sha,
            "override_sha256": _sha(raw_overrides[entry.filename]) if override else None,
            "plan": plan.metadata,
            **outcome.metadata,
        }
        record_bytes = len(json.dumps(row, ensure_ascii=True, separators=(",", ":")))
        with budget_lock:
            staged_bytes["files"] += len(outcome.document)
            staged_bytes["records"] += record_bytes
            if (staged_bytes["files"] > ffi_publish.MAX_MODULE_BYTES or
                    staged_bytes["records"] > ffi_publish.MAX_INDEX_BYTES):
                raise GenerationError("generation package byte budget exceeded")
        return entry.filename, outcome.document, row

    def validate_stage(stage):
        names, symbols = set(), set()
        inputs, evidence = {}, {}
        for document in sorted(stage.glob("*.ffi")):
            module = ffic.compile_files(parser, [document], target=args.target, canonical_files=True)
            if len(module["modules"]) != 1 or module["modules"][0]["version"] != 2:
                raise GenerationError(f"{document.name}: expected one v2 generated module")
            module_name = module["modules"][0]["module"]
            if module_name in names:
                raise GenerationError(f"duplicate generated module: {module_name}")
            names.add(module_name)
            inputs[document.name] = module["inputs"][0]["sha256"]
            for binding in (*module["bindings"], *module["discovery"]):
                if binding["symbol"] in symbols:
                    raise GenerationError(f'duplicate generated symbol: {binding["symbol"]}')
                symbols.add(binding["symbol"])
                if "c11_evidence" in binding:
                    evidence[(module_name, binding["symbol"])] = binding["c11_evidence"]
        ffic.verify_catalogue(stage / "index.json", inputs, args.target, evidence)

    def verify_inputs():
        inventory.verify_unchanged()
        for provider in providers.values():
            provider.verify_inputs()
        if raw_overrides != _override_inputs(override_dir, inventory):
            raise GenerationError("authored overrides changed during generation")
        for path, sha in snapshots.items():
            if _sha(path.read_bytes()) != sha:
                raise GenerationError(f"generator input changed during generation: {path.name}")

    with ffi_publish.transaction(output, args.target, check=args.check, full=args.all) as package:
        records = {}
        if not args.all and package.previous is not None:
            previous = package.previous
            records = {row["key"]: row for row in previous["modules"] if row["key"] != args.kernel}
            if records and (previous.get("inventory") != inventory.index_metadata or
                            previous.get("generation") != generation):
                raise GenerationError("shared inventory or generator inputs changed; run --all")
        generated = ffi_publish.bounded_map(generate, entries, args.jobs)
        if records:
            for key, prior in records.items():
                entry = inventory.by_key.get(key)
                if entry is None:
                    raise GenerationError("removed manifest module; run --all")
                raw = raw_overrides.get(entry.filename)
                if prior.get("override_sha256") != (_sha(raw) if raw is not None else None):
                    raise GenerationError(f"sibling override changed: {key}; run --all")
                plan = inventory.plan(key)
                provider, profile_key = provider_for(plan)
                # Reuse a sibling only for the same *observed* complete input
                # profile; a different planner profile requires one real probe.
                if profile_key not in observed_profiles:
                    project(entry, plan, provider, profile_key)
                else:
                    _check_public_header(root, entry, provider)
                if (digest(prior.get("plan")) != digest(plan.metadata) or
                        prior.get("projection_profile_sha256") !=
                        observed_profiles[profile_key]):
                    raise GenerationError(f"sibling generation inputs changed: {key}; run --all")
        for filename, document, record in generated:
            (package.stage / filename).write_bytes(document)
            records[record["key"]] = record
        modules = [records[key] for key in sorted(records)]
        unattempted = [entry.key for entry in inventory.entries if entry.key not in records]
        package.finish({
            "schema": INDEX_SCHEMA, "target": args.target,
            "generation": generation, "inventory": inventory.index_metadata,
            "projection_profiles": profiles,
            "modules": modules, "unattempted": unattempted, "counts": _counts(modules, unattempted),
        }, validate=validate_stage, verify=verify_inputs,
           expected_keys=(entry.key for entry in entries) if args.all else None)


def _absolute(value) -> Path:
    path = Path(value)
    if not path.is_absolute():
        raise argparse.ArgumentTypeError("expected an explicit absolute path")
    return path


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mulib-root", required=True, type=Path)
    parser.add_argument("--cephyr", required=True, type=_absolute)
    parser.add_argument("--target", required=True, choices=tuple(TARGETS))
    parser.add_argument("--libstone-revision", required=True, help="selected LibStone Git revision")
    parser.add_argument("--parser", required=True, type=_absolute,
                        help="trusted Python parser generated by genuine LLSynth")
    parser.add_argument("--scratch-root", required=True, type=_absolute)
    parser.add_argument("--system-include-dir", action="append", default=[], type=_absolute)
    parser.add_argument("--tool-input", action="append", required=True, type=_absolute,
                        help="repeat for actual compiler libraries and target resources")
    parser.add_argument("--sysroot", type=_absolute)
    parser.add_argument("--freestanding", action="store_true")
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--overrides", type=Path, help="target-specific authored override directory")
    scope = parser.add_mutually_exclusive_group(required=True)
    scope.add_argument("--all", action="store_true")
    scope.add_argument("--kernel", metavar="MANIFEST_KEY")
    parser.add_argument("--jobs", type=int, default=1, choices=range(1, 17))
    parser.add_argument("--check", action="store_true", help="compare without publishing")
    args = parser.parse_args(argv)
    from project_interface import ProjectionError

    try:
        _run(args)
    except (OSError, ValueError, ProjectionError) as exc:
        print(f"ffgen: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
