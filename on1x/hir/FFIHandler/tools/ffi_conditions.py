#!/usr/bin/env python3
"""Generate an On1x status classifier from C11Interface v1 and an authored contract."""

from __future__ import annotations

import argparse
from hashlib import sha256
import json
from pathlib import Path
import re
import sys

from cephyr_interface import MAX_BYTES, IntegerType, decode_interface


TARGET = "x86_64-linux-gnu"
C_INT = IntegerType("int", 3, 32, True, 4, 4)
C_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]{0,127}")
CASE_NAME = re.compile(r"[A-Z][A-Za-z0-9]{0,63}")
UNRECOGNIZED = "UnrecognizedStatus"
MAX_CONTRACT_BYTES = 16 * 1024
MAX_FAILURES = 16


def require(condition, message):
    if not condition:
        raise ValueError(message)


def unique_members(pairs):
    obj = dict(pairs)
    require(len(obj) == len(pairs), "duplicate member in status contract")
    return obj


def identifier(value, pattern, description):
    require(isinstance(value, str) and pattern.fullmatch(value), f"invalid {description}")
    return value


def generate(projection: bytes, contract: bytes) -> str:
    """Validate the description and the explicit mapping; does not admit a call."""
    require(len(projection) <= MAX_BYTES, "C11Interface byte limit exceeded")
    require(len(contract) <= MAX_CONTRACT_BYTES, "status contract byte limit exceeded")
    obj = json.loads(contract.decode("utf-8"), object_pairs_hook=unique_members)
    require(isinstance(obj, dict)
            and obj.keys() == {"version", "interface_sha256", "symbol", "enum", "success", "failures"},
            "expected the exact status contract v1 fields")
    require(type(obj["version"]) is int and obj["version"] == 1,
            "unsupported status contract version")
    digest = sha256(projection).hexdigest()
    require(obj["interface_sha256"] == digest, "status contract does not match C11Interface SHA-256")
    symbol = identifier(obj["symbol"], C_NAME, "C function name")
    enum = identifier(obj["enum"], C_NAME, "C enum tag name")
    success = identifier(obj["success"], C_NAME, "success enumerator")
    failures = obj["failures"]
    require(isinstance(failures, dict) and 1 <= len(failures) <= MAX_FAILURES,
            "expected 1 to 16 explicit failure mappings")

    interface = decode_interface(projection, expected_target=TARGET)
    fn = next((decl for decl in interface.functions if decl.name == symbol), None)
    require(fn is not None and fn.linkage == "external"
            and fn.definition in ("declaration", "defined") and not fn.specifiers
            and fn.calling_convention == "sysv"
            and fn.type.prototype and not fn.type.variadic and fn.type.result == C_INT,
            "status contract requires an external fixed SysV C int function without specifiers")
    tags = [tag for tag in interface.tags if tag.kind == "enum" and tag.name == enum]
    require(len(tags) == 1 and tags[0].complete, "expected one complete named status enum")
    values = {item.name: item.value for item in tags[0].enumerators}

    def code(name):
        identifier(name, C_NAME, "status enumerator")
        require(name in values and -(1 << 31) <= values[name] < (1 << 31),
                "status enumerator missing or not representable as C int")
        return values[name]

    ok = code(success)
    seen_codes, seen_cases, conditions = {ok}, {UNRECOGNIZED}, []
    for name, case in sorted(failures.items()):
        case = identifier(case, CASE_NAME, "On1x condition case")
        status = code(name)
        require(status not in seen_codes, "overlapping status values")
        require(case not in seen_cases, "duplicate or reserved condition case")
        seen_codes.add(status)
        seen_cases.add(case)
        conditions.append((status, case))
    conditions.sort()

    result = "Result<i64, ForeignCondition>"
    lines = [
        "# Generated by ffi_conditions.py; status mapping only, not a native import.",
        f"# C11Interface v1 SHA-256: {digest}; symbol: {symbol}",
        "from std.core.Pervasive import Result;",
        "",
        "enum ForeignCondition {",
        *(f"    {case}(i64)," for _, case in conditions),
        f"    {UNRECOGNIZED}(i64)",
        "}",
        "",
        f"fn signal_status(status: i64) -> {result} {{",
        f"    if status == {ok} {{ return variant<{result}>(Ok, status); }}",
        *(f"    if status == {status} {{ return variant<{result}>(Err,"
          f" variant<ForeignCondition>({case}, status)); }}"
          for status, case in conditions),
        f"    return variant<{result}>(Err, variant<ForeignCondition>({UNRECOGNIZED}, status));",
        "}",
        "",
    ]
    return "\n".join(lines)


def read_bounded(path: Path, limit: int) -> bytes:
    with path.open("rb") as source:
        return source.read(limit + 1)


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("projection", type=Path, help="original Cephyr --emit-interface=sexp output")
    cli.add_argument("contract", type=Path, help="explicit status contract v1 JSON")
    args = cli.parse_args()
    try:
        output = generate(read_bounded(args.projection, MAX_BYTES),
                          read_bounded(args.contract, MAX_CONTRACT_BYTES))
    except (ValueError, OSError, RecursionError) as exc:
        cli.exit(1, f"ffi_conditions: {exc}\n")
    sys.stdout.write(output)


if __name__ == "__main__":
    main()
