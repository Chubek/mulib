        assert rows['mulib_typed_add']['linkage']=='internal'
        wider=rows['mulib_typed_wider']
        fingerprint=wider['native_fingerprint']
        extension=f'''ffi 2; {TARGET}
            extend mulib.typed {{
                select c::mulib_typed_wider;
                fn c::mulib_typed_wider fingerprint "{fingerprint}" requires 0 <= 0;
                obligation native_retention_unknown;
            }}'''
        override=ffic.parse_overrides(parser_module,extension.encode(),w/'override.ffi')
        assert override.target==ffic.LEGACY_TARGET and override.module=='mulib.typed'
        assert override.selections==('mulib_typed_wider',)
        assert override.obligations==('native_retention_unknown',)
        assert override.overrides=={'mulib_typed_wider':{'fingerprint':fingerprint,'guards':[[0,0]]}}
