#include "on1x_container_shared.h"

#include <mulib-xatomics.h>
#include <mulib-xthreads.h>
#include <stdlib.h>
#include <string.h>

#ifndef ON1X_SHARED_MALLOC
#define ON1X_SHARED_MALLOC malloc
#endif
#ifndef ON1X_SHARED_FREE
#define ON1X_SHARED_FREE free
#endif
#ifndef ON1X_SHARED_THREAD_CREATE
#define ON1X_SHARED_THREAD_CREATE mulib_xthread_create
#endif
#ifndef ON1X_SHARED_MAX_PAYLOAD
#define ON1X_SHARED_MAX_PAYLOAD (64u * 1024u * 1024u)
#endif

typedef struct {
    bool atomic, cell, writer;
    size_t size;
    on1x_unique_destructor destroy;
    uint32_t readers;
    union {
        uint32_t local;
        mulib_xatomic_u32_t atomic;
    } refs;
} shared_block;

/* Unspecified representation bytes may be copied, but native workers only
 * interpret the verified uint8_t elements of one generated byte array.
 * The malloc tail has no declared type and max_align_t alignment, just like
 * an ordinary on1x_unique payload. */
static size_t payload_offset(void) {
    const size_t alignment = _Alignof(max_align_t);
    const size_t remainder = sizeof(shared_block) % alignment;
    return sizeof(shared_block) + (remainder ? alignment - remainder : 0);
}

static void *payload(shared_block *block) {
    return (unsigned char *)block + payload_offset();
}

/* Called only by a live strong owner. CAS prevents wrapping the count;
 * all atomic operations in the existing MuLIB kernel are seq_cst. */
static bool retain(shared_block *block) {
    if (!block->atomic) {
        if (!block->refs.local || block->refs.local == UINT32_MAX) return false;
        ++block->refs.local;
        return true;
    }
    uint32_t count = mulib_xatomic_u32_load(&block->refs.atomic);
    do {
        if (!count || count == UINT32_MAX) return false;
    } while (!mulib_xatomic_u32_compare_exchange(&block->refs.atomic, &count, count + 1));
    return true;
}

static void release(shared_block *block) {
    if (!block) return;
    const uint32_t previous = block->atomic
        ? mulib_xatomic_u32_fetch_sub(&block->refs.atomic, 1)
        : block->refs.local--;
    if (!previous) abort(); /* private ABI invariant, not stale-pointer validation */
    if (previous != 1) return;
    if (block->writer || block->readers) abort();
    if (block->destroy) block->destroy(payload(block));
    ON1X_SHARED_FREE(block);
}

static void drop_claim(void *slot) {
    release(*(shared_block **)slot);
}

static shared_block *get(on1x_unique *owner, bool atomic) {
    shared_block **slot = on1x_unique_borrow(owner, sizeof *slot, __FILE__, __LINE__, 1);
    if (!*slot || (*slot)->atomic != atomic) abort();
    return *slot;
}

static on1x_unique *new_claim(void *source, size_t size,
                              on1x_unique_destructor destroy, bool atomic, bool cell) {
    const size_t offset = payload_offset();
    if (!source || !size || size > ON1X_SHARED_MAX_PAYLOAD ||
        size > SIZE_MAX - offset || (atomic && destroy))
        return NULL;
    shared_block *block = ON1X_SHARED_MALLOC(offset + size);
    if (!block) return NULL;
    block->atomic = atomic;
    block->cell = cell;
    block->writer = false;
    block->readers = 0;
    block->size = size;
    block->destroy = destroy;
    if (atomic) mulib_xatomic_u32_store(&block->refs.atomic, 1);
    else block->refs.local = 1;

    /* Only clear the caller's rooted source after both allocations succeed. */
    shared_block *claim = block;
    on1x_unique *owner = on1x_unique_try_box(&claim, sizeof claim, drop_claim);
    if (!owner) {
        ON1X_SHARED_FREE(block);
        return NULL;
    }
    memcpy(payload(block), source, size);
    memset(source, 0, size);
    return owner;
}

on1x_unique *on1x_shared_v1_new(void *source, size_t size,
                               on1x_unique_destructor destroy, bool atomic) {
    return new_claim(source, size, destroy, atomic, false);
}

on1x_unique *on1x_shared_v1_clone(on1x_unique *owner, bool atomic) {
    shared_block *block = get(owner, atomic);
    if (!retain(block)) return NULL;
    shared_block *claim = block;
    on1x_unique *copy = on1x_unique_try_box(&claim, sizeof claim, drop_claim);
    if (!copy) release(block);
    return copy;
}

void on1x_shared_v1_read(on1x_unique *owner, bool atomic, void *out, size_t size) {
    shared_block *block = get(owner, atomic);
    if (!out || size != block->size) abort();
    memcpy(out, payload(block), size);
}

static void drop_reader(void *slot) {
    shared_block *block = *(shared_block **)slot;
    if (!block || !block->readers || block->writer) abort();
    --block->readers;
    release(block);
}

static void drop_writer(void *slot) {
    shared_block *block = *(shared_block **)slot;
    if (!block || block->readers || !block->writer) abort();
    block->writer = false;
    release(block);
}

on1x_unique *on1x_shared_v1_cell_new(void *source, size_t size,
                                    on1x_unique_destructor destroy) {
    return new_claim(source, size, destroy, false, true);
}

int on1x_shared_v1_cell_try_borrow(on1x_unique *owner, bool write, on1x_unique **out) {
    shared_block *block = get(owner, false);
    if (!block->cell || !out) abort();
    if (block->writer || (write && block->readers)) return 0;
    if (!retain(block)) return -1;

    shared_block *claim = block;
    on1x_unique *guard = on1x_unique_try_box(&claim, sizeof claim,
                                            write ? drop_writer : drop_reader);
    if (!guard) {
        release(block);
        return -1;
    }
    if (write) block->writer = true;
    else ++block->readers; /* cannot wrap: each reader owns a strong count */
    *out = guard;
    return 1;
}

void on1x_shared_v1_cell_replace(on1x_unique *writer, void *source, void *out,
                                 size_t size) {
    shared_block *block = get(writer, false);
    if (!block->cell || !block->writer || !source || !out || size != block->size)
        abort();
    memcpy(out, payload(block), size);
    memcpy(payload(block), source, size);
    memset(source, 0, size);
}

typedef struct {
    shared_block *block;
    size_t begin, end, count;
    uint8_t byte;
} count_job;

static int count_bytes(void *context) {
    count_job *job = context;
    shared_block *block = job->block; /* take the published native claim */
    const unsigned char *bytes = payload(block);
    size_t count = 0;
    for (size_t i = job->begin; i < job->end; ++i)
        count += bytes[i] == job->byte;
    job->count = count;
    release(block);
    return 0;
}

int64_t on1x_shared_v1_parallel_count(on1x_unique *owner, size_t length,
                                      uint8_t byte, int64_t workers) {
    if (workers < 1 || workers > ON1X_SHARED_ARC_MAX_WORKERS) return -1;
    shared_block *block = get(owner, true);
    if (!length || length > block->size || length > 256) return -1;
    const size_t n = (size_t)workers < length ? (size_t)workers : length;
    count_job jobs[ON1X_SHARED_ARC_MAX_WORKERS];
    mulib_xthread_t threads[ON1X_SHARED_ARC_MAX_WORKERS];
    size_t started = 0;
    for (; started < n; ++started) {
        if (!retain(block)) break;
        jobs[started] = (count_job){
            block, length * started / n, length * (started + 1) / n, 0, byte
        };
        if (ON1X_SHARED_THREAD_CREATE(&threads[started], count_bytes,
                                      &jobs[started]) != MULIB_XTHREAD_OK) {
            release(block);
            break;
        }
    }
    int64_t result = 0;
    for (size_t i = 0; i < started; ++i) {
        /* A join failure here would violate the native thread contract.
         * Never return while a worker could still own our stack storage. */
        if (mulib_xthread_join(threads[i], NULL) != MULIB_XTHREAD_OK) abort();
        result += (int64_t)jobs[i].count;
    }
    return started == n ? result : -1;
}
